#!/usr/bin/env python3
"""Write the probe cases of this review into an OUTPUT directory (outside the
tree).  Every case runs on the installation catalogue (no seal), so it reads
exactly the records data/standards/ ships.

Usage: gen_cases.py <repo_root> <out_dir>

Cases written:
  ss_pitzer/            pitzerActivity op (the single-salt Pitzer kernel), per salt, per m, per T
  hmw/                  speciate op, activityModel pitzerHMW, restricted network
  davies/               speciate op, activityModel davies, restricted network
  pkg_<model>_<salt>/   electrolyteActivity op through a thermoPhysPropDict
                        `formulation electrolyteGammaPhi; activityModel { model Pitzer|eNRTL; }`
                        -- the route every process unit takes
  ms_enrtl/             enrtlMultiSalt op (NaCl + KCl, 1-1 only by the op's refusal)
"""
import os
import sys

SALTS = {   # name: (cation, anion, zc, |za|, m_max for the 25 C grid)
    "NaCl":   ("Na", "Cl", 1, 1, 6.0),
    "KCl":    ("K", "Cl", 1, 1, 4.5),
    "CaCl2":  ("Ca", "Cl", 2, 1, 6.0),
    "Na2SO4": ("Na", "SO4", 1, 2, 1.75),
    "MgSO4":  ("Mg", "SO4", 2, 2, 2.5),
}
GRID = [0.01, 0.02, 0.05, 0.1, 0.2, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 4.0, 4.5, 5.0, 6.0]
# NaCl temperatures: Archer's printed table temperatures (273/298/323/373 K, as
# the shipped archer01 case uses them) plus 60 C, model-only.
TEMPS_NACL = [298.15, 273.0, 298.0, 323.0, 333.15, 373.0]
# The MEASURED (critically evaluated) tables the repository already carries.
DATASETS = {   # salt: path relative to the repo root
    "NaCl":   "data/curation/electrolytes/Na-Cl/constant/experiments/Na-Cl.dat",
    "KCl":    "data/curation/electrolytes/K-Cl/constant/experiments/K-Cl.dat",
    "CaCl2":  "data/curation/electrolytes/Ca-Cl/constant/experiments/Ca-Cl.dat",
    "Na2SO4": "data/curation/electrolytes/Na-SO4/constant/experiments/Na-SO4.dat",
}
ARCHER = "tutorials/props/electrolyte/archer01_nacl_cold_to_hot/constant/experiments/archer92_tables9_10.dat"


def _strip(txt):
    import re
    txt = re.sub(r"/\*.*?\*/", "", txt, flags=re.S)
    return re.sub(r"//[^\n]*", "", txt)


def read_table(repo, salt):
    """[(m, gamma, phi)] from a curation dataset (columns m gamma phi)."""
    import re
    if salt not in DATASETS:
        return []
    txt = _strip(open(f"{repo}/{DATASETS[salt]}", encoding="utf-8").read())
    body = re.search(r"\bdata\s*\((.*?)\)\s*;", txt, flags=re.S).group(1)
    nums = [float(x) for x in body.split()]
    return [tuple(nums[i:i + 3]) for i in range(0, len(nums), 3)]


def read_archer(repo):
    """{T: [(m, gamma, phi)]} from Archer (1992) Tables 9/10 as shipped."""
    import re
    txt = _strip(open(f"{repo}/{ARCHER}", encoding="utf-8").read())
    out = {}
    for T, body in re.findall(r"nacl(\d+)\s*\((.*?)\)\s*;", txt, flags=re.S):
        rows = re.findall(r"m\s+([-0-9.eE]+);\s*gamma\s+([-0-9.eE]+);\s*phi\s+([-0-9.eE]+);", body)
        out[float(T)] = [tuple(map(float, r)) for r in rows]
    return out

HEADER = "/* review probe -- generated by gen_cases.py */\n"


def grid(mmax):
    return [m for m in GRID if m <= mmax + 1e-12]


def nu(zc, za):
    from math import gcd
    g = gcd(zc, za)
    return za // g, zc // g


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEADER + text)


def control(desc):
    return ("application  choupoProps;\n"
            f"description  \"{desc}\";\nverbosity    1;\n")


WATER_ONLY = """recordType    thermophysicalPropertySystem;
schemaVersion 2;
components ( water );
equilibrium
{
    formulation gammaPhi;
    liquid { activityModel ideal; standardState pureLiquid; }
    vapour { fugacityModel idealGas; }
}
"""


def aqueous_surface(model):
    return f"""recordType    thermophysicalPropertySystem;
schemaVersion 2;
components ( water );
aqueousProperties
{{
    activityCoefficients {{ model {model}; referenceBasis aqueousMolality; }}
}}
"""


REPO = "."


def points():
    """(salt, T, m) evaluation points shared by every model: the fixed grid,
    plus every molality of every measured table (so models are evaluated AT
    the measured points, never interpolated)."""
    pts = set()
    for s, (_, _, _, _, mmax) in SALTS.items():
        ms = set(grid(mmax)) | {r[0] for r in read_table(REPO, s)}
        for m in ms:
            pts.add((s, 298.15, m))
    # every salt hot (100 C), model-vs-model only (no hot table in the tree
    # except NaCl's Archer row): what each family does off 25 C.
    for s, (_, _, _, _, mmax) in SALTS.items():
        for m in (0.5, 1.0, min(3.0, mmax)):
            pts.add((s, 373.15, m))
    arch = read_archer(REPO)
    for T in TEMPS_NACL[1:]:
        ms = set(grid(6.0)) | {r[0] for r in arch.get(T, [])}
        for m in ms:
            pts.add(("NaCl", T, m))
    return sorted(pts)


def tag(s, T, m):
    return f"{s}_T{T:.2f}_m{m:g}"


def gen_ss(out):
    ops = []
    for s, T, m in points():
        c, a, _, _, _ = SALTS[s]
        ops.append(f"""    {{ name {tag(s,T,m).replace('.','p')}; type pitzerActivity; cation {c}; anion {a};
      temperature {T}; molality {{ from {m}; to {m}; n 2; }}
      output {{ file {tag(s,T,m)}.csv; }} }}""")
    write(f"{out}/ss_pitzer/system/controlDict", control("single-salt Pitzer kernel probe"))
    write(f"{out}/ss_pitzer/system/propsDict", "operations\n(\n" + "\n".join(ops) + "\n);\n")
    write(f"{out}/ss_pitzer/constant/thermoPhysPropDict", WATER_ONLY)


def gen_speciate(out, model, dirname, model_word):
    ops = []
    for s, T, m in points():
        c, a, zc, za, _ = SALTS[s]
        nc, na = nu(zc, za)
        ops.append(f"""    {{ name {tag(s,T,m).replace('.','p')}; type speciate; activityModel {model};
      temperature {T}; analyticalTotals {{ {c} {nc*m:.10g} mol/kg; {a} {na*m:.10g} mol/kg; }}
      pH 7.0; networkScope restricted; network ( water-dissociation );
      reason "review probe: a single fully dissociated salt, no ion pairs, the same state the single-salt kernels see";
      diagMeanIonic ( {{ cation {c}; anion {a}; }} );
      output {{ file {tag(s,T,m)}.csv; }} }}""")
    write(f"{out}/{dirname}/system/controlDict", control(f"{model} speciation probe"))
    write(f"{out}/{dirname}/system/propsDict", "operations\n(\n" + "\n".join(ops) + "\n);\n")
    write(f"{out}/{dirname}/constant/thermoPhysPropDict", aqueous_surface(model_word))


def gen_davies_full(out):
    """Davies WITH the catalogue's full ion-association network (no
    restriction): the way Davies is meant to be used (ion pairs carry the
    specific interaction).  25 C, every point up to I ~ 1.5."""
    ops = []
    for s, T, m in points():
        c, a, zc, za, _ = SALTS[s]
        nc, na = nu(zc, za)
        I = 0.5 * (nc * zc * zc + na * za * za) * m
        if T != 298.15 or I > 1.5 + 1e-9:
            continue
        ops.append(f"""    {{ name {tag(s,T,m).replace('.','p')}; type speciate; activityModel davies;
      temperature {T}; analyticalTotals {{ {c} {nc*m:.10g} mol/kg; {a} {na*m:.10g} mol/kg; }}
      pH 7.0; output {{ file {tag(s,T,m)}.csv; }} }}""")
    write(f"{out}/davies_full/system/controlDict", control("Davies + full ion-association probe"))
    write(f"{out}/davies_full/system/propsDict", "operations\n(\n" + "\n".join(ops) + "\n);\n")
    write(f"{out}/davies_full/constant/thermoPhysPropDict", aqueous_surface("Davies"))


def gen_pkg(out, model):
    for s, (c, a, zc, za, mmax) in SALTS.items():
        d = f"{out}/pkg_{model}_{s}"
        ops = []
        for (s2, T, m) in points():
            if s2 != s:
                continue
            ops.append(f"""    {{ name {tag(s,T,m).replace('.','p')}; type electrolyteActivity; temperature {T};
      molality {{ from {m}; to {m}; n 2; }} output {{ file {tag(s,T,m)}.csv; }} }}""")
        write(f"{d}/system/controlDict", control(f"package {model} {s} probe"))
        write(f"{d}/system/propsDict", "operations\n(\n" + "\n".join(ops) + "\n);\n")
        write(f"{d}/constant/thermoPhysPropDict", f"""recordType    thermophysicalPropertySystem;
schemaVersion 2;
components ( water {s} );
equilibrium
{{
    formulation electrolyteGammaPhi;
    aqueous {{ activityModel {{ model {model}; }} compositionBasis molality; }}
    vapour  {{ fugacityModel idealGas; }}
}}
caloric
{{
    energyBasis elementsDatum;
    aqueous {{ enthalpyRoute ionicReferencePlusExcess; }}
    vapour  {{ enthalpyRoute idealGasCp; }}
}}
""")


def gen_ms(out):
    ops = []
    for m in grid(4.5):
        ops.append(f"""    {{ name ms_m{str(m).replace('.','p')}; type enrtlMultiSalt;
      salts ( {{ cation Na; anion Cl; }} {{ cation K; anion Cl; }} );
      totalMolality {m}; sweepPoints 3; tauEE 0.0; formulation published;
      output {{ file ms_m{m:g}.csv; }} }}""")
    write(f"{out}/ms_enrtl/system/controlDict", control("multi-salt eNRTL reduction probe"))
    write(f"{out}/ms_enrtl/system/propsDict", "operations\n(\n" + "\n".join(ops) + "\n);\n")
    write(f"{out}/ms_enrtl/constant/thermoPhysPropDict", WATER_ONLY)


def main():
    global REPO
    repo, out = sys.argv[1], sys.argv[2]
    REPO = repo
    gen_ss(out)
    gen_speciate(out, "pitzerHMW", "hmw", "PitzerHMW")
    gen_speciate(out, "davies", "davies", "Davies")
    gen_davies_full(out)
    gen_pkg(out, "Pitzer")
    gen_pkg(out, "eNRTL")
    gen_ms(out)


if __name__ == "__main__":
    main()
