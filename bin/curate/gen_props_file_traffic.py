#!/usr/bin/env python3
"""Generate gui/schemas/propsFileTraffic.json from the engine's table.
    bin/curate/gen_props_file_traffic.py            (writes the file)
    bin/curate/gen_props_file_traffic.py --check    (exit 1 when it is stale)

WHY (DEV.md 4c C172 slice 3; docs/design/one-app-two-homes.md).  What each
properties operation type READS and WRITES has ONE home in the engine, the
file-traffic table in src/propertyOps/PropsPlan.cpp, and the engine publishes
it (`choupoProps --file-traffic`).  The GUI needs it in a browser that has
not loaded the engine yet: the Workflow's inspector shows what a step reads
and writes before any run, the calculation map draws the records an op
writes, and the worker reads the case's records back after a run.  Until
slice 3 the GUI kept its own hand-written copy of the writes in each op
schema's `x-choupo.writes`, held equal to the table by a gate; that copy is
gone, and this file is GENERATED from the engine instead -- derived, never
transcribed.  bin/curate/check_props_order.py arm (c) refuses a stale one.

The JSON is the table as the engine prints it, nothing added: one entry per
registered type, its `reads` and `writes` as {key, kind, default} in the
engine's order (kind: file | record | proposal | membraneName; default: the
value the engine takes when the key is absent, "" none).  A type the table
does not carry is listed under `untabled`.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROPS = ROOT / "choupoProps"
OUT = ROOT / "gui" / "schemas" / "propsFileTraffic.json"

HEADER = ("GENERATED by bin/curate/gen_props_file_traffic.py from "
          "`choupoProps --file-traffic` (the one home: the file-traffic table in "
          "src/propertyOps/PropsPlan.cpp).  Do not edit; regenerate.")


def engine_lines():
    env = dict(os.environ, CHOUPO_HOME=str(ROOT))
    r = subprocess.run([str(PROPS), "--file-traffic"], capture_output=True, text=True,
                       env=env, timeout=120)
    if r.returncode != 0:
        raise RuntimeError(f"choupoProps --file-traffic exited {r.returncode}:\n"
                           f"{(r.stdout + r.stderr)[-2000:]}")
    return r.stdout.splitlines()


def build(lines):
    """The JSON object for the engine's printed table (one builder: the gate
    calls it too, so the two cannot read the table two ways)."""
    types, untabled = {}, []
    for line in lines:
        f = line.split("\t")
        if len(f) == 2 and f[1] == "UNTABLED":
            untabled.append(f[0])
            continue
        if len(f) == 2 and f[1] == "none":
            types.setdefault(f[0], {"reads": [], "writes": []})
            continue
        if len(f) >= 4 and f[1] in ("read", "write"):
            row = types.setdefault(f[0], {"reads": [], "writes": []})
            row["reads" if f[1] == "read" else "writes"].append(
                {"key": f[2], "kind": f[3], "default": f[4] if len(f) > 4 else ""})
    return {"comment": HEADER,
            "types": {t: types[t] for t in sorted(types)},
            "untabled": sorted(untabled)}


def render(obj):
    return json.dumps(obj, indent=1, ensure_ascii=False) + "\n"


def main():
    if not PROPS.exists():
        print(f"gen_props_file_traffic: REFUSED -- {PROPS} not built (make all)")
        return 1
    text = render(build(engine_lines()))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"gen_props_file_traffic: STALE -- {OUT.relative_to(ROOT)} is not the "
                  f"engine's table; run bin/curate/gen_props_file_traffic.py")
            return 1
        print(f"gen_props_file_traffic: OK -- {OUT.relative_to(ROOT)} is the engine's table")
        return 0
    OUT.write_text(text)
    print(f"gen_props_file_traffic: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
