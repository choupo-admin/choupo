"""Gate: every sized item has ONE unique plant tag, the equipment list is the
recount of design/, and the tag reads the same on every surface.

    bin/curate/check_equipment_list.py

WHY THIS EXISTS.  Slice S1 of docs/design/the-plant-document-set.md gave every
sized item a plant tag (`P-101A`, Turton's `XX-YZZ A/B` form, generated by ONE
rule in src/postProcessing/sizing/EquipmentTag.cpp, a `tag <word>;` on the
postDict entry winning) and published the equipment list
(`reports/equipment/equipmentList.csv`, the result JSON's `equipmentList`
block, a printable GUI sheet).  A tag that differs between the sheet and the
cost table is worse than no tag: it is the same item with two names.

WHAT THIS CHECKS
  (a) THE LETTER TABLE COVERS THE KINDS.  Every equipment kind a sizer
      assigns (`equipmentType = "..."`, the registered `type_` of the sizers
      that use it, the clean-utilities `finishItem` kinds) has letters in the
      table of EquipmentTag.cpp; an unlisted kind would be tagged `X`.
  (b) PER WITNESS CASE (donepezil01_tablets, swro01_campoDalias,
      ChemicalPlantTutorial), run in a scratch copy:
      * EXACTLY ONE UNIQUE TAG per item: the item count of the result JSON
        `equipment`, of the `design/` sheets (recounted from disk), of the
        JSON `equipmentList` and of `equipmentList.csv` are the SAME number,
        every item has a non-empty tag, no tag is shared;
      * THE TAG IS THE SAME EVERYWHERE: sheet `tag`, JSON `tagNo`, list row,
        list CSV row, and (ChemicalPlantTutorial, which declares the `design`
        and `economics` reports) `sizing.csv` and `costs.csv`;
      * THE LIST IS THE RECOUNT OF design/: the list's purchased / bare-module
        costs equal the item's own `cost` block and the sheets' `cost {}`;
      * the generated tags follow the rule's shape, the N items of a parallel
        family share one base and take A..N (swro01: six trains), and a sector
        of a sectored plant has ONE sector number, distinct from the others.
  (c) A DECLARED TAG WINS AND IS ANNOUNCED: a scratch copy of the tablet plant
      declaring `tag V-900;` on an entry shows V-900 on its sheet and a
      `[tag]` line in the run.
  (d) A DECLARED DUPLICATE REFUSES BY NAME: two entries declaring the same
      tag fail the sizing, naming both items and the tag.

WHAT THIS DOES NOT CHECK, said plainly:
  * WHETHER A LETTER IS THE RIGHT ONE for a kind: the table is a convention
    of ours, documented in docs/ai/packs/design-cost.md, not a standard.
  * The GUI page (tested by gui/tests/equipmentListSheet.test.ts, run by
    `bin/runTests --gui`).
  * Sector numbering against the flowsheet's declared order (only that each
    sector has one distinct number): the order is the engine's own topology.

SABOTAGE, BY HAND (recorded 2026-11-03; each restored with `cp` and the
engine rebuilt with one idempotent `make all`):
  S1  EquipmentTag.cpp: the duplicate refusal `throw` commented out.  Arm (d)
      goes red (the two declared tags run to exit 0 and two items share one),
      and arm (b) of swro01 is unaffected.  Result: CAUGHT by (d).
  S2  EquipmentListWriter.cpp: the `tag` of the CSV row written from `r.item`.
      Arm (b) goes red on the CSV-versus-sheet comparison.  CAUGHT.
"""
import csv
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

TABLET = "tutorials/batch/plant/donepezil01_tablets"
SWRO = "tutorials/plant/swro01_campoDalias"
SECTORED = "tutorials/plant/ChemicalPlantTutorial"


def run(case_dir: Path):
    p = subprocess.run([str(ROOT / "choupoSolve"), str(case_dir)],
                       capture_output=True, text=True)
    return p.returncode, p.stdout, p.stderr


def stage(rel: str, edit=None):
    tmp = Path(tempfile.mkdtemp(prefix="equipment_list_"))
    dst = tmp / Path(rel).name
    shutil.copytree(ROOT / rel, dst, ignore=shutil.ignore_patterns(
        "design", "reports", "converged", "postProcessing", "log.*"))
    if edit:
        edit(dst)
    return dst


def result_json(out: str):
    m = re.search(r"<<<Choupo:result-begin>>>\s*(.*?)\s*<<<Choupo:result-end>>>",
                  out, re.S)
    return json.loads(m.group(1)) if m else None


def csv_rows(path: Path):
    if not path.is_file():
        return None
    with path.open(newline="", errors="replace") as fh:
        return list(csv.DictReader(fh))


def find_csv(case: Path, report: str, name: str):
    for p in (case / "reports" / report / name,
              case / "postProcessing" / report / "0" / name):
        if p.is_file():
            return p
    return None


def sheets(case: Path):
    """{(unit, item-word): sheet fields} recounted from design/ on disk."""
    out = {}
    d = case / "design"
    if not d.is_dir():
        return out
    for f in sorted(d.rglob("*")):
        if not f.is_file():
            continue
        t = f.read_text(errors="replace")
        if "recordType  designSheet" not in t:
            continue
        t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
        t = re.sub(r"//[^\n]*", "", t)
        g = lambda k: (re.search(r"^%s\s+\"?([^\";\n]+)\"?\s*;" % k, t, re.M) or [None, ""])[1].strip()
        cm = re.search(r"^cost\s*\n\{(.*?)^\}", t, re.S | re.M)
        cost = {}
        if cm:
            for k in ("purchased", "bareModule", "totalModule"):
                m = re.search(r"^\s*%s\s+([-0-9.eE+]+)\s*;" % k, cm.group(1), re.M)
                if m:
                    cost[k] = float(m.group(1))
        out[f.relative_to(d).as_posix()] = {
            "unit": g("unit"), "item": g("item"), "tag": g("tag"), "cost": cost}
    return out


def close(a, b):
    return abs(a - b) <= 1e-6 * max(1.0, abs(a), abs(b))


def check_table(problems):
    cpp = (ROOT / "src/postProcessing/sizing/EquipmentTag.cpp").read_text()
    keys = set(re.findall(r'\{\s*"([A-Za-z:]+)"\s*,\s*"[A-Z]+"\s*\}', cpp))
    kinds = set()
    sizing = ROOT / "src/postProcessing"
    for f in list(sizing.glob("sizing/*.cpp")) + [sizing / "CleanUtilitiesPass.cpp"]:
        t = f.read_text(errors="replace")
        kinds |= set(re.findall(r'equipmentType\s*=\s*"([A-Za-z]+)"', t))
        kinds |= set(re.findall(
            r'finishItem\([^,]+,\s*"[^"]*",\s*(?:"[^"]*"|\w+),\s*"([A-Za-z]+)"', t))
        if re.search(r"equipmentType\s*=\s*type_", t):
            h = f.with_suffix(".H")
            if h.is_file():
                kinds |= set(re.findall(
                    r'type_\s*=\s*"([A-Za-z]+)"', h.read_text(errors="replace")))
    kinds.discard("ratedMachine")
    for k in sorted(kinds):
        if k not in keys:
            problems.append(f"(a) the equipment kind '{k}' has no letters in the"
                            " table of EquipmentTag.cpp (it would be tagged X)")
    for k in ("ratedMachine:volumeRate", "ratedMachine:tabletPress",
              "ratedMachine:packagingLine", "ratedMachine:batchVolume",
              "ratedMachine:massRate"):
        if k not in keys:
            problems.append(f"(a) the rated-machine kind '{k}' has no letters")
    return len(kinds)


def check_case(rel, problems, want_csvs=False):
    case = stage(rel)
    rc, out, err = run(case)
    if rc != 0:
        problems.append(f"{rel}: does not run to exit 0")
        return None
    js = result_json(out)
    if js is None or not js.get("equipment"):
        problems.append(f"{rel}: the run emits no `equipment` block")
        return None
    items = [i for i in js["equipment"] if i.get("type") != "declaredQuote"]
    sh = sheets(case)
    lst = (js.get("equipmentList") or {}).get("rows", [])
    lcsv = csv_rows(case / "reports/equipment/equipmentList.csv")
    n = len(items)
    if not (len(sh) == n == len(lst) == (len(lcsv) if lcsv is not None else -1)):
        problems.append(f"{rel}: the counts disagree -- JSON equipment {n}, design/"
                        f" sheets {len(sh)}, JSON list {len(lst)}, list CSV "
                        f"{None if lcsv is None else len(lcsv)}")
        return None
    tags = [i.get("tagNo", "") for i in items]
    if any(not t for t in tags):
        problems.append(f"{rel}: an item has no tag")
    if len(set(tags)) != len(tags):
        problems.append(f"{rel}: tags are not unique: "
                        f"{sorted(t for t in set(tags) if tags.count(t) > 1)}")
    sheet_by_tag = {s["tag"]: s for s in sh.values()}
    list_by_item = {r["itemId"]: r for r in lst}
    csv_by_item = {r["item"]: r for r in lcsv}
    for i in items:
        it, t = i["item"], i.get("tagNo", "")
        s = [x for x in sh.values()
             if x["unit"] == i["unit"] and (x["item"] or "") == (i.get("tag") or "")]
        if len(s) != 1 or s[0]["tag"] != t:
            problems.append(f"{rel}: item {it}: JSON tag {t!r}, sheet "
                            f"{[x['tag'] for x in s]}")
        if list_by_item.get(it, {}).get("tag") != t:
            problems.append(f"{rel}: item {it}: list JSON tag differs from {t!r}")
        if csv_by_item.get(it, {}).get("tag") != t:
            problems.append(f"{rel}: item {it}: list CSV tag differs from {t!r}")
        c = i.get("cost")
        lr = list_by_item.get(it, {})
        if c and lr.get("purchased") is not None:
            if not (close(c["purchased"], lr["purchased"])
                    and close(c["bareModule"], lr["bareModule"])):
                problems.append(f"{rel}: item {it}: the list's costs differ from the item's")
            sc = sheet_by_tag.get(t, {}).get("cost", {})
            if sc and not close(sc.get("purchased", c["purchased"]), c["purchased"]):
                problems.append(f"{rel}: item {it}: the sheet's cost differs from the item's")
        elif c and lr.get("purchased") is None:
            problems.append(f"{rel}: item {it} is costed but its list row has no cost")
    if want_csvs:
        sz = csv_rows(find_csv(case, "design", "sizing.csv") or case / "none")
        co = csv_rows(find_csv(case, "economics", "costs.csv") or case / "none")
        if sz is None or co is None or "tag" not in (sz[0] if sz else {}):
            problems.append(f"{rel}: sizing.csv / costs.csv carry no `tag` column")
        else:
            for col, rows in (("sizing.csv", sz), ("costs.csv", co)):
                got = {r["tag"] for r in rows if r.get("tag")}
                if not got <= set(tags):
                    problems.append(f"{rel}: {col} names tags no item has: "
                                    f"{sorted(got - set(tags))}")
                if col == "sizing.csv" and got != set(tags):
                    problems.append(f"{rel}: sizing.csv misses tags {sorted(set(tags) - got)}")
    return case, items, js


def main() -> int:
    problems = []
    nkinds = check_table(problems)

    # ---- the tablet plant: a flat case, machines and a vessel
    r = check_case(TABLET, problems)
    # ---- the desalination plant: six trains -> the letters A..F
    s = check_case(SWRO, problems)
    ntrain = 0
    if s:
        _, items, _ = s
        fam = {}
        for i in items:
            if i["unit"] == "HPpump":
                fam[i["tagNo"]] = i
        letters = sorted(t[-1] for t in fam)
        bases = {t[:-1] for t in fam}
        if letters != list("ABCDEF") or len(bases) != 1:
            problems.append(f"{SWRO}: the six HPpump trains should share one base and"
                            f" take A..F; got {sorted(fam)}")
        ntrain = len(fam)
        if not all(re.fullmatch(r"[A-Z]+-1\d\d(?:[A-Z]|[A-Z]/[A-Z]|[A-Z]-[A-Z])?", i["tagNo"])
                   for i in items):
            problems.append(f"{SWRO}: a generated tag departs from the XX-1ZZ shape")
    # ---- the sectored flagship: sector numbers, and the CSV columns
    c = check_case(SECTORED, problems, want_csvs=True)
    if c:
        _, items, _ = c
        ys = {}
        for i in items:
            m = re.fullmatch(r"[A-Z]+-(\d)\d\d.*", i["tagNo"])
            if not m:
                problems.append(f"{SECTORED}: tag {i['tagNo']} departs from XX-YZZ")
                continue
            ys.setdefault(i.get("sector", ""), set()).add(m.group(1))
        if any(len(v) != 1 for v in ys.values()):
            problems.append(f"{SECTORED}: a sector carries several sector numbers: {ys}")
        named = [next(iter(v)) for k, v in ys.items() if k]
        if len(set(named)) != len(named):
            problems.append(f"{SECTORED}: two sectors share a sector number: {ys}")

    # ---- (c) a declared tag wins, announced
    def declare(dst):
        pd = dst / "system" / "postDict"
        t = pd.read_text()
        t2 = re.sub(r"(unitName\s+binderPrep;)", r"\1 tag V-900;", t, count=1)
        if t2 == t:
            raise SystemExit("check_equipment_list: cannot place the declared tag"
                             " in the tablet postDict -- fix the probe")
        pd.write_text(t2)
    d = stage(TABLET, declare)
    rc, out, err = run(d)
    sh = sheets(d)
    if rc != 0 or not any(x["tag"] == "V-900" for x in sh.values()) \
            or "[tag]" not in out:
        problems.append("(c) a declared `tag V-900;` did not win and announce "
                        f"(exit {rc})")

    # ---- (d) a declared duplicate refuses by name
    def dup(dst):
        pd = dst / "system" / "postDict"
        t = pd.read_text()
        t = re.sub(r"(unitName\s+binderPrep;)", r"\1 tag V-901;", t, count=1)
        t = re.sub(r"(unitName\s+coatingSuspensionPrep;)", r"\1 tag V-901;", t, count=1)
        pd.write_text(t)
    d = stage(TABLET, dup)
    rc, out, err = run(d)
    msg = out + err
    if not ("would both be tagged" in msg and "V-901" in msg):
        problems.append("(d) two items declaring the same tag were not refused by"
                        " name (no 'would both be tagged ... V-901')")

    if problems:
        print("check_equipment_list: FAILED")
        for p in problems:
            print("  " + p)
        return 1
    print(f"check_equipment_list: OK -- every sized item of the tablet plant, the"
          f" six-train desalination plant and the sectored flagship has exactly"
          f" one unique tag, the same in its design sheet, the result JSON, the"
          f" equipment list (JSON and CSV) and, on the flagship, sizing.csv and"
          f" costs.csv; the list recounts design/ and the items' costs; the"
          f" {ntrain} HPpump trains take one base and the letters A..F; the"
          f" letter table covers {nkinds} sizer kinds; a declared tag wins and"
          f" is announced, a declared duplicate refuses by name.  NOT CHECKED:"
          f" whether a letter is the right one (a convention), the GUI page.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
