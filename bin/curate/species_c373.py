#!/usr/bin/env python3
"""Make the aqueous-species and ionisation records of C373 from the batch's evidence tables.

    bin/curate/species_c373.py write     (re)write every record the tables say `build`
    bin/curate/species_c373.py check     compare the tables with the tree; exit 1 on any difference
    bin/curate/species_c373.py list      families, species and step counts
    bin/curate/species_c373.py scale     the one-scale table (formation-enthalpy differences against the printed step enthalpies)
    bin/curate/species_c373.py fcompare  printed formation readings against the catalogue's values for the same species (formation_compare.tsv)
    bin/curate/species_c373.py compare   records already in the catalogue against Goldberg's selected values (chem `compare` families)

SOURCE OF TRUTH: data/curation/batches/species_c373/*.tsv, one reading per row:
  sources.tsv    key -> full citation and the scale the source states
  families.tsv   one row per family: navigation root, who writes its chemistry, the neutral component whose
                 crystal datum and heat of solution give the neutral aqueous enthalpy, the tolerance of the
                 one-scale check
  species.tsv    key, formula, charge, family, position in the ladder (0 = the most protonated form, the
                 speciation master), build (new) | update (exists, rewritten; navigation already names it) | existing (not touched)
  steps.tsv      one ionisation step per row: pK, dH, dCp as PRINTED, the source, the table and page, and
                 whether the number was read from a page image (a later human check)
  formation.tsv  hfAq / sAq of a species, the arithmetic that gives it from printed numbers, the tables and
                 pages, whether read from an image

What is written: species/<key>.dat for every species with status `build`; chemistry/<key>-formation.dat
(forward records from the master, plus the inverse written from the fully dissociated form) for every family
whose `chem` is `build`; the generated block of metadata/aqueous-navigation.dat.  A family whose chem is
`existing` has its records written by hand in an earlier campaign (C372): `check` holds them to steps.tsv.

Units: tables in kJ/mol and J/mol/K as printed; records in J/mol and J/mol/K (the corpus convention, H+ = 0).
MW is the sum of the engine's own atomic weights (src/thermo/AtomicWeights.cpp), 3 decimals.
"""
