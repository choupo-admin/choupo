#!/usr/bin/env python3
"""Make the aqueous-species and ionisation records of C373 from the batch's evidence tables.

    bin/curate/species_c373.py write     (re)write every record the tables say `build`
    bin/curate/species_c373.py check     compare the tables with the tree; exit 1 on any difference
    bin/curate/species_c373.py list      families, species and step counts

SOURCE OF TRUTH: data/curation/batches/species_c373/*.tsv, one reading per row:
  sources.tsv    key -> full citation and the scale the source states
  families.tsv   one row per family: navigation root, who writes its chemistry, the neutral component whose
                 crystal datum and heat of solution give the neutral aqueous enthalpy, the tolerance of the
                 one-scale check
  species.tsv    key, formula, charge, family, position in the ladder (0 = the most protonated form, the
                 speciation master), build (new) | update (exists, rewritten; navigation already names it) | existing (not touched)
  steps.tsv      one ionisation step per row: pK, dH, dCp as PRINTED, the source, the table and page, and
                 whether the number was read from a page image (a later human check)
  formation.tsv  hfAq / sAq of a species, the arithmetic that gives it from printed numbers, the tables and
                 pages, whether read from an image

What is written: species/<key>.dat for every species with status `build`; chemistry/<key>-formation.dat
(forward records from the master, plus the inverse written from the fully dissociated form) for every family
whose `chem` is `build`; the generated block of metadata/aqueous-navigation.dat.  A family whose chem is
`existing` has its records written by hand in an earlier campaign (C372): `check` holds them to steps.tsv.

Units: tables in kJ/mol and J/mol/K as printed; records in J/mol and J/mol/K (the corpus convention, H+ = 0).
MW is the sum of the engine's own atomic weights (src/thermo/AtomicWeights.cpp), 3 decimals.
"""
import re
import sys
from decimal import Decimal as D
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import species_c320 as c320  # noqa: E402  (weights, atoms, charge_of, mw)

ROOT = HERE.parents[1]
BATCH = ROOT / "data" / "curation" / "batches" / "species_c373"
SPECIES = ROOT / "data" / "standards" / "species"
CHEM = ROOT / "data" / "standards" / "chemistry"
NAV = ROOT / "metadata" / "aqueous-navigation.dat"
BEGIN = "    // BEGIN C373 (generated by bin/curate/species_c373.py from data/curation/batches/species_c373/*.tsv; do not edit)"
END = "    // END C373"
TOOL = "bin/curate/species_c373.py"
TABLES = "data/curation/batches/species_c373"


def load(name):
    lines = (BATCH / name).read_text(encoding="utf-8").splitlines()
    hdr = lines[0].split("\t")
    rows = []
    for ln in lines[1:]:
        if not ln.strip():
            continue
        f = ln.split("\t")
        f += [""] * (len(hdr) - len(f))
        assert len(f) == len(hdr), (name, ln)
        rows.append(dict(zip(hdr, f)))
    return rows


def tables():
    t = {n: load(n + ".tsv") for n in ("sources", "families", "species", "steps", "formation")}
    t["src"] = {r["key"]: r for r in t["sources"]}
    t["fam"] = {r["family"]: r for r in t["families"]}
    t["sp"] = {r["key"]: r for r in t["species"]}
    return t


def clean(s):
    return s.replace(";", ",").replace('"', "'")


def ladder(t, family):
    sp = sorted((r for r in t["species"] if r["family"] == family), key=lambda r: int(r["position"]))
    return sp


def steps_of(t, family):
    return sorted((r for r in t["steps"] if r["family"] == family), key=lambda r: int(r["step"]))


def kj_to_j(s):
    return int((D(s) * 1000).to_integral_value())


def jnum(x):
    """Decimal J/mol as a short exact literal."""
    return str(int(x)) if x == x.to_integral_value() else format(x.normalize(), "f")


def logk_text(x):
    q = x.quantize(D("0.001"))
    return format(q.normalize(), "f") if q != 0 else "0"


def cite(t, key):
    return t["src"][key]["citation"]


def step_cite(t, r):
    return f"{cite(t, r['src'])}, {r['where']}"


# ---------------------------------------------------------------- species records
def species_header(t, sp, fam, kind):
    k = sp["key"]
    L = ["/*--------------------------------*- Choupo -*--------------------------------*\\",
         f"  species/{k}.dat -- ONE model species, ONE typed file: {kind}.",
         f"  Made by {TOOL} from {TABLES}/*.tsv, which holds every",
         "  reading (source, table, page, whether read from a page image).  Standard state: ideal solution at",
         "  1 mol/kg, 298.15 K, H+ = 0."]
    return L


def render_species(t, sp):
    fam = t["fam"][sp["family"]]
    z = int(sp["charge"])
    f = sp["formula"]
    assert c320.charge_of(f) == z, (sp["key"], f, z)
    lad = ladder(t, sp["family"])
    pos = int(sp["position"])
    last = len(lad) - 1
    form = [r for r in t["formation"] if r["species"] == sp["key"]]
    label = fam["label"]
    if pos == 0:
        kind = f"the most protonated form of {label}, the speciation MASTER of its family"
    elif pos == last:
        kind = f"the fully dissociated form of {label}"
    else:
        kind = f"an intermediate ionisation state of {label}"
    L = species_header(t, sp, fam, kind)
    if form:
        L.append("  The formation values are DERIVED from printed numbers; the arithmetic, tables and pages are in the")
        L.append("  source line below and in formation.tsv.")
    else:
        L.append("  NO `aqueousThermo` ON PURPOSE: " + (fam["nothermo"] or
                 "the ionisation (pK, dH) of this family is evaluated in a work in hand and is in chemistry/, so the SPECIATION"
                 " is complete; no work in hand prints a formation enthalpy or entropy for this species, so a balance that"
                 " needs its enthalpy REFUSES BY NAME instead of borrowing a value."))
    L.append("\\*-----------------------------------------------------------------------------*/")
    L += ["recordType modelSpecies;", "schemaVersion 1;", "", f"name    {sp['key']};", f'formula     "{f}";',
          f"charge  {z:+d};" if z else "charge  0;", f"MW {{ value {c320.mw(f):g}; unit g/mol;}}"]
    if form:
        q = {r["quantity"]: r for r in form}
        srcs = []
        for r in form:
            srcs.append(f"{r['quantity']} [{r['unit']}] {r['value']}: {r['derivation']} -- {cite(t, r['src'])}, {r['where']}"
                        + (" (read from a page image)" if r["image"] == "yes" else "")
                        + (f"; {r['note']}" if r["note"] else ""))
        L.append("aqueousThermo")
        L.append("{")
        L.append('source "' + clean(" ## ".join(srcs)) + '";')
        if "hfAq" in q:
            L.append(f"hfAq {{ value {jnum(D(q['hfAq']['value']) * 1000)}; unit J/mol;}}")
        if "sAq" in q:
            L.append(f"sAq  {{ value {format(D(q['sAq']['value']).normalize(), 'f')}; unit J/mol/K;}}")
        L.append("}")
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- chemistry records
def ladder_data(t, family):
    lad = ladder(t, family)
    st = steps_of(t, family)
    assert len(st) == len(lad) - 1, (family, len(st), len(lad))
    return lad, st


def cumulative(st, upto):
    """sum pK and sum dH over steps 1..upto; dH None if any is missing."""
    pk = sum(D(r["pK"]) for r in st[:upto])
    dh = None
    if all(r["dH"] for r in st[:upto]):
        dh = sum(D(r["dH"]) for r in st[:upto])
    return pk, dh


def step_lines(t, fam, st):
    L = []
    for r in st:
        bits = [f"pK{r['step']} = {r['pK']}"]
        L.append(bits[0] + (f", dH{r['step']} = {r['dH']} kJ/mol" if r["dH"] else ", dH not printed")
                 + (f", dCp {r['dCp']} J/mol/K" if r["dCp"] else "")
                 + (f" (grade {r['grade']})" if r["grade"] else ""))
    return L


def source_line(t, fam, st):
    src_keys = sorted({r["src"] for r in st})
    parts = []
    for r in st:
        parts.append(f"{r['where']}: pK{r['step']} {r['pK']}" + (f", dH{r['step']} {r['dH']} kJ/mol" if r["dH"] else "")
                     + (" (read from a page image)" if r["image"] == "yes" else ""))
    cit = "; ".join(cite(t, k) for k in src_keys)
    return clean(f"{cit} -- " + "; ".join(parts) + " (pK, dH_ion at 298.15 K)")


def render_chem(t, family, i):
    """record of the species at ladder position i (i = 0: the inverse from the last)."""
    fam = t["fam"][family]
    lad, st = ladder_data(t, family)
    n = len(lad) - 1
    label = fam["label"]
    if i == 0:
        mname, ion, nu = lad[0]["key"], lad[n]["key"], n
        pk, dh = cumulative(st, n)
        logk, dhj = pk, (-dh * 1000 if dh is not None else None)
        eq = f"{lad[n]['key']}({lad[n]['charge']}) + {n} H+  <=>  {lad[0]['key']}"
        what = (f"the {label} master as the sum of its fully dissociated form (the inverse of the records written from the master;"
                " a case declares one master and the closure activates the record reachable from it)")
        masters = f"{{ ion {ion}; nu 1; }} {{ ion H; nu {n}; }}"
        sign = "the sign flips with the direction written"
    else:
        mname = lad[i]["key"]
        pk, dh = cumulative(st, i)
        logk, dhj = -pk, (dh * 1000 if dh is not None else None)
        eq = f"{lad[0]['key']}  <=>  {lad[i]['key']} + {i} H+" if i > 1 else f"{lad[0]['key']}  <=>  {lad[i]['key']} + H+"
        what = (f"the {'first' if i == 1 else 'first ' + str(i)} dissociation{'s' if i > 1 else ''} of {label}, written from the master")
        masters = f"{{ ion {lad[0]['key']}; nu 1; }} {{ ion H; nu {-i}; }}"
        sign = "the sign flips with the direction written" if i > 1 else "the sign flips with the direction written"
    carries = "the sum of the first %d steps" % (n if i == 0 else i) if (i == 0 and n > 1) or i > 1 else "the first step" if i == 1 else "the one step"
    L = ["/*--------------------------------*- Choupo -*--------------------------------*\\",
         f"  chemistry/{mname}-formation.dat -- {what}:",
         f"      {eq}", ""]
    L.append(f"  logK25 and dH are the PRINTED values of the sources below (standard state ideal solution at 1 mol/kg, 298.15 K):")
    for ln in step_lines(t, fam, st):
        L.append("      " + ln)
    for k in sorted({r["src"] for r in st}):
        L.append(f"  {k}: {cite(t, k)}; {t['src'][k]['scale']}.")
    L.append(f"  This record carries {carries} ({sign}).")
    if dhj is None:
        L.append("  A dH is not printed for every step this record sums, so the record carries NO dH and its K is flat in T,")
        L.append("  which the engine announces; nothing is borrowed.")
    L.append("  The constant-dCp term of the printed dCp is NOT carried: the record grammar has no place for it (a")
    L.append("  van't Hoff integral with a constant dCp is exactly the `analytic` A1, A3, A4 terms; proposed, not done).")
    if fam["note"]:
        L.append("  " + fam["note"])
    L += ["\\*-----------------------------------------------------------------------------*/",
          "recordType aqueousSpeciation;", "schemaVersion 1;", "",
          f"species {mname}; masters ( {masters} );"]
    tail = f"      logK25 {logk_text(logk)};"
    if dhj is not None:
        tail += f" dH {jnum(dhj)};"
    tail += f' source "{source_line(t, fam, st[: (n if i == 0 else i)])}";'
    L.append(tail)
    return "\n".join(L) + "\n"


def chem_files(t):
    out = {}
    for fam in t["families"]:
        if fam["chem"] != "build":
            continue
        lad = ladder(t, fam["family"])
        for i in range(0, len(lad)):
            out[CHEM / f"{lad[i]['key']}-formation.dat"] = render_chem(t, fam["family"], i)
    return out


def species_files(t):
    return {SPECIES / f"{r['key']}.dat": render_species(t, r) for r in t["species"] if r["status"] in ("build", "update")}


def nav_block(t):
    L = [BEGIN]
    for fam in t["families"]:
        if not fam["root"] or fam["root"] == "-":
            continue
        for r in ladder(t, fam["family"]):
            if r["status"] != "build":
                continue    # `update`: already named in the hand-written part of the file
            c = "   // the master of the family" if int(r["position"]) == 0 else ""
            L.append(f"    {r['key']:<9} {{ familyRoots ( {fam['root']} ); }}{c}")
    L.append(END)
    return "\n".join(L) + "\n"


def nav_text(t):
    txt = NAV.read_text(encoding="utf-8")
    blk = nav_block(t)
    if BEGIN in txt:
        a = txt.index(BEGIN)
        b = txt.index(END) + len(END) + 1
        return txt[:a] + blk + txt[b:]
    # first time: insert before the closing brace of speciesNavigation (the line `}` before topicVocabulary comment)
    marker = "}\n\n// The CLOSED vocabulary of process topics."
    assert marker in txt
    return txt.replace(marker, blk + marker, 1)


def expected(t):
    files = {}
    files.update(species_files(t))
    files.update(chem_files(t))
    files[NAV] = nav_text(t)
    return files


# ---------------------------------------------------------------- the checks the gate also uses
def parse_chem(path):
    s = path.read_text(encoding="utf-8")
    m = re.search(r"logK25\s+([-+0-9.eE]+)\s*;(?:\s*dH\s+([-+0-9.eE]+)\s*;)?", s)
    sp = re.search(r"^species\s+(\S+);\s*masters\s*\(\s*(.*?)\)\s*;", s, re.M | re.S)
    return {"logK": D(m.group(1)), "dH": D(m.group(2)) if m.group(2) else None, "species": sp.group(1), "masters": sp.group(2)}


def parse_hf(path):
    s = path.read_text(encoding="utf-8")
    m = re.search(r"hfAq\s*\{\s*value\s+([-+0-9.eE]+)", s)
    return D(m.group(1)) / 1000 if m else None


def neutral_hf(t, fam):
    """crystal dHf + heat of solution of the family's neutral component, kJ/mol; None if not declared."""
    comp = fam["neutral_component"]
    if not comp or comp == "-":
        return None
    c = (ROOT / "data" / "standards" / "components" / f"{comp}.dat").read_text(encoding="utf-8")
    p = (ROOT / "data" / "standards" / "parameters" / "solution" / f"{comp}-water.dat").read_text(encoding="utf-8")
    hf = D(re.search(r"dHf_298\s+([-+0-9.eE]+)", c).group(1)) / 1000
    ds = D(re.search(r"dHsoln\s+([-+0-9.eE]+)\s*J/mol", p).group(1)) / 1000
    return hf + ds


def check(t):
    bad = []
    n = 0
    for path, text in expected(t).items():
        n += 1
        if not path.exists():
            bad.append(f"missing: {path.relative_to(ROOT)}")
        elif path.read_text(encoding="utf-8") != text:
            bad.append(f"differs from what {TOOL} renders: {path.relative_to(ROOT)}")
    # keys unique, charge from formula, MW
    keys = [r["key"] for r in t["species"]]
    if len(keys) != len(set(keys)):
        bad.append("duplicate species key in species.tsv")
    for r in t["species"]:
        if c320.charge_of(r["formula"]) != int(r["charge"]):
            bad.append(f"{r['key']}: charge {r['charge']} != formula {r['formula']}")
    # the existing hand-written chemistry holds to steps.tsv
    for fam in t["families"]:
        lad, st = ladder_data(t, fam["family"])
        nn = len(lad) - 1
        for i in range(0, len(lad)):
            p = CHEM / f"{lad[i]['key']}-formation.dat"
            if not p.exists():
                bad.append(f"{fam['family']}: no chemistry/{lad[i]['key']}-formation.dat")
                continue
            pc = parse_chem(p)
            if i == 0:
                pk, dh = cumulative(st, nn)
                want_k, want_h = pk, (-dh * 1000 if dh is not None else None)
            else:
                pk, dh = cumulative(st, i)
                want_k, want_h = -pk, (dh * 1000 if dh is not None else None)
            if abs(pc["logK"] - want_k) > D("0.0006"):
                bad.append(f"{p.name}: logK25 {pc['logK']} != steps.tsv {want_k}")
            if (pc["dH"] is None) != (want_h is None) or (want_h is not None and abs(pc["dH"] - want_h) > D("0.5")):
                bad.append(f"{p.name}: dH {pc['dH']} != steps.tsv {want_h}")
    # one-scale: hf differences along the ladder reproduce the step enthalpies within the family's tolerance
    rows = []
    for fam in t["families"]:
        lad, st = ladder_data(t, fam["family"])
        tol = D(fam["tolerance_kJ"]) if fam["tolerance_kJ"] else None
        hfs = []
        for i, r in enumerate(lad):
            if i == 0:
                hfs.append(neutral_hf(t, fam))
            else:
                p = SPECIES / f"{r['key']}.dat"
                hfs.append(parse_hf(p) if p.exists() else None)
        for i in range(1, len(lad)):
            if hfs[i] is None or hfs[i - 1] is None or not st[i - 1]["dH"]:
                continue
            diff = hfs[i] - hfs[i - 1]
            rows.append((fam["family"], i, hfs[i] - hfs[i - 1], D(st[i - 1]["dH"])))
            if tol is not None and abs(diff - D(st[i - 1]["dH"])) > tol:
                bad.append(f"{fam['family']} step {i}: hf difference {diff} kJ/mol vs dH {st[i-1]['dH']} exceeds {tol}")
    return bad, n, rows


def main():
    t = tables()
    cmd = sys.argv[1] if len(sys.argv) > 1 else "list"
    if cmd == "list":
        for fam in t["families"]:
            lad = ladder(t, fam["family"])
            print(fam["family"], len(lad), "species", fam["chem"])
        return 0
    if cmd == "write":
        n = 0
        for path, text in expected(t).items():
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                path.write_text(text, encoding="utf-8")
                n += 1
        print(f"species_c373: {n} files written or updated, {len(expected(t))} governed")
        return 0
    if cmd == "check":
        bad, n, rows = check(t)
        for b in bad:
            print("FAIL: " + b)
        if cmd == "check" and not bad:
            print(f"species_c373: OK -- {n} files reproduce byte-identically from the tables; {len(rows)} ladder steps held to their one-scale tolerance")
        return 1 if bad else 0
    if cmd == "scale":
        bad, n, rows = check(t)
        for fam, i, a, b in rows:
            print(f"{fam}\tstep {i}\thf diff {a}\tprinted dH {b}\tdiff {a-b}")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
