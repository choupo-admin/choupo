def load(name):
    lines = (BATCH / name).read_text(encoding="utf-8").splitlines()
    hdr = lines[0].split("\t")
    rows = []
    for ln in lines[1:]:
        if not ln.strip():
            continue
        f = ln.split("\t")
        f += [""] * (len(hdr) - len(f))
        assert len(f) == len(hdr), (name, ln)
        rows.append(dict(zip(hdr, f)))
    return rows


def tables():
    t = {n: load(n + ".tsv") for n in ("sources", "families", "species", "steps", "formation")}
    t["fcompare"] = load("formation_compare.tsv") if (BATCH / "formation_compare.tsv").exists() else []
    t["src"] = {r["key"]: r for r in t["sources"]}
    t["fam"] = {r["family"]: r for r in t["families"]}
    t["sp"] = {r["key"]: r for r in t["species"]}
    return t


def clean(s):
    return s.replace(";", ",").replace('"', "'")


def ladder(t, family):
    sp = sorted((r for r in t["species"] if r["family"] == family), key=lambda r: int(r["position"]))
    return sp


def steps_of(t, family):
    return sorted((r for r in t["steps"] if r["family"] == family), key=lambda r: int(r["step"]))


def kj_to_j(s):
    return int((D(s) * 1000).to_integral_value())


def jnum(x):
    """Decimal J/mol as a short exact literal."""
    return str(int(x)) if x == x.to_integral_value() else format(x.normalize(), "f")


def logk_text(x):
    q = x.quantize(D("0.001"))
    return format(q.normalize(), "f") if q != 0 else "0"


def cite(t, key):
    return t["src"][key]["citation"]


def step_cite(t, r):
    return f"{cite(t, r['src'])}, {r['where']}"


# ---------------------------------------------------------------- species records
def species_header(t, sp, fam, kind):
    k = sp["key"]
    L = ["/*--------------------------------*- Choupo -*--------------------------------*\\",
         f"  species/{k}.dat -- ONE model species, ONE typed file: {kind}.",
         f"  Made by {TOOL} from {TABLES}/*.tsv, which holds every",
         "  reading (source, table, page, whether read from a page image).  Standard state: ideal solution at",
         "  1 mol/kg, 298.15 K, H+ = 0."]
    return L


def render_species(t, sp):
    fam = t["fam"][sp["family"]]
    z = int(sp["charge"])
    f = sp["formula"]
    assert c320.charge_of(f) == z, (sp["key"], f, z)
    lad = ladder(t, sp["family"])
    pos = int(sp["position"])
    last = len(lad) - 1
    form = [r for r in t["formation"] if r["species"] == sp["key"]]
    label = fam["label"]
    m = master_pos(fam)
    if pos == m and m == 0:
        kind = f"the most protonated form of {label}, the speciation MASTER of its family"
    elif pos == m:
        kind = f"{label} in the form a case declares (the compound as weighed), the speciation MASTER of its family"
    elif pos == 0:
        kind = f"the most protonated form of {label}"
    elif pos == last:
        kind = f"the fully dissociated form of {label}"
    else:
        kind = f"an intermediate ionisation state of {label}"
    L = species_header(t, sp, fam, kind)
    if form:
        if all(r["derivation"].startswith("printed") for r in form):
            L.append("  The formation values are the PRINTED numbers of the source; the table, page and row are in the")
            L.append("  source line below and in formation.tsv.")
        else:
            L.append("  The formation values are DERIVED from printed numbers; the arithmetic, tables and pages are in the")
            L.append("  source line below and in formation.tsv.")
    else:
        L.append("  NO `aqueousThermo` ON PURPOSE: " + (fam["nothermo"] or
                 "the ionisation (pK, dH) of this family is evaluated in a work in hand and is in chemistry/, so the SPECIATION"
                 " is complete; the evaluated compilation prints ionisation quantities only (no formation enthalpy or entropy), and none"
                 " was entered from another work in this pass, so a balance that needs the enthalpy of this species REFUSES BY NAME"
                 " instead of borrowing a value."))
    L.append("\\*-----------------------------------------------------------------------------*/")
    L += ["recordType modelSpecies;", "schemaVersion 1;", "", f"name    {sp['key']};", f'formula     "{f}";',
          f"charge  {z:+d};" if z else "charge  0;", f"MW {{ value {c320.mw(f):g}; unit g/mol;}}"]
    if form:
        L.append("aqueousThermo")
        L.append("{")
        L += thermo_lines(t, form)
        L.append("}")
    return "\n".join(L) + "\n"


def thermo_lines(t, form):
    """the source / hfAq / sAq lines of an aqueousThermo block, from the formation rows of one species."""
    q = {r["quantity"]: r for r in form}
    srcs = []
    for r in form:
        srcs.append(f"{r['quantity']} [{r['unit']}] {r['value']}: {r['derivation']} -- {cite(t, r['src'])}, {r['where']}"
                    + (" (read from a page image)" if r["image"] == "yes" else "")
                    + (f"; {r['note']}" if r["note"] else ""))
    L = ['source "' + clean(" ## ".join(srcs)) + '";']
    if "hfAq" in q:
        L.append(f"hfAq {{ value {jnum(D(q['hfAq']['value']) * 1000)}; unit J/mol;}}")
    if "sAq" in q:
        L.append(f"sAq  {{ value {format(D(q['sAq']['value']).normalize(), 'f')}; unit J/mol/K;}}")
    # a value whose origin is not a plain table reading (an estimate printed in the source) declares it, per value
    prov = [(k, q[k]) for k in ("hfAq", "sAq") if k in q and q[k].get("origin") not in ("", None, "literature")]
    if prov:
        L.append("provenance")
        L.append("{")
        for k, r in prov:
            L.append(f"    {k}")
            L.append("    {")
            L.append(f"        origin  {r['origin']};")
            L.append(f'        method  "{clean(r["method"])}";')
            L.append("    }")
        L.append("}")
    return L


# an EXISTING species (hand-written in an earlier campaign, carrying other blocks) that lacks formation data gets
# the generated block INSIDE its aqueousThermo, between two marker lines; every other byte of the record is kept.
IBEGIN = "// BEGIN C376 formation data (generated by bin/curate/species_c373.py from data/curation/batches/species_c373/*.tsv; do not edit)"
IEND = "// END C376"
STUB = re.compile(r"// CURATION STUB.*?is served\.\n", re.S)


def inject_text(t, sp, text):
    form = [r for r in t["formation"] if r["species"] == sp["key"]]
    a = text.find(IBEGIN)
    if a >= 0:
        b = text.index(IEND, a) + len(IEND) + 1
        text = text[:a] + text[b:]
    text = STUB.sub("", text)
    if re.search(r"^\s*hfAq\s*\{", text, re.M):
        raise SystemExit(f"{sp['key']}: the record already carries hfAq; an existing value is compared in formation_compare.tsv, never overwritten")
    m = re.search(r"aqueousThermo\s*\n\{\n", text)
    assert m, sp["key"]
    block = IBEGIN + "\n" + "\n".join(thermo_lines(t, form)) + "\n" + IEND + "\n"
    return text[:m.end()] + block + text[m.end():]


# ---------------------------------------------------------------- chemistry records
def master_pos(fam):
    return int(fam.get("master") or 0)


def ladder_data(t, family):
    lad = ladder(t, family)
    st = steps_of(t, family)
    assert len(st) == len(lad) - 1, (family, len(st), len(lad))
    return lad, st


def cumulative(st, upto):
    """sum pK and sum dH over steps 1..upto; dH None if any is missing."""
    pk = sum(D(r["pK"]) for r in st[:upto])
    dh = None
    if all(r["dH"] for r in st[:upto]):
        dh = sum(D(r["dH"]) for r in st[:upto])
    return pk, dh


# THE MARK TRAVELS WITH THE STORED NUMBER (ES-01, 2026-11-13).  A step whose `dH_basis` column says
# `formationDifference` stores a reaction enthalpy that IS the difference of the formation enthalpies (hfAq) of
# the two species of the step -- and some of those carry a per-value provenance word in formation.tsv.  The
# record's `dH` then carries the word of its LEAST CERTAIN input: estimated if any input is an estimate,
# measured (no block, the generator's convention for a plain table reading) only when every input is.  The
# ranking is the order of the classes in src/core/Origin.H (most certain first); a word it does not rank stops
# the tool rather than being guessed.
ORIGIN_RANK = {"literature": 0, "measured": 0, "experimental": 0, "derived": 1, "regressed": 2, "fitted": 2,
               "predictive": 3, "predicted": 3, "estimated": 4, "estimate": 4, "assumed": 5,
               "placeholder": 6, "stub": 6}


def dh_mark(t, family, steps):
    """(word, method) for the dH summed over `steps`, or None when every formation value it comes from is measured."""
    lad = ladder(t, family)
    inputs = []
    for r in steps:
        basis = r.get("dH_basis", "")
        if basis == "":
            continue                        # a dH printed by the source as such: its own reading, no formation input
        if basis != "formationDifference":
            raise SystemExit(f"{family} step {r['step']}: dH_basis '{basis}' is not a basis this tool knows")
        s = int(r["step"])
        for sp in (lad[s - 1]["key"], lad[s]["key"]):
            rows = [f for f in t["formation"] if f["species"] == sp and f["quantity"] == "hfAq"]
            if len(rows) != 1:
                raise SystemExit(f"{family} step {s}: dH_basis formationDifference needs exactly one hfAq row for {sp} in formation.tsv")
            word = rows[0]["origin"] or "literature"
            if word not in ORIGIN_RANK:
                raise SystemExit(f"{sp} hfAq: provenance word '{word}' is not ranked here (the classes of src/core/Origin.H)")
            if sp not in [i[0] for i in inputs]:
                inputs.append((sp, word, rows[0]["method"]))
    if not inputs:
        return None
    worst = max(inputs, key=lambda i: ORIGIN_RANK[i[1]])[1]
    if ORIGIN_RANK[worst] == 0:
        return None
    named = ", ".join(f"{sp} ({w})" for sp, w, _ in inputs)
    weakest = [i for i in inputs if ORIGIN_RANK[i[1]] == ORIGIN_RANK[worst]]
    methods = []
    for _, _, m in weakest:
        if m and m not in methods:
            methods.append(m)
    method = (f"the difference of the formation enthalpies hfAq of {named} in their species records, so it carries the word "
              f"of its least certain input ({', '.join(i[0] for i in weakest)}"
              + (f": {' / '.join(methods)}" if methods else "") + ")")
    return worst, clean(method)


DH_MARK_NOTE = ["  The dH is the difference of formation enthalpies at least one of which is not a measurement; the",
                "  `provenance { dH {} }` block below carries the word of the least certain one, and the engine announces",
                "  it whenever a run moves log K with this dH (a temperature other than 298.15 K)."]


def dh_mark_lines(mark):
    word, method = mark
    return ["", "provenance", "{", "    dH", "    {", f"        origin  {word};", f'        method  "{method}";', "    }", "}"]


def step_lines(t, fam, st):
    L = []
    for r in st:
        bits = [f"pK{r['step']} = {r['pK']}"]
        L.append(bits[0] + (f", dH{r['step']} = {r['dH']} kJ/mol" if r["dH"] else ", dH not printed")
                 + (f", dCp {r['dCp']} J/mol/K" if r["dCp"] else "")
                 + (f" (grade {r['grade']})" if r["grade"] else "")
                 + (" [printed as approximate]" if "approximate" in r["note"] else ""))
    return L


def source_line(t, fam, st):
    src_keys = sorted({r["src"] for r in st})
    groups = {}
    for r in st:
        item = f"pK{r['step']} {r['pK']}" + (f", dH{r['step']} {r['dH']} kJ/mol" if r["dH"] else "") + \
            (" (read from a page image)" if r["image"] == "yes" else "")
        groups.setdefault(r["where"], []).append(item)
    cit = "; ".join(cite(t, k) for k in src_keys)
    return clean(f"{cit} -- " + "; ".join(f"{w}: " + ", ".join(items) for w, items in groups.items()) + " (pK, dH_ion at 298.15 K)")


def render_chem_master(t, family, j, m):
    """record of the species at ladder position j, written from a master at position m > 0 (no inverse record)."""
    fam = t["fam"][family]
    lad, st = ladder_data(t, family)
    label = fam["label"]
    if j > m:
        ks = st[m:j]
        pk = sum(D(r["pK"]) for r in ks)
        dhj = sum(D(r["dH"]) for r in ks) * 1000 if all(r["dH"] for r in ks) else None
        logk, nuh = -pk, -(j - m)
        eq = f"{lad[m]['key']}  <=>  {lad[j]['key']} + {j - m} H+" if j - m > 1 else f"{lad[m]['key']}  <=>  {lad[j]['key']} + H+"
        what = f"{'a dissociation' if j - m == 1 else 'the first %d dissociations' % (j - m)} of {label}, written from the master"
    else:
        ks = st[j:m]
        pk = sum(D(r["pK"]) for r in ks)
        dhj = -sum(D(r["dH"]) for r in ks) * 1000 if all(r["dH"] for r in ks) else None
        logk, nuh = pk, m - j
        eq = f"{lad[m]['key']} + {m - j} H+  <=>  {lad[j]['key']}" if m - j > 1 else f"{lad[m]['key']} + H+  <=>  {lad[j]['key']}"
        what = f"{'a protonation' if m - j == 1 else 'the first %d protonations' % (m - j)} of {label}, written from the master"
    a, b = (ks[0]["step"], ks[-1]["step"])
    carries = f"step {a}" if a == b else f"steps {a} to {b}"
    L = ["/*--------------------------------*- Choupo -*--------------------------------*\\",
         f"  chemistry/{lad[j]['key']}-formation.dat -- {what}:",
         f"      {eq}", f"  Made by {TOOL} from {TABLES}/*.tsv.", ""]
    L.append("  logK25 and dH are the PRINTED values of the sources below (standard state ideal solution at 1 mol/kg, 298.15 K):")
    for ln in step_lines(t, fam, st):
        L.append("      " + ln)
    for k in sorted({r["src"] for r in st}):
        L.append(f"  Source: {cite(t, k)}; {t['src'][k]['scale']}.")
    L.append(f"  The master is {lad[m]['key']}, the form a case declares; this record carries {carries} (the sign flips with the direction written).")
    if dhj is None:
        L.append("  A dH is not printed for the step this record carries, so it carries NO dH and its K is flat in T,")
        L.append("  which the engine announces; nothing is borrowed.")
    L.append("  The constant-dCp term of the printed dCp is NOT carried: the record grammar has no place for it (a")
    L.append("  van't Hoff integral with a constant dCp is exactly the `analytic` A1, A3, A4 terms; proposed, not done).")
    if dhj is not None and dh_mark(t, family, ks):
        L += DH_MARK_NOTE
    if fam["note"]:
        L.append("  " + fam["note"])
    L += ["\\*-----------------------------------------------------------------------------*/",
          "recordType aqueousSpeciation;", "schemaVersion 1;", "",
          f"species {lad[j]['key']}; masters ( {{ ion {lad[m]['key']}; nu 1; }} {{ ion H; nu {nuh}; }} );"]
    tail = f"      logK25 {logk_text(logk)};"
    if dhj is not None:
        tail += f" dH {jnum(dhj)};"
    tail += f' source "{source_line(t, fam, ks)}";'
    L.append(tail)
    mark = dh_mark(t, family, ks) if dhj is not None else None
    if mark:
        L += dh_mark_lines(mark)
    return "\n".join(L) + "\n"


def render_chem(t, family, i):
    """record of the species at ladder position i (i = 0: the inverse from the last)."""
    fam = t["fam"][family]
    lad, st = ladder_data(t, family)
    n = len(lad) - 1
    label = fam["label"]
    if i == 0:
        mname, ion, nu = lad[0]["key"], lad[n]["key"], n
        pk, dh = cumulative(st, n)
        logk, dhj = pk, (-dh * 1000 if dh is not None else None)
        eq = f"{lad[n]['key']}({lad[n]['charge']}) + {n} H+  <=>  {lad[0]['key']}"
        what = (f"the {label} master as the sum of its fully dissociated form (the inverse of the records written from the master;"
                " a case declares one master and the closure activates the record reachable from it)")
        masters = f"{{ ion {ion}; nu 1; }} {{ ion H; nu {n}; }}"
        sign = "the sign flips with the direction written"
    else:
        mname = lad[i]["key"]
        pk, dh = cumulative(st, i)
        logk, dhj = -pk, (dh * 1000 if dh is not None else None)
        eq = f"{lad[0]['key']}  <=>  {lad[i]['key']} + {i} H+" if i > 1 else f"{lad[0]['key']}  <=>  {lad[i]['key']} + H+"
        what = (f"the {'first' if i == 1 else 'first ' + str(i)} dissociation{'s' if i > 1 else ''} of {label}, written from the master")
        masters = f"{{ ion {lad[0]['key']}; nu 1; }} {{ ion H; nu {-i}; }}"
        sign = "the sign flips with the direction written" if i > 1 else "the sign flips with the direction written"
    carries = "the sum of the first %d steps" % (n if i == 0 else i) if (i == 0 and n > 1) or i > 1 else "the first step" if i == 1 else "the one step"
    L = ["/*--------------------------------*- Choupo -*--------------------------------*\\",
         f"  chemistry/{mname}-formation.dat -- {what}:",
         f"      {eq}", f"  Made by {TOOL} from {TABLES}/*.tsv.", ""]
    L.append(f"  logK25 and dH are the PRINTED values of the sources below (standard state ideal solution at 1 mol/kg, 298.15 K):")
    for ln in step_lines(t, fam, st):
        L.append("      " + ln)
    for k in sorted({r["src"] for r in st}):
        L.append(f"  Source: {cite(t, k)}; {t['src'][k]['scale']}.")
    L.append(f"  This record carries {carries} ({sign}).")
    if dhj is None:
        L.append("  A dH is not printed for every step this record sums, so the record carries NO dH and its K is flat in T,")
        L.append("  which the engine announces; nothing is borrowed.")
    L.append("  The constant-dCp term of the printed dCp is NOT carried: the record grammar has no place for it (a")
    L.append("  van't Hoff integral with a constant dCp is exactly the `analytic` A1, A3, A4 terms; proposed, not done).")
    if dhj is not None and dh_mark(t, family, st[: (n if i == 0 else i)]):
        L += DH_MARK_NOTE
    if fam["note"]:
        L.append("  " + fam["note"])
    L += ["\\*-----------------------------------------------------------------------------*/",
          "recordType aqueousSpeciation;", "schemaVersion 1;", "",
          f"species {mname}; masters ( {masters} );"]
    tail = f"      logK25 {logk_text(logk)};"
    if dhj is not None:
        tail += f" dH {jnum(dhj)};"
    tail += f' source "{source_line(t, fam, st[: (n if i == 0 else i)])}";'
    L.append(tail)
    mark = dh_mark(t, family, st[: (n if i == 0 else i)]) if dhj is not None else None
    if mark:
        L += dh_mark_lines(mark)
    return "\n".join(L) + "\n"


def chem_files(t):
    out = {}
    for fam in t["families"]:
        if fam["chem"] != "build":
            continue
        lad = ladder(t, fam["family"])
        m = master_pos(fam)
        for i in range(0, len(lad)):
            if m == 0:
                out[CHEM / f"{lad[i]['key']}-formation.dat"] = render_chem(t, fam["family"], i)
            elif i != m:
                out[CHEM / f"{lad[i]['key']}-formation.dat"] = render_chem_master(t, fam["family"], i, m)
    return out


def species_files(t):
    out = {SPECIES / f"{r['key']}.dat": render_species(t, r) for r in t["species"] if r["status"] in ("build", "update")}
    have = {r["species"] for r in t["formation"]}
    for r in t["species"]:
        if r["status"] == "existing" and r["key"] in have:
            p = SPECIES / f"{r['key']}.dat"
            out[p] = inject_text(t, r, p.read_text(encoding="utf-8"))
    return out


def nav_block(t):
    L = [BEGIN]
    for fam in t["families"]:
        if not fam["root"] or fam["root"] == "-":
            continue
        for r in ladder(t, fam["family"]):
            if r["status"] != "build":
                continue    # `update`: already named in the hand-written part of the file
            c = "   // the master of the family" if int(r["position"]) == master_pos(fam) else ""
            L.append(f"    {r['key']:<9} {{ familyRoots ( {fam['root']} ); }}{c}")
    L.append(END)
    return "\n".join(L) + "\n"


def nav_text(t):
    txt = NAV.read_text(encoding="utf-8")
    blk = nav_block(t)
    if BEGIN in txt:
        a = txt.index(BEGIN)
        b = txt.index(END) + len(END) + 1
        return txt[:a] + blk + txt[b:]
    # first time: insert before the closing brace of speciesNavigation (the line `}` before topicVocabulary comment)
    marker = "}\n\n// The CLOSED vocabulary of process topics."
    assert marker in txt
    return txt.replace(marker, blk + marker, 1)


def stale(files):
    """tool-made species/chemistry files that no table governs any more."""
    out = []
    for d, mark in ((SPECIES, f"Made by {TOOL}"), (CHEM, f"Made by {TOOL}")):
        for p in sorted(d.glob("*.dat")):
            if p not in files and mark in p.read_text(encoding="utf-8")[:900]:
                out.append(p)
    return out


def expected(t):
    files = {}
    files.update(species_files(t))
    files.update(chem_files(t))
    files[NAV] = nav_text(t)
    return files


# ---------------------------------------------------------------- the checks the gate also uses
def parse_chem(path):
    s = path.read_text(encoding="utf-8")
    m = re.search(r"logK25\s+([-+0-9.eE]+)\s*;(?:\s*dH\s+([-+0-9.eE]+)\s*;)?", s)
    sp = re.search(r"^species\s+(\S+);\s*masters\s*\(\s*(.*?)\)\s*;", s, re.M | re.S)
    return {"logK": D(m.group(1)), "dH": D(m.group(2)) if m.group(2) else None, "species": sp.group(1), "masters": sp.group(2)}


def parse_hf(path):
    s = path.read_text(encoding="utf-8")
    m = re.search(r"hfAq\s*\{\s*value\s+([-+0-9.eE]+)", s)
    return D(m.group(1)) / 1000 if m else None


def neutral_hf(t, fam):
    """crystal dHf + heat of solution of the family's neutral component, kJ/mol; None if not declared."""
    comp = fam["neutral_component"]
    if not comp or comp == "-":
        return None
    c = (ROOT / "data" / "standards" / "components" / f"{comp}.dat").read_text(encoding="utf-8")
    p = (ROOT / "data" / "standards" / "parameters" / "solution" / f"{comp}-water.dat").read_text(encoding="utf-8")
    hf = D(re.search(r"dHf_298\s+([-+0-9.eE]+)", c).group(1)) / 1000
    ds = D(re.search(r"dHsoln\s+([-+0-9.eE]+)\s*J/mol", p).group(1)) / 1000
    return hf + ds


def reading_of(t, key, q):
    """a printed reading held in formation_compare.tsv for a species with no file (catalogue column `-`), kJ/mol."""
    for c in t["fcompare"]:
        if c["species"] == key and c["quantity"] == q and c["catalogue"] == "-":
            return D(c["reading"])
    return None


def parse_sAq(path):
    m = re.search(r"sAq\s*\{\s*value\s+([-+0-9.eE]+)", path.read_text(encoding="utf-8"))
    return D(m.group(1)) if m else None


def check(t):
    bad = []
    # every catalogue value named in formation_compare.tsv is what the record carries (the table cannot rot)
    for c in t["fcompare"]:
        path = SPECIES / f"{c['species']}.dat"
        if c["catalogue"] == "-":
            if path.exists() and parse_hf(path) is not None:
                bad.append(f"{c['species']}: formation_compare.tsv says the species has no record data, but it carries hfAq")
            continue
        have = parse_hf(path) if c["quantity"] == "hfAq" else parse_sAq(path)
        if have is None or abs(have - D(c["catalogue"])) > D("0.0006"):
            bad.append(f"{c['species']} {c['quantity']}: formation_compare.tsv says the catalogue carries {c['catalogue']}, the record carries {have}")
    n = 0
    exp = expected(t)
    for p in stale(exp):
        bad.append(f"stale: {p.relative_to(ROOT)} was made by the tool and no table governs it any more")
    for path, text in exp.items():
        n += 1
        if not path.exists():
            bad.append(f"missing: {path.relative_to(ROOT)}")
        elif path.read_text(encoding="utf-8") != text:
            bad.append(f"differs from what {TOOL} renders: {path.relative_to(ROOT)}")
    # keys unique, charge from formula, MW
    keys = [r["key"] for r in t["species"]]
    if len(keys) != len(set(keys)):
        bad.append("duplicate species key in species.tsv")
    for r in t["species"]:
        if c320.charge_of(r["formula"]) != int(r["charge"]):
            bad.append(f"{r['key']}: charge {r['charge']} != formula {r['formula']}")
    # the existing hand-written chemistry holds to steps.tsv
    for fam in t["families"]:
        if fam["chem"] != "existing":
            continue        # `build`: rendered above; `compare`: records of another origin, reported by `compare`, never held
        lad, st = ladder_data(t, fam["family"])
        nn = len(lad) - 1
        for i in range(0, len(lad)):
            p = CHEM / f"{lad[i]['key']}-formation.dat"
            if not p.exists():
                bad.append(f"{fam['family']}: no chemistry/{lad[i]['key']}-formation.dat")
                continue
            pc = parse_chem(p)
            if i == 0:
                pk, dh = cumulative(st, nn)
                want_k, want_h = pk, (-dh * 1000 if dh is not None else None)
            else:
                pk, dh = cumulative(st, i)
                want_k, want_h = -pk, (dh * 1000 if dh is not None else None)
            if abs(pc["logK"] - want_k) > D("0.0006"):
                bad.append(f"{p.name}: logK25 {pc['logK']} != steps.tsv {want_k}")
            if (pc["dH"] is None) != (want_h is None) or (want_h is not None and abs(pc["dH"] - want_h) > D("0.5")):
                bad.append(f"{p.name}: dH {pc['dH']} != steps.tsv {want_h}")
    # one-scale: hf differences along the ladder reproduce the step enthalpies within the family's tolerance
    rows = []
    for fam in t["families"]:
        lad, st = ladder_data(t, fam["family"])
        tol = D(fam["tolerance_kJ"]) if fam["tolerance_kJ"] else None
        hfs = []
        for i, r in enumerate(lad):
            p = SPECIES / f"{r['key']}.dat"
            own = parse_hf(p) if p.exists() else None
            if i == 0 and own is None:
                nh = neutral_hf(t, fam)             # a neutral master carries no hfAq: its datum is component + pair
                hfs.append(nh if nh is not None else reading_of(t, r["key"], "hfAq"))
            else:
                hfs.append(own)
        for i in range(1, len(lad)):
            if hfs[i] is None or hfs[i - 1] is None or not st[i - 1]["dH"]:
                continue
            diff = hfs[i] - hfs[i - 1]
            rows.append((fam["family"], i, hfs[i] - hfs[i - 1], D(st[i - 1]["dH"])))
            if tol is not None and abs(diff - D(st[i - 1]["dH"])) > tol:
                bad.append(f"{fam['family']} step {i}: hf difference {diff} kJ/mol vs dH {st[i-1]['dH']} exceeds {tol}")
    return bad, n, rows


def analytic_dH(a, T=298.15):
    """dH (J/mol) implied by a PHREEQC analytic log K(T) = A1 + A2 T + A3/T + A4 log10 T + A5/T^2 + A6 T^2."""
    import math
    a = list(a) + [0.0] * (6 - len(a))
    dlog = a[1] - a[2] / T ** 2 + a[3] / (T * math.log(10)) - 2 * a[4] / T ** 3 + 2 * a[5] * T
    return 8.314462 * math.log(10) * T * T * dlog


def compare(t):
    """records already in the catalogue against Goldberg's selected values: pK and dH as the record implies them."""
    rows = []
    for c in load("compare.tsv"):
        fam = c["family"]
        st = steps_of(t, fam)
        idx = [int(x) for x in c["steps"].split("+")]
        sel = [r for r in st if int(r["step"]) in idx]
        gpk = sum(D(r["pK"]) for r in sel)
        gdh = sum(D(r["dH"]) for r in sel) if all(r["dH"] for r in sel) else None
        path = CHEM / (c["record"] + ".dat")
        txt = path.read_text(encoding="utf-8")
        m = re.search(r"logK25\s+([-+0-9.eE]+)\s*;", txt)
        h = re.search(r"\bdH\s+([-+0-9.eE]+)\s*;", txt)
        an = re.search(r"analytic\s*\(([^)]*)\)", txt)
        sign = 1 if c["direction"] == "formation" else -1     # formation: logK = +pK; ionisation: logK = -pK
        rpk = D(m.group(1)) * sign
        rdh = (-D(h.group(1)) * sign / 1000) if h else None   # as an ionisation enthalpy, kJ/mol
        adh = None
        if an:
            adh = -D(repr(analytic_dH([float(x) for x in an.group(1).split()]) / 1000)) * sign
        rows.append((c["record"], fam, c["steps"], rpk, gpk, rdh, adh, gdh))
    return rows


def print_compare(t):
    print("record\tfamily\tsteps\tpK(record)\tpK(Goldberg)\tdiff\tdH_ion(record dH)\tdH_ion(analytic at 298.15)\tdH_ion(Goldberg)\tdiff(dH field)\tdiff(analytic)")
    for rec, fam, steps, rpk, gpk, rdh, adh, gdh in compare(t):
        f = lambda x: "" if x is None else f"{float(x):.3f}"
        d1 = "" if rdh is None or gdh is None else f"{float(rdh - gdh):+.2f}"
        d2 = "" if adh is None or gdh is None else f"{float(adh - gdh):+.2f}"
        print(f"{rec}\t{fam}\t{steps}\t{float(rpk):.3f}\t{float(gpk):.3f}\t{float(rpk - gpk):+.3f}\t{f(rdh)}\t{f(adh)}\t{f(gdh)}\t{d1}\t{d2}")



