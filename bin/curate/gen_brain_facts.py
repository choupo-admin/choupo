"""Regenerate the FACTS block of BRAIN.md from TRACKED sources only.

    bin/curate/gen_brain_facts.py            rewrite the block in place
    bin/curate/gen_brain_facts.py --check    exit 1 with a diff if it differs

The block sits between `<!-- brain-facts:begin -->` and `<!-- brain-facts:end -->`.
Every number is read from a tracked file (generated/releaseInventory.json,
generated/caseManifest.json, the registrations in src/, the gate scripts, the
lesson files, the validation tables, the golden files); nothing is typed.
Deterministic and idempotent: no date, no commit hash, no clock.  (C241.)
"""
import ast, difflib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BEGIN, END = "<!-- brain-facts:begin -->", "<!-- brain-facts:end -->"


def count(path, pat):
    return len(re.findall(pat, (ROOT / path).read_text(), re.M))


def known_open():
    tree = ast.parse((ROOT / "bin/curate/check_energy_closure.py").read_text())
    for n in tree.body:
        if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "KNOWN_OPEN":
            return len(n.value.keys)
    raise SystemExit("gen_brain_facts: KNOWN_OPEN not found")


def wrap(text, width=78):
    out, line = [], ""
    for w in text.split():
        if line and len(line) + 1 + len(w) > width:
            out.append(line)
            line = "  " + w
        else:
            line = (line + " " + w) if line else w
    out.append(line)
    return "\n".join(out)


def block():
    inv = json.loads((ROOT / "generated/releaseInventory.json").read_text())
    man = json.loads((ROOT / "generated/caseManifest.json").read_text())
    cat, tut, eng = inv["catalogue"], inv["tutorials"], inv["engine"]
    cases = man["cases"]
    top = {}
    app = {}
    for p, v in cases.items():
        top[p.split("/")[1]] = top.get(p.split("/")[1], 0) + 1
        app[v["application"]] = app.get(v["application"], 0) + 1
    order = ["steady", "props", "batch", "plant", "ctrl", "unsteady"]
    tops = ", ".join("%s %d" % (k, top[k]) for k in order if k in top)
    tops += "".join(", %s %d" % (k, v) for k, v in sorted(top.items()) if k not in order)
    apps = ", ".join("%s %d" % (k, v) for k, v in
                     sorted(app.items(), key=lambda kv: (-kv[1], kv[0])))
    vv = (ROOT / "docs/architecture/verification-and-validation.md").read_text()
    sec3 = vv.split("## 3. ")[1].split("\n## 3a.")[0]
    rows = [l for l in sec3.splitlines() if l.startswith("| `")]
    fit = sum(1 for l in rows if "**fit-consistency**" in l)
    anchored = []
    for e in sorted((ROOT / "tutorials").rglob("expected")):
        if any("anchor" in ln.split() for ln in e.read_text().splitlines()
               if not ln.lstrip().startswith("#")):
            anchored.append(e.parent.relative_to(ROOT).as_posix())
    plants = sum(1 for a in anchored if a.startswith("tutorials/plant/"))
    cols = sum(1 for a in anchored if "distillationColumn" in cases.get(a, {}).get("unitTypes", []))
    lay = sorted(p.parent.parent.relative_to(ROOT).as_posix()
                 for p in (ROOT / "tutorials").rglob("layoutDict"))
    l_pl = sum(1 for p in lay if p.startswith("tutorials/plant/"))
    l_bp = sum(1 for p in lay if p.startswith("tutorials/batch/plant/"))
    ng = len(list((ROOT / "bin/curate").glob("check_*.py")))
    nl = len(list((ROOT / "gui/src/ui/methods").glob("*Lesson.ts")))
    uo = count("src/unitOperations/UnitOperation.cpp", r'reg\("')
    po = count("src/propertyOps/PropertyOperation.cpp", r'reg\("')
    L = ["Generated by bin/curate/gen_brain_facts.py from the tracked tree.",
         "- Line `%s`; latest release `%s` (%s)." % (inv["line"], inv["latestRelease"], inv["latestReleasedAt"]),
         wrap("- Runnable cases %d: %s.  By binary: %s.  Golden-checked %d." %
              (tut["runnableCases"], tops, apps, tut["regressionChecks"])),
         wrap("- Engine: %d unit operations, %d property operations, %d binaries, %d gates, %d EduTool lesson files." %
              (uo, po, eng["engines"], ng, nl)),
         wrap("- Catalogue: %d components, %d aqueous species; pairs NRTL %d, UNIQUAC %d, Wilson %d, Henry %d, Pitzer %d, eNRTL %d; %d membranes, %d adsorbents, %d utilities." %
              (cat["components"], cat["aqueousSpecies"], cat["nrtlPairs"], cat["uniquacPairs"], cat["wilsonPairs"],
               cat["henryPairs"], cat["pitzerPairs"], cat["enrtlPairs"], cat["membranes"], cat["adsorbents"], cat["utilities"])),
         wrap("- Validation: %d rows in the named subset (%d of them fit-consistency); %d cases carry `anchor` rows; %d of those are plants, %d are distillation columns.  `check_energy_closure` KNOWN_OPEN: %d cases." %
              (len(rows), fit, len(anchored), plants, cols, known_open())),
         wrap("- Layout cases: %d (%d under tutorials/plant, %d under tutorials/batch/plant, %d elsewhere)." %
              (len(lay), l_pl, l_bp, len(lay) - l_pl - l_bp))]
    return "\n".join(L)


def main():
    f = ROOT / "BRAIN.md"
    t = f.read_text()
    i, j = t.index(BEGIN) + len(BEGIN), t.index(END)
    new = t[:i] + "\n" + block() + "\n" + t[j:]
    if "--check" in sys.argv:
        if new != t:
            sys.stdout.writelines(difflib.unified_diff(t.splitlines(1), new.splitlines(1), "BRAIN.md (disk)", "BRAIN.md (fresh)"))
            print("gen_brain_facts: the FACTS block is stale -- run bin/curate/gen_brain_facts.py")
            return 1
        return 0
    f.write_text(new)
    return 0


sys.exit(main())
