"""Generate a reference-equation record from its committed page-image transcription.

    bin/curate/helmholtz/gen_record.py <fluid>/<Equation>.txt          # write the record
    bin/curate/helmholtz/gen_record.py --check <fluid>/<Equation>.txt  # exit 1 if stale

The transcription (bin/curate/helmholtz/<fluid>/<Equation>.txt) is the ONE
committed home of the numbers read off a primary's page images; the record
data/standards/parameters/Helmholtz/<Equation>.dat is DERIVED from it here and
is never edited by hand (the Svehla-1962 precedent, bin/curate/svehla1962/).

Units: the transcription writes each table in the publication's own units;
this script converts kJ to J and MPa stays a declared unit, by moving the
decimal exponent of the printed string -- the printed digits survive.  Each
check value's significant-digit count is taken from its PRINTED STRING, and
values of one table row are grouped into one check entry per digit count,
so the engine judges every value at exactly the precision it was printed to.
"""
import os
import re
import sys
from decimal import Decimal, getcontext

getcontext().prec = 40

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(ROOT, "data", "standards", "parameters", "Helmholtz")


def sections(path):
    out, cur, head = {}, None, {}
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"\[([\w-]+)\]\s*(.*)$", line)
        if m:
            cur = m.group(1); out[cur] = []; head[cur] = m.group(2); continue
        out[cur].append(line.strip())
    return out, head


def kv(lines):
    d = {}
    for l in lines:
        k, _, v = l.partition(" ")
        d[k] = v.strip()
    return d


def sigdigits(s):
    s = s.lstrip("+-").split("e")[0]
    digits = s.replace(".", "").lstrip("0")
    return len(digits)


def shift(s, k):
    """The printed string s times 10^k, written without touching its digits."""
    m = re.match(r"^([+-]?[\d.]+)(?:e([+-]?\d+))?$", s)
    e = int(m.group(2) or 0) + k
    return m.group(1) + (f"e{e}" if e else "")


def column(name, vals):
    rows = ["  ".join(vals[i:i + 4]) for i in range(0, len(vals), 4)]
    body = "\n".join("                " + r for r in rows)
    return f"            {name:<8}(\n{body}\n            );\n"


def generate(src):
    sec, head = sections(src)
    ident = kv(sec["identity"]); c = kv(sec["constants"]); v = kv(sec["validity"])
    tp = kv(sec["triplePoint"])
    eq = ident["equation"]

    # A MOLAR-basis paper (mol/dm3, J/mol) is converted to the kernel's mass
    # basis HERE, in exact decimal arithmetic with the paper's own molar mass
    # M [g/mol]: rho [kg/m3] = rho [mol/dm3] * M;  e [J/kg] = e [J/mol] * 1000/M.
    # The converted value is written to 20 significant digits; the digit
    # count a check value is judged at stays the one the paper PRINTED.
    M = Decimal(ident["M"].split()[0]) if "M" in ident else None

    def factor(u):
        return {"mol/dm3": M, "J/mol": 1000 / M if M else None,
                "J/mol/K": 1000 / M if M else None}.get(u)

    def molar(numstr, u):
        f = factor(u)
        if f is None: return None, u
        return Decimal(numstr) * f, {"mol/dm3": "kg/m3", "J/mol": "J/kg", "J/mol/K": "J/kg/K"}[u]

    def fmt(d):
        return format(d.normalize() if d == d.to_integral() else +d, ".20g")

    def unit(val):                 # "0.1889241 kJ/kg/K" -> "0.1889241e3 J/kg/K"
        num, u = val.split(" ", 1)
        if u.startswith("kJ"):
            return shift(num, 3) + " " + u[1:]
        x, uu = molar(num, u)
        if x is not None:
            return f"{fmt(x)} {uu}"
        return val

    L = []
    w = L.append
    w("/*--------------------------------*- Choupo -*--------------------------------*\\")
    w(f"  {eq} -- the reference equation of state of {ident['fluid']}.")
    w("")
    w("  GENERATED by bin/curate/helmholtz/gen_record.py from the page-image")
    w(f"  transcription bin/curate/helmholtz/{os.path.basename(os.path.dirname(src))}/{os.path.basename(src)}")
    w("  (each table read twice from the page images and diffed; the pages and")
    w("  tables are named there).  Do not edit by hand: edit the transcription")
    w("  and regenerate.  Every check value below is the publication's own,")
    w("  reproduced by the engine at its printed precision at every load (a miss")
    w("  refuses the record) and by bin/curate/check_reference_eos.py.")
    w("")
    if "M" in ident:
        w(f"  The paper is written on a MOLAR basis; every density, energy and")
        w(f"  entropy below was converted to the kernel's mass basis by the generator,")
        w(f"  in exact decimal arithmetic, with the paper's own molar mass")
        w(f"  M = {ident['M']} (the printed digit counts are kept).")
        w("")
    w("  Licence of the numbers: the coefficients and tabulated values of a")
    w("  published equation are facts, cited to their paper; no program's fluid")
    w("  file was used, as origin or cross-check.")
    w("\\*-----------------------------------------------------------------------------*/")
    w("recordType    helmholtzEquationOfState;")
    w("schemaVersion 1;")
    w("")
    w(f"equation      {eq};")
    w(f"fluid         {ident['fluid']};")
    w(f"citation      \"{ident['citation']}\";")
    w(f"url           \"{ident['url']}\";")
    w(f"read          \"{ident['read']}\";")
    w("licence       \"published coefficients and tabulated values, cited to their primary; values read from the journal article (page images, and its text layer where it has one)\";")
    w("")
    w(f"reducing                        // {head['constants']}")
    w("{")
    w(f"    Tc      {c['Tc']};")
    w(f"    rhoc    {unit(c['rhoc'])};")
    w("}")
    w(f"R           {unit(c['R'])};")
    w("")
    w(f"triplePoint {{ T {tp['T']}; }}      // {head['triplePoint']}")
    w("")
    w(f"validity                        // {head['validity']}")
    w("{")
    for k in ("Tmin", "Tmax", "pMax"):
        w(f"    {k:<7} {v[k]};")
    w(f"    extrapolation \"{v['extrapolation']}\";")
    w("}")
    w("")
    w(f"uncertainty \"{v['uncertainty']}\";")
    w("")

    # ---- ideal ----------------------------------------------------------
    #  rows: <kind> <coefficient> [<parameter>]; kinds lead0 (the constant),
    #  lead1 (the tau coefficient), logTau, power (n, t), planckEinstein
    #  (n, gamma); `planckEinsteinB` is the same term printed as
    #  ln(1 - exp(b tau)) with b < 0 (gamma = -b, sign moved here).
    rows = [r.split() for r in sec["ideal"]]
    lead = {"lead0": "0", "lead1": "0"}
    logtau, pw, pe = None, [], []
    for r in rows:
        if r[0] in lead: lead[r[0]] = r[1]
        elif r[0] == "logTau": logtau = r[1]
        elif r[0] == "power": pw.append((r[1], r[2]))
        elif r[0] == "planckEinstein": pe.append((r[1], r[2]))
        elif r[0] == "planckEinsteinB": pe.append((r[1], r[2][1:] if r[2].startswith("-") else "-" + r[2]))
        else: raise SystemExit(f"{src}: unknown ideal kind {r[0]}")
    w(f"ideal                           // {head['ideal']}")
    w("{")
    w(f"    lead      ( {lead['lead0']}  {lead['lead1']} );")
    if logtau: w(f"    logTau    {logtau};")
    if pw:
        w("    power")
        w("    {")
        w("        n     ( " + " ".join(x[0] for x in pw) + " );")
        w("        t     ( " + " ".join(x[1] for x in pw) + " );")
        w("    }")
    if pe:
        w("    planckEinstein")
        w("    {")
        w("        n     ( " + " ".join(x[0] for x in pe) + " );")
        w("        gamma ( " + " ".join(x[1] for x in pe) + " );")
        w("    }")
    w("}")
    w("")

    # ---- residual -------------------------------------------------------
    groups = [("residual-power", "power", ["n", "d", "t"]),
              ("residual-exponential", "exponential", ["n", "d", "t", "c"]),
              ("residual-gaussian", "gaussian", ["n", "d", "t", "alpha", "beta", "gamma", "epsilon"]),
              ("residual-nonAnalytic", "nonAnalytic", ["n", "a", "b", "beta", "A", "B", "C", "D"])]
    w("residual")
    w("{")
    for key, name, cols in groups:
        if key not in sec: continue
        rows = [r.split() for r in sec[key]]
        idx = [r[0] for r in rows]
        w(f"        // terms {idx[0]}-{idx[-1]}, {head[key]}")
        w(f"        {name}")
        w("        {")
        for j, col in enumerate(cols):
            L.append(column(col, [r[j + 1] for r in rows]).rstrip("\n"))
        w("        }")
    w("}")
    w("")

    # ---- check values ---------------------------------------------------
    def entries(fixed, vals, tabname):
        """One entry per (significant-digit count, printed scale) among vals
        [(key, printed str, unitshift, unit, scale)]."""
        by = {}
        for key, s, k, u, sc in vals:
            text = u if k is None else f"{shift(s, k)} {u}"   # k None: converted value already in u
            by.setdefault((sigdigits(s), sc or ""), []).append(f"{key} {text};")
        out = []
        for dig, sc in sorted(by):
            scale = f" printedScale {sc};" if sc else ""
            out.append(f"        {{ table \"{tabname}\"; {fixed} digits {dig};{scale}\n          " + " ".join(by[(dig, sc)]) + " }")
        return out

    w("// The publication's own tabulated values, converted to SI by moving the")
    w("// decimal exponent of the printed string (the printed digits survive);")
    w("// `digits` is the count of significant digits PRINTED for each value.")
    w("checkValues")
    w("{")
    UNIT = {  # printed unit -> (exponent shift, record unit)
        "K": (0, "K"), "MPa": (0, "MPa"), "kPa": (0, "kPa"), "kg/m3": (0, "kg/m3"),
        "kJ/kg": (3, "J/kg"), "kJ/kg/K": (3, "J/kg/K"), "m/s": (0, "m/s"),
        "mol/dm3": (0, "mol/L"), "J/mol": (0, "J/mol"), "J/mol/K": (0, "J/(mol.K)")}

    def table(key, listname, fixedcols):
        if key not in sec: return
        rows = sec[key]
        cols = rows[0].split()[1:]; units = rows[1].split()[1:]
        assert rows[0].startswith("columns") and rows[1].startswith("units"), key
        w(f"    {listname}")
        w("    (")
        for r in rows[2:]:
            t = r.split()
            page = [x for x in t if x.startswith("page=")]
            t = [x for x in t if not x.startswith("page=")]
            fixed = " ".join(f"{c} {t[cols.index(c)]} {UNIT[units[cols.index(c)]][1]};" for c in fixedcols)
            vals = []
            for j, c in enumerate(cols):
                if c in fixedcols: continue
                x, uu = molar(t[j], units[j])
                if x is not None:
                    vals.append((c, t[j], None, f"{fmt(x)} {uu}", fmt(factor(units[j]))))
                    continue
                k, u = UNIT[units[j]]
                vals.append((c, t[j], k, u, None))
            tab = head[key].split("table=")[-1].split()[0] if "table=" in head[key] else key
            hp = re.search(r"page=(\S+)", head[key])
            pg = page[0] if page else (f"page={hp.group(1)}" if hp else "")
            label = f"Table {tab}" + (f" ({pg})" if pg else "")
            for e in entries(fixed, vals, label):
                w(e)
        w("    );")

    table("saturation", "saturation", ["T"])
    table("singlePhase", "pTState", ["T", "p"])
    w("}")
    return eq, "\n".join(L) + "\n"


def main(argv):
    check = "--check" in argv
    srcs = [a for a in argv if not a.startswith("--")]
    if not srcs:
        srcs = sorted(os.path.join(HERE, d, f) for d in os.listdir(HERE)
                      if os.path.isdir(os.path.join(HERE, d))
                      for f in os.listdir(os.path.join(HERE, d)) if f.endswith(".txt"))
    bad = 0
    for src in srcs:
        src = src if os.path.isabs(src) else os.path.join(HERE, src) if not os.path.exists(src) else src
        eq, text = generate(src)
        out = os.path.join(OUTDIR, eq + ".dat")
        if check:
            if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
                print(f"gen_record: STALE {out} -- regenerate from {src}"); bad = 1
        else:
            open(out, "w", encoding="utf-8").write(text)
            print(f"gen_record: wrote {out}")
    if check and not bad:
        print(f"gen_record: OK -- {len(srcs)} record(s) are the generation of their transcription")
    return bad


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
