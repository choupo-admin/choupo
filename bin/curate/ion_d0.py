"""The limiting diffusivity D0 of an ion, as a record block (DEV.md 4c C403).

SOURCE OF TRUTH: data/curation/batches/ion_d0_c403/ion_d0.tsv -- one row per ion: the row label of the
primary table, its 0 / 18 / 25 C entries as printed, and the second table's 25 C reading kept as a cross-check
(it enters no value).  The value stored in a species record is the 25 C entry of the primary table.

    bin/curate/ion_d0.py write     rewrite the `transport` D0 block of every species record the table names
    bin/curate/ion_d0.py list      print the rows with the value each record carries

Two kinds of record are served.  A record that already carries a `transport` block (radius + D0) has its D0
datum and the provenance of that datum replaced; a record without one gets a D0-only block, inserted before
`volumetric` (or at the end).  The records generated by species_c320.py call `transport_block()` from here
when they are rendered, so the generator and this tool cannot disagree about a byte.

Primary tables (read at the page from the images, because Li & Gregory's text layer is garbled):
  LG     Li & Gregory 1974, Geochim. Cosmochim. Acta 38, 703-714, Table 1 (p. 705), 10^-6 cm2/s
  DUDEK  Dudek & Fedkiw 1999, Anal. Chem. 71, 1469-1473, Table 1 (p. 1470), 10^-5 cm2/s
  RS     Robinson & Stokes, Electrolyte Solutions, 2nd ed. 1959, READ IN THE RUSSIAN TRANSLATION (Izdatel'stvo
         Inostrannoi Literatury, Moscow, 1963), Appendix 6.1, pp. 534-535: the limiting equivalent ionic conductance
         lambda0 at 25 C, S cm2/eq as printed; D = RT lambda0 / (|z| F^2) (the Nernst relation), z from the `z` column.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPECIES = ROOT / "data" / "standards" / "species"
TABLE = ROOT / "data" / "curation" / "batches" / "ion_d0_c403" / "ion_d0.tsv"
COLS = ["species", "src", "label", "t0", "t18", "t25", "crc_label", "crc_d", "z", "page", "ref", "temps"]

LG_SRC = ("Y.-H. Li and S. Gregory, Diffusion of ions in sea water and in deep-sea sediments, "
          "Geochim. Cosmochim. Acta 38 (1974) 703-714, Table 1 (p. 705: tracer and self-diffusion "
          "coefficients of ions at infinite dilution, 10^-6 cm2/s at 0, 18 and 25 C)")
DUDEK_SRC = ("D. A. Dudek and P. S. Fedkiw, Infinite-Dilution Diffusion Coefficients of Complex Ions "
             "from Solution Conductivity Data, Anal. Chem. 71 (1999) 1469-1473, doi:10.1021/ac981054i, "
             "Table 1 (p. 1470: handbook values of diffusion coefficients at infinite dilution and 25 C)")

RS_SRC = ("R. A. Robinson and R. H. Stokes, Electrolyte Solutions, 2nd ed., Butterworths, London, 1959, read in the Russian "
          "translation (R. Robinson, R. Stoks, Rastvory elektrolitov, ed. A. N. Frumkin, Izdatel'stvo Inostrannoi Literatury, "
          "Moskva, 1963), Appendix 6.1 (Predel'naya ekvivalentnaya elektroprovodnost' ionov pri 25 C v vode)")

CROSS = ("        //  Cross-check, entering no value: the CRC Handbook of Chemistry and Physics, 82nd ed., table\n"
         "        //  'Ionic Conductivity and Diffusion at Infinite Dilution' (PDF pp. 304-306 of the folder copy), read at its page\n"
         "        //  as a second opinion on this ion at 25 C; it is a compilation and is not this value's origin.\n")

NO_RADIUS = ("    //  D0 ONLY (DEV.md 4c C403).  No `radius` is curated for this ion: the tier's radius is the HYDRATED radius of\n"
             "    //  Nightingale, J. Phys. Chem. 63 (1959) 1381, Table I, and it was not read for this record.  A Stokes radius\n"
             "    //  computed from D0 would be a different convention under the same key, so none is written: DSPM-DE still\n"
             "    //  refuses this ion by name, while the multi-ionic polarisation film and the electrodialysis units read D0 alone.\n")

WITH_RADIUS = ("    //  `radius` is the HYDRATED radius r_H of Nightingale, J. Phys. Chem. 63 (1959) 1381, Table I -- the convention\n"
               "    //  of every DSPM-DE pore fitted against it -- with its own provenance below.  `D0` is the 25 C limiting\n"
               "    //  diffusivity read at the page of Li & Gregory 1974 (DEV.md 4c C403; its own provenance below); before: a value\n"
               "    //  transcribed by machine from a geochemical database.\n")


def fmt(v):
    return "%.4g" % v


def load():
    rows = {}
    for ln in TABLE.read_text(encoding="utf-8").splitlines()[1:]:
        if not ln.strip():
            continue
        f = ln.split("\t")
        f += [""] * (len(COLS) - len(f))
        r = dict(zip(COLS, f))
        rows[r["species"]] = r
    return rows


def _num(s):
    return None if s == "" else float(s)


R_GAS = 8.314462618      # J/(mol K), CODATA 2018 exact
F_FARADAY = 96485.33212  # C/mol, CODATA 2018 exact
T_REF = 298.15           # K


def nernst(lam_scm2_per_eq, z):
    """D = R T lambda0 / (|z| F^2), lambda0 in S cm2/eq converted to S m2/eq (x 1e-4); m2/s."""
    return R_GAS * T_REF / F_FARADAY ** 2 * lam_scm2_per_eq * 1e-4 / abs(z)


def value(r):
    """The stored D0, m2/s: the primary table's 25 C entry."""
    if r["src"] == "LG":
        return _num(r["t25"]) * 1e-10
    if r["src"] == "RS":
        return nernst(_num(r["t25"]), int(r["z"]))
    return _num(r["t25"]) * 1e-9          # DUDEK, 10^-5 cm2/s


def d0_datum(r):
    return "D0 { value %s; unit m2/s; }" % fmt(value(r))


def d0_block(r):
    ind = "        "
    v = value(r)
    if r["src"] == "LG":
        t = [_num(r["t0"]), _num(r["t18"]), _num(r["t25"])]
        source = LG_SRC + ", row %s, column 25 C: %s x 10^-6 cm2/s" % (r["label"], fmt(t[2]))
        method = ("read at the page, 2026-11-15 (DEV.md 4c C403): the scan's text layer of this table is garbled, so "
                  "the row was read from the page image; the 25 C entry converted (1 x 10^-6 cm2/s = 1 x 10^-10 m2/s) "
                  "to %s m2/s" % fmt(v))
        parts = ["%s %s" % (lab, "not given" if x is None else "%s x 1e-10 m2/s" % fmt(x))
                 for lab, x in zip(("0 C", "18 C", "25 C"), t)]
        notes = ("Li & Gregory give, for the same row, " + "; ".join(parts) +
                 " (kept here for the later check of the Stokes-Einstein correction to the run temperature, "
                 "thermo/transport/StokesEinstein.H, which is applied by the consumer).")
        if r["species"] == "PO4":
            notes += (" The printed row label reads 'HP4 3-' (a typesetting slip; the sequence H2PO4-, HPO4 2-, and the "
                      "trivalent charge identify PO4 3-).")
        if r["crc_d"]:
            c = _num(r["crc_d"]) * 1e-9
            notes += (" A second compiled table (named in the comment above) gives %s m2/s for this ion at 25 C (%+.1f %%)."
                      % (fmt(c), (c - v) / v * 100))
            if r["species"] == "MoO4":
                notes += (" The second table's printed D is twice this value, but its own conductivity entry (74.5 x 1e-4 m2 S/mol "
                          "per equivalent) gives 9.92e-10 m2/s through its own formula D = (RT/F^2)(lambda/|z|): the printed D "
                          "appears to omit the division by |z|, and the primary table agrees with the implied value.")
            elif abs(c - v) / v > 0.2:
                notes += " The two tables disagree by far more than for the other ions; this record keeps the primary table's value and flags the pair for the reader."
    elif r["src"] == "RS":
        lam = _num(r["t25"])
        z = int(r["z"])
        source = (RS_SRC + ", " + r["page"] + ", row %s: lambda0 = %s S cm2/eq at 25 C; the book's own literature reference for the row: %s"
                  % (r["label"], r["t25"], r["ref"]))
        method = ("read at the page image, 2026-11-15 (DEV.md 4c C403): lambda0 = %s S cm2/eq (x 1e-4 = %s S m2/eq), converted by the Nernst "
                  "relation D = R T lambda0 / (|z| F^2) with R = 8.314462618 J/mol/K, F = 96485.33212 C/mol, T = 298.15 K "
                  "(RT/F^2 = %.6e), |z| = %d, to %s m2/s" % (r["t25"], fmt(lam * 1e-4), R_GAS * T_REF / F_FARADAY ** 2, abs(z), fmt(v)))
        notes = ("The same conversion applied to the book's Na+ row (lambda0 50.10) gives %s m2/s, +%.1f %% against Li & Gregory's "
                 "1.33e-9 for Na+ (the conductance and tracer routes differ by that much).  No page of the English edition "
                 "was seen: every page named here is the Russian translation's." % (fmt(nernst(50.10, 1)), (nernst(50.10, 1) / 1.33e-9 - 1) * 100))
        if r["temps"]:
            notes += "  " + r["temps"]
        if r["crc_d"]:
            c = _num(r["crc_d"]) * 1e-9
            notes += (" A second compiled table (named in the comment above) gives %s m2/s for this ion at 25 C (%+.2f %%)."
                      % (fmt(c), (c - v) / v * 100))
    else:
        source = (DUDEK_SRC + ", row D(Cu+): 1.20 x 10^-5 cm2/s (the paper cites it to its ref. 8, Y. Marcus, "
                  "Ion Properties, Marcel Dekker 1997, ch. 11, and uses it in its own analysis)")
        method = ("read at the page, 2026-11-15 (DEV.md 4c C403): Table 1 of the paper, row D_Cu+, 1.20e-5 cm2/s converted "
                  "to 1.20e-9 m2/s; the value is the paper's quotation of a handbook value, not its own measurement")
        notes = ("Neither Li & Gregory 1974 nor the second compiled table lists Cu+.  A quoted secondary value: the "
                 "primary measurement behind it is not read here.")
    blk = ind + "D0\n" + ind + "{\n"
    blk += ind + '    source        "%s";\n' % source
    blk += ind + "    origin        literature;\n"
    blk += ind + '    method        "%s";\n' % method
    blk += ind + "    reviewStatus  interim;\n"
    blk += ind + '    notes         "%s";\n' % notes.replace('"', "'")
    blk += ind + "}\n"
    return blk


def transport_block(r):
    """A complete D0-only `transport` block (a record that has none)."""
    s = "transport\n{\n" + NO_RADIUS + "    " + d0_datum(r) + "\n"
    s += "    provenance\n    {\n"
    if r["crc_d"]:
        s += CROSS
    s += d0_block(r) + "    }\n}\n"
    return s


def block_span(t, name):
    m = re.search(r"^" + name + r"\s*\n\{", t, re.M)
    if not m:
        return None
    i = t.index("{", m.start())
    d = 0
    for j in range(i, len(t)):
        if t[j] == "{":
            d += 1
        elif t[j] == "}":
            d -= 1
            if d == 0:
                return m.start(), j + 1
    raise ValueError(name)


def apply_to_text(t, r):
    """Return the record text with this ion's D0 datum and provenance in place."""
    span = block_span(t, "transport")
    if span is None:
        new = transport_block(r)
        m = re.search(r"^volumetric\s*\n\{", t, re.M)
        if m:
            return t[:m.start()] + new + "\n" + t[m.start():]
        return t.rstrip("\n") + "\n\n" + new
    a, b = span
    body = t[a:b].split("\n")[2:-1]
    k = 0
    while k < len(body) and (body[k].strip().startswith("//") or not body[k].strip()):
        k += 1
    head, rest = body[:k], body[k:]
    if any(re.match(r"\s*radius \{", ln) for ln in rest):
        head = WITH_RADIUS.rstrip("\n").split("\n")
    if not any(re.match(r"\s*D0 \{ value", ln) for ln in rest):
        #  a record with a radius and no D0 yet (I-): the datum goes right after the radius line
        k = next(i for i, ln in enumerate(rest) if re.match(r"\s*radius \{", ln))
        rest.insert(k + 1, "    " + d0_datum(r))
    rest = [("    " + d0_datum(r)) if re.match(r"\s*D0 \{ value", ln) else ln for ln in rest]
    txt = "\n".join(rest)
    pm = re.search(r"    provenance\n    \{\n", txt)
    pre, post = txt[:pm.end()], txt[pm.end():]
    post = re.sub(r'        source  "USGS PHREEQC[^\n]*\n', "", post)
    post = re.sub(r"        licence publicDomain;\n", "", post)
    dm = re.search(r"        D0\n        \{\n.*?\n        \}\n", post, re.S)
    if dm:
        post = post[:dm.start()] + post[dm.end():]
    post = post.replace(CROSS, "")
    post = post.replace("  The source line above is the radius's; the record-level `source` is the D0's.", "")
    idx = post.rstrip().rfind("    }")
    post = post[:idx] + (CROSS if r["crc_d"] else "") + d0_block(r) + post[idx:]
    new_tb = "transport\n{\n" + "\n".join(head) + ("\n" if head else "") + pre + post
    if not new_tb.endswith("\n"):
        new_tb += "\n"
    new_tb += "}"
    return t[:a] + new_tb + t[b:]


def verify():
    """Errors: a D0 provenance block with no D0 value (I- had one), a D0 value with no provenance block, and a
    table row whose record carries another number."""
    errs = []
    rows = load()
    for p in sorted(SPECIES.glob("*.dat")):
        t = p.read_text(encoding="utf-8")
        has_prov = re.search(r"^\s*D0\s*\n\s*\{", t, re.M) is not None
        m = re.search(r"^\s*D0 \{ value ([0-9.eE+-]+);", t, re.M)
        if has_prov and not m:
            errs.append(f"{p.name}: a D0 provenance block but no `D0 {{ value ...; unit m2/s; }}` datum -- the ion has no value")
        if m and not has_prov:
            errs.append(f"{p.name}: a D0 value with no D0 provenance block")
        r = rows.get(p.stem)
        if r is not None:
            if not m:
                errs.append(f"{p.name}: the D0 table names this ion but the record carries no D0 value")
            elif abs(float(m.group(1)) - float(fmt(value(r)))) > 1e-9 * abs(value(r)):
                errs.append(f"{p.name}: D0 {m.group(1)} differs from the table's {fmt(value(r))}")
    return errs


def main():
    rows = load()
    cmd = sys.argv[1] if len(sys.argv) > 1 else "list"
    if cmd == "list":
        for n, r in rows.items():
            print(n, r["src"], r["label"], fmt(value(r)))
        return 0
    if cmd == "write":
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import species_c320 as sc
        governed = {n for n, rs in sc.by_species(sc.load_table()).items() if rs[0]["status"] == "included"}
        n_w = 0
        for n, r in rows.items():
            p = SPECIES / (n + ".dat")
            if n in governed:
                continue        # species_c320.py renders these, through transport_block()
            t = p.read_text(encoding="utf-8")
            t2 = apply_to_text(t, r)
            if t2 != t:
                p.write_text(t2, encoding="utf-8")
                n_w += 1
        print("ion_d0: wrote %d record(s); the C320-governed ones are written by species_c320.py" % n_w)
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
