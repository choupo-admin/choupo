#!/usr/bin/env python3
"""Gate: a public fact about an immutable release has ONE home -- its tag.

    bin/curate/check_release_identity.py

WHY THIS EXISTS.  Ordered by Vitor 2026-08-08 after an outside review of the
public website found the homepage claiming 284 runnable tutorials while the
Releases page said 331 -- and the truth, counted from the v2607 tag by the
generator's own definition, is 288.  Neither public number was ever right.
The root cause was DESIGNED, not drifted: release_inventory.py's own docstring
said the storefront label is the last release while "only the COUNTS below
track the current tree" -- one artefact carrying a release's name over the dev
tree's numbers, and every surface that consumed it inherited the conflation.
Alongside it, three hand-written citation strings disagreed with each other
and with CITATION.cff, and the homepage's fallback literals were a years-old
snapshot (41 aqueous species against the tag's 50).

THE RULE, as ruled: a public fact about an immutable release must have one
authoritative home and be derived FROM THAT RELEASE.  The home is
generated/releases/<tag>.json, generated by `release_inventory.py --release
<tag>` from a worktree of the tag; the site's fallback literals are a CHECKED
MIRROR of it (the same pattern as the decision index's prose counts: the copy
may exist for static correctness, but a gate recounts it every run, so it can
never quietly become an independent home).

WHAT THIS CHECKS.
  (a) THE ARTEFACT IS THE TAG'S.  each generated/releases/<tag>.json records
      the commit it was counted from, and that commit must be what the tag
      resolves to today.  An artefact whose commit does not match its tag is
      describing something other than the release it names.
  (b) THE ARTEFACT SURVIVES A RECOUNT.  `--check-release <tag>` rebuilds the
      inventory from a fresh worktree of the tag and diffs -- so a hand-edit
      of the committed artefact, or a generator change that alters the
      counts' meaning, is caught rather than shipped.
  (c) EVERY data-inv LITERAL IN THE SITE SOURCES equals the artefact value it
      names.  The literals exist so the static HTML is truthful without
      JavaScript; this arm is what stops them drifting the way 284 and 41 did.
  (d) ONE CITATION.  The artefact's rendered citation is recomputed here from
      `git show <tag>:CITATION.cff` through the SAME parse_cff the generator
      uses (imported, not copied -- a second implementation would drift), and
      every on-page citation string must equal it byte for byte.
  (e) NO BARE HAND COUNTS.  A 2-4 digit number adjacent to "runnable
      tutorials/cases" in site prose OUTSIDE a data-inv span is refused by
      name -- that is exactly the form the 331 took.

WHAT THIS DOES NOT CHECK, stated plainly.
  * THE PRODUCTION HOST.  This gate reads the repository's site sources; what
    is actually served at choupo.org may differ, and cannot be verified from
    here.
  * /vYYMM/app/ HAS NO PRODUCER.  releases.html and the homepage link a
    frozen app at the release's own /vYYMM/app/ -- "the URL you cite, teach
    from, and archive" -- and NOTHING in bin/buildSite creates or copies that
    tree.  If the
    production host does not carry a hand-uploaded archive, those buttons
    404.  This gate cannot verify either way and says so instead of
    implying coverage; the finding is escalated in the audit report, because
    fixing it properly (archiving a frozen WASM build) is a decision about
    public artefacts, not a patch.
  * ONLY THE RELEASES THAT HAVE AN ARTEFACT.  A release joins by generating
    its artefact at tag time; the gate iterates over generated/releases/*.json
    and knows nothing of a tag whose artefact was never committed.  Where two
    artefacts carry the same fact the NEWEST wins, because the site speaks for
    the current stable release.
"""
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE_PAGES = ["site/index.html", "site/releases.html", "site/models.html"]
FROZEN_APPS = "site/frozenApps.txt"

spec = importlib.util.spec_from_file_location(
    "relinv", ROOT / "bin" / "curate" / "release_inventory.py")
relinv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(relinv)


def flatten(art: dict) -> dict:
    flat = {k: art[k] for k in ("release", "releasedAt", "citationRendered")
            if k in art}
    for g in ("catalogue", "engine", "tutorials", "totals"):
        flat.update(art.get(g, {}))
    return flat


def main() -> int:
    fail = []
    artefacts = sorted((ROOT / "generated" / "releases").glob("v*.json"))
    if not artefacts:
        print("check_release_identity: FAILED\n  no release artefact exists "
              "under generated/releases/ -- the public release facts have no "
              "authoritative home, which is the exact state this gate was "
              "built to end.")
        return 1

    flats = {}
    for af in artefacts:
        art = json.loads(af.read_text())
        tag = art.get("tag", "")
        flats.update(flatten(art))

        # (a) the artefact is the tag's
        want = subprocess.run(["git", "rev-parse", tag + "^{}"],
                              capture_output=True, text=True,
                              cwd=ROOT).stdout.strip()
        if not want:
            fail.append(f"{af.name}: its tag '{tag}' does not resolve -- an "
                        "artefact for a tag that does not exist describes "
                        "nothing")
        elif art.get("commit") != want:
            fail.append(
                f"{af.name} records commit {art.get('commit','?')[:10]} but "
                f"tag {tag} resolves to {want[:10]}.  The artefact is not a "
                "description of the release it names -- regenerate from the "
                "tag, or find out who moved an immutable tag.")

        # (b) the recount
        p = subprocess.run([sys.executable,
                            str(ROOT / "bin/curate/release_inventory.py"),
                            "--check-release", tag],
                           capture_output=True, text=True, cwd=ROOT)
        if p.returncode != 0:
            fail.append(f"{af.name}: recount from tag {tag} diverges -- "
                        + (p.stderr.strip() or p.stdout.strip())[:200])

        # (d) one citation, recomputed through the generator's own parser
        cff = subprocess.run(["git", "show", f"{tag}:CITATION.cff"],
                             capture_output=True, text=True, cwd=ROOT).stdout
        if cff:
            want_cite = relinv.parse_cff(cff)["rendered"]
            if art.get("citationRendered") != want_cite:
                fail.append(
                    f"{af.name}: citationRendered does not match a fresh "
                    f"render of {tag}:CITATION.cff.  The citation's one home "
                    "is the tag's cff; the artefact merely carries it.")
        else:
            fail.append(f"{af.name}: {tag} has no CITATION.cff to check "
                        "against")

    # (c) the site literals are a checked mirror
    span = re.compile(r'data-inv="(\w+)"[^>]*>([^<]*)<')
    for page in SITE_PAGES:
        src = (ROOT / page)
        if not src.is_file():
            fail.append(page + " is missing -- the site surface this gate "
                        "audits has moved")
            continue
        text = src.read_text()
        for m in span.finditer(text):
            key, lit = m.group(1), m.group(2).strip()
            if key not in flats:
                fail.append(f"{page}: data-inv=\"{key}\" names a fact no "
                            "release artefact carries -- either the key is "
                            "stale or the artefact lost a field")
            elif lit and lit != str(flats[key]):
                fail.append(
                    f"{page}: the fallback literal for '{key}' is '{lit}' "
                    f"but the release artefact says '{flats[key]}'.  This is "
                    "the 284-vs-288 defect reborn; refill from the artefact.")

        # (e) bare hand counts in prose
        stripped = span.sub(">", text)
        for m in re.finditer(r'\b(\d{2,4})\s+runnable\s+(?:tutorial|case)\w*',
                             stripped, re.I):
            fail.append(
                f"{page}: bare count '{m.group(0)}' outside a data-inv span "
                "-- a hand-carried release fact, the exact form the stale "
                "'331 runnable tutorials' took.  Wrap it in a data-inv span "
                "fed by the artefact.")

    # (f) a frozen-app link must name a copy somebody declared exists
    declared = set()
    fa = ROOT / FROZEN_APPS
    if not fa.is_file():
        fail.append(FROZEN_APPS + " is missing -- without it a /vYYMM/app/ "
                    "link is checked against nothing, which is the state that "
                    "put a 404 on the homepage's release button on 2026-09-02")
    else:
        for line in fa.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                declared.add(line)
        for d in sorted(declared):
            if not (ROOT / "generated" / "releases" / (d + ".json")).is_file():
                fail.append(
                    f"{FROZEN_APPS} declares a frozen app for '{d}', which has "
                    "no release artefact -- a frozen copy of a release that "
                    "does not exist is not a thing that can be cited")
    for page in SITE_PAGES:
        src = ROOT / page
        if not src.is_file():
            continue
        for m in re.finditer(r'href="/(v\d{4})/app/"', src.read_text()):
            if m.group(1) not in declared:
                fail.append(
                    f"{page} links the frozen app at /{m.group(1)}/app/, which "
                    f"is not declared in {FROZEN_APPS}.  Nothing in this "
                    "repository PRODUCES that tree -- it is uploaded by hand to "
                    "the site repo -- so a link to it is a promise this repo "
                    "cannot keep.  Upload the copy, add the line, then link it.")

    if fail:
        print("check_release_identity: FAILED")
        for f in fail:
            print("  " + f)
        return 1

    print(
        "check_release_identity: OK -- "
        + ", ".join(a.name for a in artefacts)
        + " each records the commit its tag resolves to, survives a fresh "
        "recount from a worktree of that tag, and carries a citation equal to "
        "a fresh render of the tag's own CITATION.cff through the generator's "
        "parser (imported, not copied).  Every data-inv fallback literal in "
        f"{len(SITE_PAGES)} site source pages equals its artefact value, and "
        "no bare hand count sits beside 'runnable tutorials' in prose.  Every "
        f"frozen-app link is declared in {FROZEN_APPS} "
        f"({len(declared) or 'none'} declared), so a link to an archive that "
        "was never uploaded is refused by name.  NOT CHECKED, said plainly: "
        "the PRODUCTION HOST (this gate reads repo sources; choupo.org may "
        "differ) -- and that is exactly what the declaration cannot prove "
        "either: it records that somebody SAYS the copy was uploaded, not "
        "that it is being served.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
