"""The NanoFiltran paper's ONE case, and copies of a PART of it for a gate.

    from paper_case import CASE, part_of, op_blocks, subset_case

WHY (2026-10-24, DEV.md 4c C147).  The three former cases nanofiltran01 (code to
code), nanofiltran03 (Fig. 3) and nanofiltran02 (Table 2, Fig. 4) became ONE case,
tutorials/props/membrane/nanofiltran_geraldesAlves2008, its tables and figures
generated by system/postProcessDict.  The gates that re-run the pore at other node counts
(check_nanofiltran_reference, check_nanofiltran_paper, check_ion_diffusivity_temperature)
need a copy of ONE part of it: running the whole case at 1601 nodes would spend
minutes on ops the arm does not read, and a node count rewritten across the whole
file would also rewrite the grid study's own N.  This is the one home of which op
belongs to which part and of how a part is copied -- never a regex per gate.

A copy carries the case's constant/ and system/ WITHOUT the postProcessDict (its items name
ops the copy no longer has, and the post-processing is held by its own gate,
check_postprocessing), without `expected`, and without any run output.
"""
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CASE = ROOT / "tutorials" / "props" / "membrane" / "nanofiltran_geraldesAlves2008"


def part_of(op):
    """A: NanoFiltran's matrix (code to code); B: Fig. 3 (dye*); C: Table 2 (N<nodes>)."""
    if op.startswith("dye"):
        return "B"
    if re.fullmatch(r"N\d+", op):
        return "C"
    return "A"


def _strip_comment(line):
    i = line.find("//")
    return line if i < 0 else line[:i]


def op_blocks(text):
    """{op name: its `{ ... }` block text} of the operations list, in file order."""
    start = text.index("operations\n(\n") + len("operations\n(\n")
    blocks, depth, cur = {}, 0, []
    for line in text[start:].splitlines(keepends=True):
        code = _strip_comment(line)
        if depth == 0 and code.strip() == ");":
            break
        if depth == 0 and "{" not in code:
            continue            # a comment line between blocks
        cur.append(line)
        depth += code.count("{") - code.count("}")
        if depth == 0 and cur:
            block = "".join(cur)
            m = re.search(r"^\s*name\s+(\S+);", block, re.M)
            blocks[m.group(1)] = block
            cur = []
    return blocks


def subset_case(dst, keep, edit=None, src=CASE):
    """Copy the case into `dst` keeping only the operations named in `keep` (or for
    which keep(name) is true); `edit(text) -> text` then runs on the propsDict."""
    dst = Path(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns(
        "expected", "postProcessing", "*.csv", "postProcessDict"))
    #  the case's REFERENCE and EXPERIMENTAL csv files are inputs: copy them back
    for sub in ("reference", "experimental"):
        if (src / "constant" / sub).is_dir():
            shutil.copytree(src / "constant" / sub, dst / "constant" / sub, dirs_exist_ok=True)
    pd = dst / "system" / "propsDict"
    text = pd.read_text()
    blocks = op_blocks(text)
    want = [n for n in blocks if (keep(n) if callable(keep) else n in keep)]
    if not want:
        raise SystemExit("paper_case.subset_case: no operation kept of %s" % list(blocks))
    head = text[:text.index("operations\n(\n")]
    text = head + "operations\n(\n" + "".join(blocks[n] for n in want) + ");\n"
    if edit is not None:
        text = edit(text)
    pd.write_text(text)
    return dst
