C-----COMPUTATION OF RESIDUALS BETWEEN MODEL PREDICTIONS AND EXPERIMENTAL DATA
	FUNCTION funk(OPTVAR)
	IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      PARAMETER (NDX=205,NCX=20,NVX=(NDX+1)*(NCX+1))
	PARAMETER (NVMAX=4)
      PARAMETER (SMALL=1.0E-15)

	real*8 funk
      real*8 OPTVAR(NVMAX)
      CHARACTER*3 ACONV
C    EXPERIMENTAL / NUMERICAL NF DATA SET:
	REAL*8 Z(NCX),RS(NCX),D(NCX),CIB(NCX),KC(NCX),
     1       XM(NDX),DELTA,EPSX,RP,CX,JV,T,URF
      CHARACTER*12 NAM(NCX)
	COMMON /NFDATA/
     1 Z,RS,D,CIB,KC,XM,NAM,DELTA,EPSX,RP,CX,JV,T,
     2 EWATER,EMEMB,NC,ND,URF,ITMAX,IACT,TOL,ITMON


C    EXPERIMENTAL DATA FOR DATA FITTING
      REAL*8 JVEXP(NDX),CPEXP(NDX,NCX),CPNUM(NDX,NCX),STOL
	INTEGER NO(NVMAX),OPT(NVMAX),OBJF,IEXP,SITER
      COMMON /OPT/ JVEXP,CPEXP,CPNUM,STOL,NO,OPT,
     1             NEXP,IOPT,SITER,OBJF,IEXP

C    NUMERICAL SOLUTION FOR OUTPUT
	REAL*8 CI(NCX,NDX),CI0(NCX),PHI(NDX),KCV(NCX),KDF(NCX),
     1       KCDOT(NCX),PHIL(NCX),RESCI(NCX),RREAL(NCX),ROBS(NCX),
     2       GB(NCX),GP(NCX),PHILE(NCX),RESBAL,RESEQ,RESKC,DPHIDX
	COMMON /SOLVER/CI,CI0,PHI,KCDOT,KCV,KDF,PHIL,RESCI,RREAL,ROBS,
     1       GB,GP,PHILE,DPHIDX,RESKC,RESBAL,RESEQ,JITER

	

	DO 45, I=1,4
         IF(NO(I).EQ.1) CX=OPTVAR(I)*10. 
         IF(NO(I).EQ.2) RP=ABS(OPTVAR(I))*1.e-9
         IF(NO(I).EQ.3) DELTA=ABS(OPTVAR(I))*1.e-6
         IF(NO(I).EQ.4) EMEMB=ABS(OPTVAR(I))*100.
45    CONTINUE
      ERR1=0.
	ERR2=0.
	ERR3=0.
	ACONV="YES"
      DO 10, IEXP=1,NEXP
       JV=JVEXP(IEXP)
       CALL MODEL()
       DO 201, IC=1,NC
        ERR=ABS(CI(IC,ND)-CPEXP(IEXP,IC))/CPEXP(IEXP,IC)*100.
        ERR1=ERR1+ERR
	  IF(ERR.GT.ERR2) ERR2=ERR
        ERR3=ERR3+(CI(IC,ND)-CPEXP(IEXP,IC))**2
201     enddo
10    enddo
      ERR1=ERR1/NC/NEXP
      ERR3=SQRT(ERR3/NC/NEXP)
      IF(OBJF.EQ.1) funk=ERR1
	IF(OBJF.EQ.2) funk=ERR2
	IF(OBJF.EQ.3) funk=ERR3
      IF (JITER.GT.ITMAX) ACONV="NO"

      PRINT *,"_______________________________________________",
     1"_______________________"
	print *,"CX(MOL/M3) Rp(M)      Delta(M)   Eps.pore",
     1" Av.err(%)  Max.err(%)  CONVERGED"
      PRINT 107,CX,RP,DELTA,EMEMB,ERR1,ERR2,ACONV
107 	format(F10.2,E11.3,E11.3,F10.2,2F10.1,5X,A)
	end function funk

C**************************************************************************************
C	THIS SUBROUTINE SOLVES THE EXTENDED NERNST-PLANCK EQUATIONS 
C     INSIDE A THE ACTIVE LAYER OF A NANOFILTRATION MEMBRANE.
C
C     VARIABLES LIST:
C     A(NC,NC): 	MATRIX OF THE LINEARIZED SYSTEM OF EQUATIONS
C	B(NC,1): 	VECTOR WITH THE SOLUTION OF THE LINEARIZED SYSTEM OF EQUATIONS
C     	DATA STRUCTURE:
C     	1...................ND: CI(1,ND)
C     	ND+1..............2*ND: CI(2,ND)
C     	2*ND+1............3*ND: CI(3,ND)
C     	......................
C     	(NC-1)*ND+1......NC*ND: CI(NC,ND)
C     	NC*ND+1......(NC+1)*ND: PHI(ND)
C		(NC+1)*ND+1..(NC+1)*(ND+1): CI0(1..NC),DPHIDX
C     CI(NC,ND):  CONCENTRATION OF A ION IN A NODE INSIDE THE MEMBRANE [MOL/M3]
C	CI0(NC):	IONS CONCENTRATION IN THE FEED-SIDE/MEMBRANE INTERFACE [MOL/M3]
C     CIB(NC):    IONS CONCENTRATION IN THE FEED COMPARTMENT [MOL/M3]
C     CX:         MEMBRANE CHARGE [MOL/M3]
C     D(NC):      IONS DIFFUSIVITY IN BULK SOLUTION [M2/S]
C     DELTA:      THICKNESS OF THE MEMBRANE ACTIVE LAYER [M]
C	DPHIDX:	ELECTRIC POTENTIAL GRADIENT NEAR THE FEED-DOLUTION/MEMBRANE INTERFACE
C     DM(NC):     IONS DIFFUSIVITY IN THE MEMBRANE ACTIVE LAYER [M2/S]
C	EMEMB:	DIELECTRIC CONSTANT WITHIN THE MEMBRANE ACTIVE LAYER 
C     EPSX:       MESH EXPANSION COEFFICIENT, EXPANDING FROM MEMBRANE INTERFACES TO THE MEMBRANE CENTER
C	EWATER:	DIELECTRIC CONSTANT OF THE WATER
C	F:		FARADAY CONSTANT [96500 C/EQ)
C     ITMAX:	MAXIMUM NUMBER OF ITERATIONS
C     JV:         PERMEATE FLUX [M/S]
C	KC(NC):	MASS TRANSFER COEFFICIENT FOR THE SEVERAL IONS [M/S]
C	KCDOT(NC):	MASS TRANSFER COEFFICIENT FOR THE SEVERAL IONS CORRECTED TO TAKE INTO ACCOUNT THE PERMEATE FLUX [M/S]
C	KDF(NC):	HINDRANCE FACTOR FOR DIFFUSION FOR THE SEVERAL IONS
C	KCV(NC):	HINDRANCE FACTOR FOR CONVECTION FOR THE SEVERAL IONS
C	KF:		F/R/T [C/J]
C	LDA	 	AUXILIARY VARIABLE FOR THE LINEAR SOLVER SGESV 
C	LDB		AUXILIARY VARIABLE FOR THE LINEAR SOLVER SGESV 
C	NAM(NC):	NAME OF THE IONS USED IN THE SIMULATION
C     NC: 		NUMBER OF IONS
C	NCX: 		MAXIMUM NUMBER OF IONS
C     NDX:	      MAXIMUM NUMBER OF DISCRETIZATION POINTS INSIDE THE MEMBRANE
C     ND: 		NUMBER OF DISCRETIZATION POINTS INSIDE THE MEMBRANE
C	NV:		NUMBER OF VARIABLES OF THE LINEAR PROBLEM (ND+1)*(NC+1)
C	NVX:		MAXIMUM NUMBER OF VARIABLES OF THE LINEAR PROBLEM (NDX+1)*(NCX+1)
C	NRHS:		AUXILIARY VARIABLE FOR THE LINEAR SOLVER SGESV
C     R: 		MOLAR GAS CONSTANT [8.314 J/MOL/K]
C	RESBAL:	NORMALIZED ELECTRONEUTRALITY RESIDUALS 
C	RESEQ:	NORMALIZED EQUILIBRIUM RESIDUALS 
C	RESKC:	NORMALIZED FEED-SOLUTION/ MEMBRANE MASS TRANSFER RESIDUALS 
C     ROBS(NC):	OBSERVED REJECTION COEFFICIENT OF THE SEVERAL IONS
C     RP:         MEMBRANE PORE RADIUS [M]
C     RREAL(NC):	REAL REJECTION COEFFICIENT OF THE SEVERAL IONS
C     RS(NC):	RADIUS OF THE IONS [M]
C	SMALL:	VERY SMALL VALUE PARAMETER (1.E-15) 
C     T:		TEMPERATURE [K]
C	TOL:		MAXIMUM TOLERABLE NORMALIZED RESIDUALS FOR CONVERGENCE CRITERIA
C     PHI(ND):	ELECTRICAL POTENCIAL PROFILE [VOLT]
C	PHIL(NC)	PARTITION FACTOR DUE TO STERIC EXCLUSION FOR THE SEVERAL IONS (C MEMBRANE PHASE/C BULK SOLUTION)
C	PHILE(NC)	PARTITION FACTOR DUE TO DIELECTRIC EXCLUSION FOR THE SEVERAL IONS (C MEMBRANE PHASE/C BULK SOLUTION)
C	U(NC):	ION MOBILITY INSIDE THE MEMBRANE ACTIVE LAYER [C.S/KG]
C	URF:		UNDER-RELAXATION FACTOR
C     XM(ND):     NODE POSITION [M]
C 			NODES:
C     		1    2   ...   ND-1 ND
C     		1 IS THE FEED MEMBRANE SURFACE
C     		ND-1 IS THE PERMEATE MEMBRANE SURFACE
C     		ND IS THE PERMEATE
C     Z(NC):	CHARGE OF THE IONS
	
      SUBROUTINE MODEL()
	IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      PARAMETER (NDX=205,NCX=20,NVX=(NDX+1)*(NCX+1))
      PARAMETER (NVMAX=4)
      PARAMETER (SMALL=1.E-15)

C    EXPERIMENTAL / NUMERICAL NF DATA SET:
	REAL*8 Z(NCX),RS(NCX),D(NCX),CIB(NCX),KC(NCX),
     1       XM(NDX),DELTA,EPSX,RP,CX,JV,T,URF
      CHARACTER*12 NAM(NCX)
	COMMON /NFDATA/
     1 Z,RS,D,CIB,KC,XM,NAM,DELTA,EPSX,RP,CX,JV,T,
     2 EWATER,EMEMB,NC,ND,URF,ITMAX,IACT,TOL,ITMON


C    NUMERICAL SOLUTION FOR OUTPUT
	REAL*8 CI(NCX,NDX),CI0(NCX),PHI(NDX),KCV(NCX),KDF(NCX),
     1       KCDOT(NCX),PHIL(NCX),RESCI(NCX),RREAL(NCX),ROBS(NCX),
     2       GB(NCX),GP(NCX),PHILE(NCX),RESBAL,RESEQ,RESKC,DPHIDX
	COMMON /SOLVER/CI,CI0,PHI,KCDOT,KCV,KDF,PHIL,RESCI,RREAL,ROBS,
     1       GB,GP,PHILE,DPHIDX,RESKC,RESBAL,RESEQ,JITER

C    EXPERIMENTAL DATA FOR DATA FITTING
      REAL*8 JVEXP(NDX),CPEXP(NDX,NCX),CPNUM(NDX,NCX),STOL
	INTEGER NO(NVMAX),OPT(NVMAX),OBJF,IEXP,SITER
      COMMON /OPT/ JVEXP,CPEXP,CPNUM,STOL,NO,OPT,
     1             NEXP,IOPT,SITER,OBJF,IEXP

C	AUXILIARY VARIABLES
      REAL*8 DM(NCX),U(NCX),F,R,KF,KE1,KE2,KPHI,DX
	INTEGER I,J,JITER,ITMAX,ITMON

C	LAPACK SUBROUTINE VARIABLES
      INTEGER    IPIV( NVX)
      REAL*8     A( NVX, NVX), B(NVX,1)
      INTEGER    INFO, LDA, LDB, N, NRHS      

C	PROBLEM DIMENSIONS FOR LAPACK SUBROUTINE
	NV=(ND+1)*(NC+1)
	NRHS = 1
      LDA = NVX
	LDB = NVX

C     AUXILIARY VARIABLES/PARAMETERS
	F=96500.0
	R=8.314
      KF=F/R/T

C	MESH GENERATION
      IF (EPSX.LE.1.0) EPSX=1.0000001
      XM(ND)=DELTA
      XM(ND-1)=DELTA
      DX=DELTA/2./((1.-EPSX**((ND-2)/2.))/(1.-EPSX))
      DO  523  I=1,ND-3
       XM(ND-I-1)=XM(ND-I)-DX 
	 DX=EPSX*DX  	
523   CONTINUE
      XM(1)=0.
      DO  5123  I=1,ND/2
       XM(I)=DELTA-XM(ND-I) 
	 DX=EPSX*DX  	
5123   CONTINUE


C	MASS TRANSFER COEFFICIENT CORRECTION
	DO 8236, IC=1,NC
        KPHI=JV/KC(IC)
	  KCDOT(IC)=KC(IC)*(KPHI+(1.+0.26*KPHI**1.4)**(-1.7))
8236  CONTINUE

C	COMPUTATION OF HINDRANCE FACTORS (with Cross-Sectional Averaging): Ind. Eng. Chem. Res., Vol. 45, No. 21, 2006 6955
C	AND STERIC PARTITION COEFFICIENTS
	DO 385 IC=1,NC
         RL=RS(IC)/RP
         IF (RL.GE.1.0) THEN
           KDF(IC)=1.E-8
	     KCV(IC)=1.E-8
	   ELSE
	    IF (RL.LE.0.95)KDF(IC)=(1.+9./8.*RL*DLOG(RL)
     1     -1.56034*RL+0.528155*RL**2+1.91521*RL**3
     2     -2.81903*RL**4+0.270788*RL**5+1.10115*RL**6
     3     -0.435933*RL**7)/(1.-RL)**2
	    IF (RL.GT.0.95)KDF(IC)=0.984*((1.-RL)/RL)**(5./2.)
	    KCV(IC)=(1.+3.867*RL-1.907*RL**2-0.834*RL**3)/
     1            (1+1.867*RL-0.741*RL**2)
         END IF

	   DM(IC)=D(IC)*KDF(IC)
	   U(IC)=DM(IC)*F/R/T

C     STERIC EXCLUSION	
	   PHIL(IC)=(1.-RL)**2
         IF (RL.GE.1.0) PHIL(IC)=SMALL

C     DIELECTRIC EXCLUSION: 
         DH= 6.95E-5*Z(IC)**2/RS(IC)*(1./EMEMB-1./EWATER)
         PHILE(IC)=EXP(-DH/R/T)
385   CONTINUE

C     MATRIX INITIZALIZATION
	DO 11,I=1,NV
        B(I,1)=0.0
        DO 12,J=1,NV
           A(I,J)=0.0
12	  CONTINUE
11    CONTINUE


C     ITERATION CYCLE
	IF (ITMON.NE.0) THEN
	PRINT *,"************* SOLVER MONITORING *************"
      IF (IOPT.EQ.2)
     1PRINT *,"************* EXPERIMENTAL POINT = ",IEXP
      WRITE (*,356) "ITER.","RESKC ","RESBAL ","RESEQ ",
     1      " ",(NAM(IC),IC=1,NC)
	END IF
356   FORMAT(4A8,6A8)
	DO 100, JITER=1,ITMAX
C	COEFFICIENTS ASSEMBLY
C     (ND-2)*(NC) EQS: N-P DISCRETIZATION EQUATIONS
      IEQ=0
      DO 255,IC=1,NC
	DO 25,I=1,ND-2
        DX=XM(I+1)-XM(I)
        IEQ =IEQ+1
	  A(IEQ,(IC-1)*ND+I)=
     1    DM(IC)/DX+0.5*JV*KCV(IC)
     2   -0.5*Z(IC)*U(IC)*(PHI(I+1)-PHI(I))/DX
	  A(IEQ,(IC-1)*ND+I+1)=
     1    -DM(IC)/DX+0.5*JV*KCV(IC)
     2    -0.5*Z(IC)*U(IC)*(PHI(I+1)-PHI(I))/DX
	  A(IEQ,NC*ND+I)=
     1    Z(IC)*U(IC)*0.5*(CI(IC,I+1)+CI(IC,I))/DX
	  A(IEQ,NC*ND+I+1)=
     1    -Z(IC)*U(IC)*0.5*(CI(IC,I+1)+CI(IC,I))/DX
	  A(IEQ,IC*ND)=
     1    -JV
        B(IEQ,1)=
     1    -Z(IC)*U(IC)*0.5*(CI(IC,I+1)+CI(IC,I))
     2    *(PHI(I+1)-PHI(I))/DX
25	CONTINUE
255   CONTINUE

C     (ND) EQS: CHARGE BALANCE
      DO 29, I=1,ND
        IEQ =IEQ+1
        DO 290,IC=1,NC
          A(IEQ,(IC-1)*ND+I)=Z(IC)
290     CONTINUE
        IF (I.NE.ND) THEN
           B(IEQ,1)=-CX
        END IF
29    CONTINUE

C	(NC) EQS: FEED-MEMBRANE EQUILIBRIUM
C	 DAVIES MODEL PARAMETERS AND IONIC FORCE
        ABULK=1.825E6*(1./EWATER**3/T**3)**0.5
	  AMEMB=1.825E6*(1./EMEMB**3/T**3)**0.5
        RIFB=0.
	  RIFM=0.
        DO 1928, IC=1,NC
          RIFB=RIFB+0.5*Z(IC)**2*CI0(IC)/1000.
          RIFM=RIFM+0.5*Z(IC)**2*CI(IC,1)/1000.
1928    CONTINUE


      DO 569, IC=1,NC
        IEQ =IEQ+1
	  GAMAB=DEXP(-ABULK*Z(IC)**2*(RIFB**0.5/(1.+RIFB**0.5)
     C             -0.3*RIFB))
 	  IF (Z(IC).EQ.0) GAMAB=DEXP(0.1*RIFB)
	  GAMABM=DEXP(-AMEMB*Z(IC)**2*(RIFM**0.5/(1.+RIFM**0.5)
     C             -0.3*RIFM))
 	  IF (Z(IC).EQ.0) GAMABM=DEXP(0.1*RIFM)
	  GB(IC)=GAMAB/GAMABM

        IF (IACT.EQ.0) GB(IC)=1.0
          KE1=PHIL(IC)*PHILE(IC)*GB(IC)*
     1        DEXP(-Z(IC)*KF*PHI(1))
	    A(IEQ,(IC-1)*ND+1)=1.0
          A(IEQ,NC*ND+1)=CI0(IC)*Z(IC)*KF*KE1
	    B(IEQ,1)=CI0(IC)*KE1*(1.0+Z(IC)*KF*PHI(1))
569   CONTINUE


C	(NC) EQS: MEMBRANE-PERMEATE EQUILIBRIUM 
        RIFB=0.
	  RIFM=0.
        DO 1929, IC=1,NC
          RIFB=RIFB+0.5*Z(IC)**2*CI(IC,ND)/1000.
          RIFM=RIFM+0.5*Z(IC)**2*CI(IC,ND-1)/1000.
1929    CONTINUE

      DO 579,IC=1,NC
         IEQ =IEQ+1
	  GAMAP=DEXP(-ABULK*Z(IC)**2*(RIFB**0.5/(1.+RIFB**0.5)
     C             -0.3*RIFB))
 	  IF (Z(IC).EQ.0) GAMAP=DEXP(0.1*RIFB)
	  GAMAPM=DEXP(-AMEMB*Z(IC)**2*(RIFM**0.5/(1.+RIFM**0.5)
     C             -0.3*RIFM))
 	  IF (Z(IC).EQ.0) GAMAPM=DEXP(0.1*RIFM)
	  GP(IC)=GAMAP/GAMAPM
        IF (IACT.EQ.0) GP(IC)=1.0
	    KE2=PHIL(IC)*PHILE(IC)*GP(IC)*
     1        DEXP(Z(IC)*KF*(PHI(ND)-PHI(ND-1)))
  	    A(IEQ,ND*IC-1)=1.0/CI(IC,ND)
          A(IEQ,ND*IC)=-KE2/CI(IC,ND)
          A(IEQ,ND*(NC+1)-1)=Z(IC)*KF*KE2
          A(IEQ,ND*(NC+1))=-Z(IC)*KF*KE2
	    B(IEQ,1)=KE2*(-Z(IC)*KF*(PHI(ND)-PHI(ND-1)))
579   CONTINUE


C	(NC) EQS: FEED-MEMBRANE MASS TRANSFER RESISTANCE
	DO 1725, IC=1,NC
	  IEQ=IEQ+1
        A(IEQ,ND*(NC+1)+IC)=KCDOT(IC)-JV
	  A(IEQ,IC*ND)=JV
	  A(IEQ,(ND+1)*(NC+1))=Z(IC)*KF*D(IC)*CI0(IC)
	  B(IEQ,1)=KCDOT(IC)*CIB(IC)
1725	CONTINUE
C	FEED-MEMBRANE INTERFACE CHARGE BALANCE
      IEQ=IEQ+1
      DO 2910,IC=1,NC
         A(IEQ,ND*(NC+1)+IC)=Z(IC)
2910  CONTINUE

C **************************************************** 
C     LINEAR SOLVER
C **************************************************** 
      CALL SGESV(NV,NRHS,A,LDA,IPIV,B,LDB,INFO )
                                                                        
C ****************************************************
C     UNDER-RELAXATION
C **************************************************** 
	DO 56, I=1,ND
        DO 576, IC=1,NC
          DCI=(B((IC-1)*ND+I,1)-CI(IC,I))/(CI(IC,I))
          IF (ABS(DCI).GT.1.0) DCI=ABS(DCI)/DCI
          CI(IC,I)=CI(IC,I)*(1.+URF*DCI)
576     CONTINUE
        PHI(I)=PHI(I)+URF*(B(NC*ND+I,1)-PHI(I))
        IF(ABS(PHI(I)).GT.5.) PHI(I)=.0
56    CONTINUE
      DO 5763, IC=1,NC
        DCI=(B(ND*(NC+1)+IC,1)-CI0(IC))/CI0(IC)
        IF (ABS(DCI).GT.1.0) DCI=ABS(DCI)/DCI
        CI0(IC)=CI0(IC)*(1.+URF*DCI)
5763  CONTINUE
	DPHIDX=DPHIDX+URF*(B((ND+1)*(NC+1),1)-DPHIDX)
      IF (ABS(DPHIDX).GT.500.) DPHIDX=DPHIDX/ABS(DPHIDX)
C ****************************************************
C     MATRIX RE-INITIALIZATION
C ****************************************************
      DO 1191 I=1,NV
         B(I,1)=0.0
         DO 1181 J=1,NV
            A(I,J)=0.0
1181   CONTINUE
1191   CONTINUE
C ****************************************************      
C	RESIDUES COMPUTATION:
C **************************************************** 
	DO 1956 IC=1,NC
	  RESCI(IC)=0.
1956  CONTINUE
      RESEQ=0.
	RESBAL=0.
	DO 146 I=1,ND-2
       DO 1146 IC=1,NC
        DX=XM(I+1)-XM(I)
        RESCI(IC)=RESCI(IC)+DABS(-DM(IC)*(CI(IC,I+1)-CI(IC,I))/DX
     1  -Z(IC)*U(IC)*0.5*(CI(IC,I+1)+CI(IC,I))*(PHI(I+1)-PHI(I))/DX
     2  +JV*KCV(IC)*0.5*(CI(IC,I+1)+CI(IC,I))-JV*CI(IC,ND))
1146   CONTINUE
       SUMC=0.
        DO 1249 IC=1,NC
          SUMC=SUMC+Z(IC)*CI(IC,I)
1249    CONTINUE
       RESBAL=RESBAL+DABS(SUMC+CX)
146   CONTINUE
      DO 1778 IC=1,NC 
1778     IF (PHIL(IC).LE.SMALL) RESCI(IC)=0.

     
      SUMC=0.
      SUMCP=0.
      SUMCTB=0.
      DO 1623 IC=1,NC
        SUMC=SUMC+Z(IC)*CI(IC,ND-1)
        SUMCP=SUMCP+Z(IC)*CI(IC,ND)
        SUMCTB=SUMCTB+DABS(Z(IC)*CIB(IC)) 
1623  CONTINUE
      RESBAL= RESBAL+DABS(SUMC+CX)+DABS(SUMCP)
	RESBAL= RESBAL/(SUMCTB+DABS(CX))

      RJT=0.0
      DO 7694 IC=1,NC
	  RJT=RJT+dabs(JV*CI(IC,ND))
7694  CONTINUE
      DO 7684 IC=1,NC
	  RESCI(IC)=RESCI(IC)/RJT
7684  CONTINUE



C     COMPUTE KC RESIDUAL ONLY IF POLARIZATION IS ASSUMED
      IF (KC(1).LT.10.) THEN
      RESKC=0.
      DO 6861, IC=1,NC
        RESKC=RESKC+ABS(JV*CI(IC,ND)+KCDOT(IC)*(CI0(IC)-CIB(IC))
     1       +Z(IC)*KF*D(IC)*CI0(IC)*DPHIDX-JV*CI0(IC))/RJT
6861   CONTINUE
      ELSE
         RESKC=0.
      END IF
      DO 742 IC=1,NC
         IF(PHIL(IC).GT.1.0E-10) THEN
          KE1=PHIL(IC)*PHILE(IC)*GB(IC)*
     1        DEXP(-Z(IC)*KF*PHI(1))
          KE2=PHIL(IC)*PHILE(IC)*GP(IC)*
     1        DEXP(-Z(IC)*KF*(PHI(ND-1)-PHI(ND)))
          RESEQ=RESEQ+DABS(CI(IC,1)/CI0(IC)/KE1-1.)
         IF (CI(IC,ND).GT.1.0E-11) 
     1       RESEQ=RESEQ+DABS(CI(IC,ND-1)/CI(IC,ND)/KE2-1.)
         END IF

742   CONTINUE

C **************************************************** 
C     SOLVER MONITORING 
C ****************************************************
	IF (ITMON.NE.0) THEN
       IF (MOD(JITER,ITMON).EQ.0) THEN
         WRITE (6,1999) JITER,RESKC,RESBAL,RESEQ,
     1			(RESCI(IC),IC=1,NC)	
       END IF
	END IF
1999  FORMAT (I7,1x,8(f8.4,1x),8x,8(f8.4,1x))
C **************************************************** 
C     CONVERGENCE CRITERIA
C **************************************************** 
      RM=0.
      DO 159 IC=1,NC
159      IF(RESCI(IC).GT.RM) RM=RESCI(IC)
	IF (DMAX1(RM,RESBAL,RESKC,RESEQ).LT.TOL) THEN
         GO TO 107
      END IF

100   CONTINUE
107	CONTINUE

C     COMPUTE ROBS AND RREAL
	DO 1278 IC=1,NC
        RREAL(IC)=(CI0(IC)-CI(IC,ND))/CI0(IC)
        ROBS(IC) =(CIB(IC)-CI(IC,ND))/CIB(IC)
1278  CONTINUE

	END

