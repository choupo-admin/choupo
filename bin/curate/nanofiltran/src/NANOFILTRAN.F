C-----READ PROBLEM DATA
      CALL DATAIN()
C-----INITIZALIZE SOLUTION PROFILE
      CALL INIT()
C-----NORMAL OPTION
      IF (IOPT.EQ.1) THEN
         CALL MODEL()
         CALL OUTP()
      END IF

C-----OPTIMIZATION OPTION
      IF (IOPT.EQ.2) THEN
        NDIM=0
        IF(OPT(1).NE.0) THEN
          NDIM=NDIM+1
          NO(NDIM)=1
        END IF
        IF(OPT(2).NE.0) THEN
          NDIM=NDIM+1
          NO(NDIM)=2
        END IF
        IF(OPT(3).NE.0) THEN
          NDIM=NDIM+1
          NO(NDIM)=3
        END IF
        IF(OPT(4).NE.0) THEN
          NDIM=NDIM+1
          NO(NDIM)=4
        END IF

C----INITIAL VALUE OF THE OPTIMIZATION VARIABLES (NORMALIZED)
        DO 107,I=1,NDIM
            IF (NO(I).EQ.1) OPTVAR(I)=CX/10.
            IF (NO(I).EQ.2) OPTVAR(I)=RP/1.E-9
            IF (NO(I).EQ.3) OPTVAR(I)=DELTA/1.e-6
		IF (NO(I).EQ.4) OPTVAR(I)=EMEMB/100.
107	  CONTINUE
	
C----minimize deviations between predicted and experimental rejections
	  CALL SIMPLEX(OPTVAR,NDIM,STOL,FUNK,SITER)
      
C----COMPUTE OPTIMAL PERMEATE ION CONCENTRATIONS
        DO 456, IEXP=1,NEXP
          JV=JVEXP(IEXP)
          CALL MODEL()
          DO 124,IC=1,NC
            CPNUM(IEXP,IC)=CI(IC,ND)
124       CONTINUE
456     CONTINUE

C----OUTPUT OF BEST FITTING PARAMETERS AND PREDICTIONS
      IO=66
      OPEN (UNIT=66,FILE='OUTPUT.XLW',STATUS='OLD')

	WRITE(IO,*)"___________________________________________"
      WRITE(IO,*)"  BEST FITTING PARAMETERS AND PREDICTIONS"
	WRITE(IO,*)"___________________________________________"

      DO 874,I=1,4
          IF (NO(I).EQ.1) WRITE(IO,*)
     1    "MEMBRANE CHARGE=",TB,OPTVAR(I)*10.,TB,"mol/m3"
          IF (NO(I).EQ.2) WRITE(IO,*)
     1    "PORE RADIUS",TB,OPTVAR(I)*1E-9,tb,"m"
          IF (NO(I).EQ.3) WRITE(IO,*)
     1    "MEMBRANE THICKNESS(M)=",TB,OPTVAR(I)*1.E-6
          IF (NO(I).EQ.4) WRITE(IO,*)
     1    "PORE DIELECTRIC CONSTANT",TB,OPTVAR(I)*100.
874   CONTINUE
	ERRMIN=FUNK(OPTVAR)
	WRITE(IO,*)"AVERAGE REL.ERROR=",TB,ERRMIN,"%"

	WRITE(IO,*)"PREDICTED PERMEATE ION CONCENTRATIONS:"
      WRITE(IO,4679)TB,"JV(M/S)",(TB,NAM(IC),IC=1,NC)

      DO 1235,IEXP=1,NEXP
          WRITE(IO,4678) TB,JVEXP(IEXP),(TB,CPNUM(IEXP,IC),IC=1,NC)
1235  CONTINUE
4678  FORMAT(22(A,E12.3))
4679  FORMAT(50A)

C----OUTPUT CONCENTRATION PROFILES FOR EVERY EXPERIMENTAL POINT
	WRITE(IO,*)"**********************************************"
	WRITE(IO,*)"****SIMULATION RESULTS FOR EACH EXPERIMENT****"
	WRITE(IO,*)"**********************************************"
        DO 4566, IEXP=1,NEXP
          JV=JVEXP(IEXP)
          CALL MODEL()
          DO 1264,IC=1,NC
            CPNUM(IEXP,IC)=CI(IC,ND)
1264       CONTINUE
	WRITE(IO,*)"**********************************************"
	    WRITE(IO,*)"*** EXPERIMENTAL POINT: ",IEXP
	WRITE(IO,*)"**********************************************"
          CALL OUTP()
4566     CONTINUE

	END IF
      END
