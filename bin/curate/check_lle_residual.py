"""check_lle_residual -- bubble temperatures AND tie lines fitted in ONE fit.

    bin/curate/check_lle_residual.py

WHY THIS EXISTS (DEV.md 4c C226 A1, 2026-11-05).  `fitParameters` gained a
residual kind, `T_bubble+LLE`, that adds measured BINODAL compositions to the
bubble-temperature rows in a single least-squares problem (src/propertyOps/
LleResidual.H).  A partially miscible pair (water + 1-butanol) has two kinds
of evidence about one pair of parameters, and a pair regressed to the first
alone splits the liquid wherever it likes (C16 slice 2).  The dangerous
failures of the new kind are not errors, they are plausible numbers:

  * a model that predicts ONE liquid where two were MEASURED must not get a
    made-up residual or be skipped in silence;
  * a start that splits nothing gives the penalty no gradient, and the fit
    "converges" where it began;
  * kelvins and mole fractions summed unweighted converge and mean nothing.

WHAT IT CHECKS, on tutorials/props/curation/curate13_synthetic_lle_butanol_water
(SYNTHETIC: the data are generated by the engine from KNOWN parameters, said
in every dataset header and by the engine at run time):

  (a) RECOVERY.  Both starts of the shipped case return the generating b_ij
      and b_ji (read from the datasets' own headers, not from this file) to
      1e-5 relative, converge, publish the verdict `validated`, fit 8 tie
      lines and hold out 5, with no penalised tie line.  Zero-noise
      recovery: any deviation is the residual's arithmetic.
  (b) THE TIE LINES ARE INDEPENDENT OF THE ENGINE THAT FITS THEM.  Each tie
      line of the fit and held-out datasets is recomputed here from the
      generating parameters by the Gibbs-energy-of-mixing lower convex hull
      (check_regressed_pairs.nrtl_liquid_split, the NRTL equation written
      out, no call into the engine) and must agree with the dataset to the
      hull's grid (1e-3).  An auditor that reuses the auditee's arithmetic
      checks nothing.
  (c) THE REFUSALS FIRE, each by name, on probe cases this gate BUILDS (a
      guard whose only case satisfies it is a guard nothing tests -- the
      shipped witness satisfies every one of them):
        - an IDEAL start (all zero): ONE liquid at every tie line;
        - `weighting equal` beside tie lines;
        - no `liquidLiquid { sigma }`;
        - held-out tie lines with no `maxLLE` band;
        - a package with ONE liquid phase (`formulation gammaPhi`);
        - `kind LLE` alone (T_bubble+LLE needs the bubble rows).
  (d) A MISSING SPLIT IS NAMED, AND IS A MISS.  A held-out tie line at 520 K
      (a GATE FIXTURE, labelled; not data) where the fitted pair is one
      liquid: the run completes, says on stderr that two liquids were
      MEASURED and the model predicts ONE, publishes
      `lle_penalised_ties_heldout 1`, and its verdict is `notValidated`.

WHAT IT DOES NOT CHECK.  Any real water + 1-butanol measurement (none is
in this tree); the real binodal's asymmetry; the dilute-branch accuracy
below the flash's 1e-4 simplex floor (the engine advises it); the analytic
Jacobian (not built: the finite-difference one is measured fast, C226).

SABOTAGES (by hand, 2026-11-05; see DEV.md C226): listed in the entry.
"""
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_regressed_pairs as crp  # noqa: E402

PROPS = ROOT / "choupoProps"
CASE = ROOT / "tutorials" / "props" / "curation" / "curate13_synthetic_lle_butanol_water"
PREFIX = "equilibrium.liquid.activityModel.binaryParameters.nButanol-water"


def run(case):
    p = subprocess.run([str(PROPS), "."], cwd=str(case), capture_output=True,
                       text=True, timeout=900)
    return p.returncode, p.stdout + p.stderr


def diagnostics(out):
    m = re.search(r"<<<Choupo:result-begin>>>(.*?)<<<Choupo:result-end>>>", out, re.S)
    if not m:
        return {}
    js = json.loads(m.group(1))
    return {op["name"]: (op.get("diagnostics", {}), op.get("curation", {}))
            for op in js.get("operationResults", [])}


def truth():
    """The generating parameters, from the datasets' OWN headers."""
    t = (CASE / "constant" / "experiments" / "nButanol-water-lle-synthetic-fit.dat").read_text()
    m = re.search(r"b_ij\s*=\s*([0-9.]+)\s*K,\s*b_ji\s*=\s*([0-9.]+)\s*K", t)
    return float(m.group(1)), float(m.group(2))


def ties_of(path):
    t = path.read_text()
    d = t[t.index("\ndata"):]
    rows = [l.split() for l in d.splitlines() if l.strip() and l.strip()[0].isdigit()]
    return [(float(a), float(b), float(c)) for a, b, c in rows]


def copy_case(tmp, name):
    dst = tmp / name
    shutil.copytree(CASE, dst)
    return dst


def edit(case, rel, old, new, count=1):
    p = case / rel
    s = p.read_text()
    if s.count(old) < 1:
        raise RuntimeError(f"probe edit: {old!r} not found in {rel}")
    p.write_text(s.replace(old, new, count))


def only_first_op(case):
    p = case / "system" / "propsDict"
    s = p.read_text()
    i = s.index("    {\n        name        fit_mixed_start2")
    p.write_text(s[:i] + ");\n")


def main():
    if not PROPS.exists():
        print("check_lle_residual: FAILED\n  choupoProps is not built -- the "
              "gate cannot run, so it must not pass")
        return 1
    fails = []
    tmp = Path(tempfile.mkdtemp(prefix="choupo-lle-"))
    try:
        # ---- (a) recovery -------------------------------------------------
        b_ij, b_ji = truth()
        work = copy_case(tmp, "shipped")
        rc, out = run(work)
        diag = diagnostics(out)
        if rc != 0 or not diag:
            fails.append(f"(a) the shipped case exited {rc}: {out[-400:]}")
        for op in ("fit_mixed", "fit_mixed_start2"):
            d, cur = diag.get(op, ({}, {}))
            for k, want in (("fit.0.value", b_ij), ("fit.1.value", b_ji)):
                got = d.get(k)
                if got is None or abs(got - want) > 1e-5 * abs(want):
                    fails.append(f"(a) {op}: {k} = {got}, generating value {want} "
                                 "(tolerance 1e-5 relative) -- the tie-line + "
                                 "bubble residual no longer recovers known parameters")
            for k, want in (("converged", 1), ("lle_n_ties", 8),
                            ("lle_n_ties_heldout", 5), ("lle_penalised_ties", 0),
                            ("lle_penalised_ties_heldout", 0)):
                if d.get(k) != want:
                    fails.append(f"(a) {op}: {k} = {d.get(k)}, expected {want}")
            if cur.get("verdict") != "validated":
                fails.append(f"(a) {op}: verdict {cur.get('verdict')!r}, expected validated")
        if "GENERATED, not measured" not in out:
            fails.append("(a) the run did not announce that its evidence is "
                         "GENERATED, not measured -- a synthetic witness must say so")

        # ---- (b) independent tie lines -------------------------------------
        exp = CASE / "constant" / "experiments"
        n_ties = 0
        for f in ("nButanol-water-lle-synthetic-fit.dat", "nButanol-water-lle-synthetic-validation.dat"):
            for T, xlo, xhi in ties_of(exp / f):
                # NRTL with i = nButanol, j = water; the hull's x1 is nButanol
                cut = crp.nrtl_liquid_split(T, 0.0, b_ij, 0.0, b_ji, 0.30)
                n_ties += 1
                if cut is None or abs(cut[0] - xlo) > 1e-3 or abs(cut[1] - xhi) > 1e-3:
                    fails.append(f"(b) {f}: tie line at {T} K is ({xlo}, {xhi}) in the "
                                 f"dataset and {cut} from the independent convex hull")

        # ---- (c) refusals, each by name ------------------------------------
        probes = (
            ("idealStart", "ONE liquid at all",
             lambda c: (edit(c, "system/propsDict", "initial 0;  min", "initial 0;  min"),
                        edit(c, "system/propsDict", "initial 1000;", "initial 0;"),
                        edit(c, "constant/thermoPhysPropDict", "b_ji 1000;", "b_ji 0;"))),
            ("weightingEqual", "needs `weighting uncertainty;`",
             lambda c: edit(c, "system/propsDict", "weighting   uncertainty;", "weighting   equal;")),
            ("noSigma", "`residual { liquidLiquid",
             lambda c: edit(c, "system/propsDict", "liquidLiquid\n", "liquidLiquidX\n")),
            ("noBand", "`acceptance { maxLLE <x>; }` is not",
             lambda c: edit(c, "system/propsDict", "maxLLE  0.01;", "")),
            ("oneLiquid", "carries ONE liquid phase",
             lambda c: edit(c, "constant/thermoPhysPropDict", "formulation gammaGamma;", "formulation gammaPhi;")),
            ("kindLLEalone", "kind must be T_bubble",
             lambda c: edit(c, "system/propsDict", "kind        T_bubble+LLE;", "kind        LLE;")),
        )
        for name, needle, mutate in probes:
            c = copy_case(tmp, "probe-" + name)
            only_first_op(c)
            try:
                mutate(c)
            except RuntimeError as e:
                fails.append(f"(c) {name}: {e}")
                continue
            if name == "oneLiquid":
                # the gammaPhi grammar carries no liquidPhases list
                edit(c, "constant/thermoPhysPropDict",
                     "    liquidPhases\n    (\n        { name liquid1; }\n        { name liquid2; }\n    );\n", "")
            rc, o = run(c)
            if rc == 0:
                fails.append(f"(c) {name}: the run EXITED 0 -- it must refuse")
            elif needle not in o:
                fails.append(f"(c) {name}: it failed (exit {rc}) but not by the "
                             f"expected name {needle!r}: {o[-300:]}")

        # ---- (d) a missing split is named and is a miss -----------------------
        c = copy_case(tmp, "probe-heldOutOneLiquid")
        only_first_op(c)
        vf = c / "constant" / "experiments" / "nButanol-water-lle-synthetic-validation.dat"
        s = vf.read_text()
        s = s.replace("data\n(\n", "data\n(\n      520  0.2  0.6\n", 1)   # GATE FIXTURE, not data
        vf.write_text(s)
        rc, o = run(c)
        d, cur = diagnostics(o).get("fit_mixed", ({}, {}))
        if rc != 0:
            fails.append(f"(d) the held-out-one-liquid probe exited {rc}: {o[-300:]}")
        else:
            if "two liquids were MEASURED" not in o or "predicts ONE" not in o:
                fails.append("(d) the run did not SAY that two liquids were measured "
                             "where the model predicts one")
            if d.get("lle_penalised_ties_heldout") != 1:
                fails.append(f"(d) lle_penalised_ties_heldout = {d.get('lle_penalised_ties_heldout')}, expected 1")
            if cur.get("verdict") != "notValidated":
                fails.append(f"(d) verdict {cur.get('verdict')!r}, expected notValidated "
                             "(a missing split is a MISS, never a skip)")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if fails:
        print("check_lle_residual: FAILED")
        for f in fails:
            print("  - " + f)
        return 1
    print("check_lle_residual: OK -- the mixed T_bubble+LLE fit of the SYNTHETIC "
          "water + 1-butanol witness recovers the generating b_ij and b_ji to "
          "1e-5 from two starts and validates against held-out bubble "
          f"temperatures and tie lines; {n_ties} tie lines recomputed by an "
          "independent convex hull agree with the datasets; six refusals fire "
          "by name on probes built here (ideal start, weighting equal, no "
          "sigma, no band, one liquid phase, kind LLE alone); a held-out tie "
          "line the model leaves as ONE liquid is named, counted, and a "
          "notValidated miss.  NOT checked: any real water + 1-butanol "
          "measurement, the dilute-branch accuracy below the flash's 1e-4 "
          "floor.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
