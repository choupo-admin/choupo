def public_guides(root: Path = ROOT):
    """The `DOCS :=` list of docs/Makefile -- the one home for public guides,
    read the way check_guide_pdf_fresh and copyDocs read it."""
    import re
    m = re.search(r'^DOCS\s*:=\s*(.+)$',
                  (root / "docs" / "Makefile").read_text(), re.M)
    return m.group(1).split() if m else []


def expand(entry, root: Path = ROOT):
    """The entry's globs with `<DOCS>` substituted."""
    out = []
    for p in entry["paths"]:
        if "<DOCS>" in p:
            out += [p.replace("<DOCS>", g) for g in public_guides(root)]
        else:
            out.append(p)
    return out


def entry_for(path: str, root: Path = ROOT):
    """The entry owning `path` (repo-relative), or None."""
    for e in ENTRIES:
        if any(fnmatch.fnmatchcase(path, g) for g in expand(e, root)):
            return e
    return None


def is_generated(path: str, root: Path = ROOT) -> bool:
    return entry_for(path, root) is not None


def _tracked(root: Path):
    r = subprocess.run(["git", "ls-files"], cwd=str(root),
                       capture_output=True, text=True)
    if r.returncode != 0:
        print("generated_artefacts: REFUSED -- `git ls-files` failed, so the "
              "registry cannot be compared with the tree.\n  "
              + r.stderr.strip())
        sys.exit(1)
    return [f for f in r.stdout.splitlines() if f]


def _declares_generated(p: Path) -> bool:
    try:
        head = p.read_bytes()[:3000].decode("utf-8", "ignore")
    except OSError:
        return False
    return "GENERATED by" in head or "DO NOT EDIT" in head


def check(root: Path = ROOT) -> int:
    tracked = _tracked(root)
    problems = []
    for e in ENTRIES:
        for argv in (e["generate"], e["check"]):
            if not argv:
                continue
            script = next((a for a in argv[1:] if "/" in a), None) \
                if argv[0] in (PY, "node") else None
            if script and not (root / script).is_file():
                problems.append(f"(a) {e['name']}: names {script}, which "
                                "does not exist")
        globs = expand(e, root)
        if not any(fnmatch.fnmatchcase(f, g) for f in tracked for g in globs):
            problems.append(f"(b) {e['name']}: no tracked file matches "
                            f"{globs}")
    owners = {}
    for f in tracked:
        hits = [e["name"] for e in ENTRIES
                if any(fnmatch.fnmatchcase(f, g) for g in expand(e, root))]
        if len(hits) > 1:
            problems.append(f"(e) {f} is claimed by {hits}")
        if hits:
            owners[f] = hits[0]
            continue
        if f.startswith("generated/"):
            problems.append(f"(c) {f} is under generated/ and no entry owns "
                            "it -- add one (with `generate None` if it has "
                            "no generator, saying so)")
        elif not f.startswith(("tutorials/", "data/", "src/", "bin/")) \
                and _declares_generated(root / f):
            problems.append(f"(d) {f} declares itself generated and no "
                            "entry owns it")
    if problems:
        print("generated_artefacts: FAILED")
        for p in problems:
            print("  " + p)
        return 1
    print(f"generated-artefacts: OK -- {len(ENTRIES)} registry entries own "
          f"{len(owners)} tracked file(s); every generator named exists, "
          "every entry matches a tracked file, every file under generated/ "
          "and every file that declares itself generated outside tutorials/ "
          "data/ src/ bin/ has exactly one owner.  NOT checked: whether any "
          "artefact is CURRENT (each entry's own check does that) or whether "
          "a generator really writes what its entry says (bin/integrate "
          "re-checks after every regeneration).")
    return 0


def main(argv) -> int:
    if argv[1:] == ["--check"]:
        return check()
    if argv[1:] == ["--list"]:
        for e in ENTRIES:
            gen = " ".join(e["generate"]) if e["generate"] else "(none)"
            print(f"{e['name']:<24} {e['phase']:<7} {e['conflict']:<10} "
                  f"{e['scope']:<6} {gen}")
            for g in expand(e):
                print(f"    {g}")
        return 0
    print(__doc__.split("\n\n")[0])
    print("usage: generated_artefacts.py --list | --check")
    return 0 if argv[1:] in ([], ["-h"], ["--help"]) else 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
