#!/usr/bin/env python3
"""ONE home for which tracked files are GENERATED, by what, and how to refresh.

    from generated_artefacts import ENTRIES, entry_for, is_generated

    bin/curate/generated_artefacts.py --list     the registry, one line each
    bin/curate/generated_artefacts.py --check    the registry against the tree

WHY THIS EXISTS (2026-10-20, DEV.md 4c C122).  Integrating a general's branch
cost the commander about an hour per branch, and the mechanical half of that
hour was generated files: `generated/caseManifest.json` conflicting because
both sides added a case, a guide PDF a checkout had left NEWER than its
sources, a gate-manifest claim the branch had changed.  The rule was always
clear -- a generated file is REGENERATED, never transported or hand-merged
(check_workspace_truth has said so since 2026-08-15) -- but nothing in the
tree said WHICH files are generated or WHICH command regenerates each.  That
knowledge lived in the commander's head and in ten `--check` arms scattered
through `bin/runTests`, and before this module nobody had written it down as
a list.  `bin/integrate` needs the list; so does anyone resolving a merge by
hand.  This is it, and it is the only copy.

WHAT AN ENTRY SAYS.

  paths       globs (repo-relative) naming the tracked files the generator
              owns.  `whole` entries own the file outright; `region` entries
              own a delimited block inside a hand-written file.
  generate    the argv that rewrites them (run from the repository root).
  check       the argv that exits non-zero when they are stale, or None.
              WHERE THERE IS NO CHECK, FRESHNESS IS NOT A CONTRACT: the tool
              regenerates such a file only when a merge CONFLICTS in it, and
              never re-stamps it on a clean merge (the interim review dossier
              is a curation snapshot nobody gates; re-stamping it on every
              integration would move its findings with no reader asking).
  phase       when it can run: `pre` (pure text), `build` (needs the native
              build -- the compiler's .d files or the engine), `engine` (RUNS
              cases, minutes), `node` (needs gui/node_modules), `pdf` (a guide
              render), `gates` (the gate manifest, refreshed per gate).
  conflict    what a merge conflict in it means:
                regenerate -- take main's side, run the generator;
                human      -- STOP; the conflict holds hand-written text the
                              generator would overwrite or cannot produce.

WHAT IS DELIBERATELY NOT HERE.

  * `generated/modelsCatalogue.json` is listed with `generate None`: it sits
    in generated/ but NO generator exists (check_models_catalogue says so in
    its own arm 6) -- a conflict in it is a human's.
  * `generated/releases/<tag>.json` is a RELEASE act (`release_inventory.py
    --release`), never an integration's.
  * `banner_version.py` stamps a rule across thousands of files rather than
    owning any; it is a gate, not a generator, and stays in bin/runTests.

THE --check ARM keeps this list honest in both directions, because a list of
generated files that goes stale fails in silence -- a missing entry does not
error, it just lets a conflict through to a human who then hand-merges a
generated file, which is the defect the list exists to end:
  (a) every generator and checker this registry names exists;
  (b) every entry's globs match at least one TRACKED file;
  (c) every tracked file under generated/ is covered by an entry;
  (d) every tracked file outside tutorials/ data/ src/ bin/ whose first 3000
      bytes DECLARE it generated (`GENERATED by` in capitals, or `DO NOT
      EDIT`) is covered by an entry;
  (e) no tracked file is claimed by two entries.
It does NOT check that a generator's output is current -- that is each
entry's own `check` (most are already arms of bin/runTests), nor that a
listed command really regenerates what it claims (bin/integrate observes
that on every use: it re-runs `check` after `generate` and refuses when the
artefact is still stale).
"""

