#!/usr/bin/env python3
"""Render the guides' version stamp from the engine's own CHOUPO_VERSION.

    bin/curate/guide_version.py            # write docs/version.tex
    bin/curate/guide_version.py --check    # exit 1 if it is stale

WHY THIS EXISTS.  `src/core/Banner.H` says, in a comment above the
constant, that the version lives "in ONE place (CHOUPO_VERSION) instead of
duplicating it across" -- and `docs/preamble.tex` duplicated it anyway, as a
literal `Choupo-2607` in the page footer and `Version 2607` on every title
page.  So every guide built from `main` was stamped with the last RELEASE
while documenting the DEVELOPMENT line.

That is not a cosmetic slip.  A reader downloads theoryGuide.pdf, sees
"Choupo-2607", and reasonably concludes it documents the 2607 release.  It
documents `main` -- which today carries a reactive distillation column,
pinch analysis and per-tray chemistry that 2607 does not have.  A manual
that names a release it does not describe is worse than an undated one:
the wrong label is believed.

The title page also carried a hardcoded "30 June 2026", the 2607 release
date, on documents rebuilt weeks later.  A build date is not the answer
either -- it would change the PDF bytes on every rebuild and make the
output irreproducible.  On the development line the honest stamp is the
version alone, and a tagged release gets its date when it is tagged.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BANNER = ROOT / "src" / "core" / "Banner.H"
OUT = ROOT / "docs" / "version.tex"


def engine_version() -> str:
    m = re.search(r'CHOUPO_VERSION\s*=\s*"([^"]+)"', BANNER.read_text())
    if not m:
        raise SystemExit(f"guide_version: no CHOUPO_VERSION in {BANNER}")
    return m.group(1)


def render() -> str:
    v = engine_version()
    #  A tagged release (vYYMM -> "Choupo-YYMM") carries its number on the
    #  title page; the development line says so in words instead, because
    #  "Version dev" reads like a mistake and "Choupo-dev" reads like what
    #  it is.
    m = re.fullmatch(r"Choupo-(\d{4})", v)
    title = f"Version {m.group(1)}" if m else v
    return (
        "%% GENERATED by bin/curate/guide_version.py -- DO NOT EDIT BY HAND.\n"
        "%% Source of truth: CHOUPO_VERSION in src/core/Banner.H.\n"
        "%% A runTests gate refuses a stale render.\n"
        f"\\newcommand{{\\choupoversion}}{{{v}}}\n"
        f"\\newcommand{{\\choupoversiontitle}}{{{title}}}\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists():
            print("guide_version: docs/version.tex missing -- run "
                  "bin/curate/guide_version.py")
            return 1
        if OUT.read_text() != text:
            print(f"guide_version: docs/version.tex is STALE -- the engine "
                  f"says {engine_version()}; run bin/curate/guide_version.py")
            return 1
        print(f"guide version stamp up to date ({engine_version()}, "
              "rendered from Banner.H)")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({engine_version()})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
