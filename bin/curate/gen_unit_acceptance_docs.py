"""Generate what each unit ACCEPTS, for the docs and the GUI, from the engine.

    bin/curate/gen_unit_acceptance_docs.py            (writes both outputs)
    bin/curate/gen_unit_acceptance_docs.py --check    (exit 1 when either is stale)

WHY (DEV.md 4c C188 item 5, slice C; docs/design/what-a-unit-accepts.md
section 11).  What a unit accepts is a DECLARATION in the engine
(`UnitOperation::acceptance()` / `BatchUnitOperation::acceptance()`), and both
steady and batch binaries publish every declaration as JSON
(`choupoSolve --describe-units`, `choupoBatch --describe-units`, schema
`unitAcceptance-v1`, one writer: `describeAcceptancesJson`).  Until this
generator the documentation said it in hand-written paragraphs -- a second
home for the contract, which goes false the day a declaration moves.  This
script RUNS the two binaries of THIS tree and writes, for every unit whose
class DECLARED a contract, the same four lists in two places:

  * docs/ai/unit-ops.md -- one region per unit, between
        <!-- BEGIN GENERATED unit-acceptance <type> ... -->
        <!-- END GENERATED unit-acceptance <type> -->
    An existing region is rewritten in place; a declared unit with no region
    gets one inserted just before the first heading that follows the unit's
    own heading (outside code fences), so it sits inside the unit's section;
    a region for a type that no longer declares a contract is REMOVED.  The
    text outside the regions is never touched.
  * gui/schemas/unitAcceptance.json -- the same lists, rendered once HERE so
    the GUI draws them and computes nothing (the Internals "Model" tab).

AN UNDECLARED UNIT GETS NOTHING: silence keeps meaning "nothing declared"
(the default accepts every phase and models every component).

THE FOUR LISTS (one renderer, `lists_of`, read by both outputs):
  models     -- the components the equations carry (the rule's sentence), and
                "at least one" when the unit declares it;
  mayPass    -- the declared pass-through fates, or that none is offered;
  refuses    -- one line per refusal clause the contract can write: a phase
                outside the accepted ones, a feed with no aqueous solvent, a
                component outside what it models, a feed carrying none of
                them, each further condition;
  needs      -- each package capability, with why.
Every sentence is the ENGINE's (the `why` / `sentence` fields of the
declaration); the generator adds only the clause headings.  For a choupoBatch
vessel the "judged on" line says the initial holdup, because that is where
choupoBatch applies a contract (it has no pre-solve seam; record section 10).

`--check` is held by bin/runTests (the `unit-acceptance-docs` row) and is
registered in bin/curate/generated_artefacts.py (two entries: the region,
conflict = human; the JSON, conflict = regenerate).  check_unit_acceptance
arm (l) adds what a freshness check cannot see: every declared unit is named
in both outputs and no undeclared one is.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BINARIES = (("choupoSolve", ROOT / "build" / "linux64Gcc" / "choupoSolve"),
            ("choupoBatch", ROOT / "build" / "linux64Gcc" / "choupoBatch"))
DOC = ROOT / "docs" / "ai" / "unit-ops.md"
JSON_OUT = ROOT / "gui" / "schemas" / "unitAcceptance.json"

TAG = "unit-acceptance"
BEGIN = re.compile(r"^<!-- BEGIN GENERATED " + TAG + r" (\S+) ")
END = "<!-- END GENERATED " + TAG + " {t} -->"
HEADER = ("GENERATED by bin/curate/gen_unit_acceptance_docs.py from "
          "`choupoSolve --describe-units` and `choupoBatch --describe-units` "
          "(the one home: each unit's acceptance() declaration).  Do not edit; "
          "regenerate.")


def describe(name, path):
    if not path.exists():
        raise RuntimeError(f"{path} is not built (make all)")
    env = dict(os.environ, CHOUPO_HOME=str(ROOT))
    r = subprocess.run([str(path), "--describe-units"], capture_output=True,
                       text=True, env=env, timeout=120)
    if r.returncode != 0:
        raise RuntimeError(f"{name} --describe-units exited {r.returncode}:\n"
                           + (r.stdout + r.stderr)[-1500:])
    lines = r.stdout.splitlines()
    start = next((i for i, l in enumerate(lines) if l == "{"), None)
    if start is None:
        raise RuntimeError(f"{name} --describe-units printed no JSON object")
    doc = json.loads("\n".join(lines[start:]))
    if doc.get("schema") != "unitAcceptance-v1":
        raise RuntimeError(f"{name} --describe-units: schema "
                           f"{doc.get('schema')!r}, expected unitAcceptance-v1")
    return doc["units"]


def declared_units():
    """{type: (binary, contract)} for every DECLARED contract, plus the count
    of types each binary listed.  A type declared by both binaries refuses:
    the docs have one section per type word."""
    out, listed = {}, {}
    for name, path in BINARIES:
        units = describe(name, path)
        listed[name] = len(units)
        for u in units:
            if not u.get("declared"):
                continue
            if u["type"] in out:
                raise RuntimeError(f"type '{u['type']}' declares a contract in "
                                   f"both {out[u['type']][0]} and {name}")
            out[u["type"]] = (name, u)
    return out, listed


def _end(s):
    s = s.strip()
    return s if s.endswith((".", "!", "?")) else s + "."


def lists_of(binary, u):
    """The four lists of one contract (the ONE renderer)."""
    judged = ("the vessel's initial holdup, in its initialise -- choupoBatch "
              "has no pre-solve pass" if binary == "choupoBatch" else
              "the combined feed it makes of its inlets"
              if u["appliesTo"] == "combinedFeed" else
              "each process inlet, before any unit runs when the inlet is "
              "authored, else at the unit's own solve")
    models = [_end(u["models"]["sentence"][:1].upper()
                   + u["models"]["sentence"][1:])]
    if u["models"].get("atLeastOne"):
        models.append("At least one of them besides the solvent.")
    pt = u["passThrough"]
    if pt["fates"]:
        may = ["A component it does not model, when the case DECLARES it: "
               "`passThrough { <component> { fate "
               + " | ".join(pt["fates"]) + "; }  reason \"...\"; }`"
               + (" -- " + _end(pt["why"]) if pt.get("why") else ".")]
    else:
        may = ["Nothing: no pass-through is offered, so every component it "
               "is handed enters its equations or is refused."]
    refuses = []
    acc = u["phases"]["accepted"]
    if acc != ["liquid", "vapour"]:
        refuses.append("A feed that is not "
                       + (" or ".join("a " + p for p in acc) if acc else
                          "of any phase")
                       + " -- " + _end(u["phases"].get("why", "")))
    for port in u.get("ports", []):
        if port["accepted"] != ["liquid", "vapour"]:
            refuses.append("The " + port["name"] + " inlet carrying something"
                           " that is not "
                           + (" or ".join("a " + p for p in port["accepted"])
                              if port["accepted"] else "of any phase")
                           + " -- " + _end(port.get("why", "")))
    if u["solvent"]["aqueousRequired"]:
        refuses.append("A feed carrying no aqueous solvent -- "
                       + _end(u["solvent"].get("why", "")))
    if u["models"]["rule"] != "everyComponent":
        refuses.append("A component outside what it models -- "
                       + _end(u["models"].get("why", "")))
    if u["models"].get("atLeastOne"):
        refuses.append("A feed carrying none of the components it acts on -- "
                       + _end(u["models"].get("noneWhy", "")))
    for c in u["refusesAlso"]:
        refuses.append("A feed failing `" + c["id"] + "` -- "
                       + _end(c["sentence"]))
    needs = ["`" + n["capability"] + "` -- " + _end(n["why"])
             for n in u["needs"]]
    return {"binary": binary, "judged": judged, "rule": u["models"]["rule"],
            "models": models, "mayPass": may, "refuses": refuses,
            "needs": needs}


def region(key, L):
    """One region for a GROUP of type words sharing a heading (a type and its
    aliases, whose contracts are the same object): marker id `a,b`."""
    types = key.split(",")
    named = f"`{types[0]}`" + (" (alias " + ", ".join(f"`{x}`" for x in types[1:])
                              + ")" if len(types) > 1 else "")
    out = [f"<!-- BEGIN GENERATED {TAG} {key} -- {HEADER} -->",
           f"**What {named} accepts** (generated from `{L['binary']} "
           f"--describe-units`; judged on {L['judged']}):", ""]
    for head, field in (("Models", "models"), ("May pass through", "mayPass"),
                        ("Refuses", "refuses"), ("Needs", "needs")):
        items = L[field] or ["No package capability beyond the components' "
                           "own records."]
        out.append(f"* **{head}:**")
        out += [f"  * {s}" for s in items]
    out.append(END.format(t=key))
    return out


def _heading_index(lines, t):
    """The line of the unit's own heading (`## ...` / `### ...` carrying the
    backticked type word), outside code fences, or None."""
    fence = False
    pat = re.compile(r"^#{2,3}\s.*`" + re.escape(t) + r"`")
    for i, l in enumerate(lines):
        if l.startswith("```"):
            fence = not fence
            continue
        if not fence and pat.match(l):
            return i
    return None


def _next_heading(lines, i):
    fence = False
    for j in range(i + 1, len(lines)):
        l = lines[j]
        if l.startswith("```"):
            fence = not fence
            continue
        if not fence and l.startswith("#"):
            return j
    return len(lines)


def groups(lines, units):
    r"""[(key, heading line)]: the declared types grouped by the heading that
    names them (`## ... \`spiralWoundModule\`  (alias \`membraneSW\`)`),
    in the heading's own order.  Types sharing a heading must declare the
    SAME contract -- an alias is one class -- or the generator refuses."""
    by_head = {}
    for t in units:
        h = _heading_index(lines, t)
        if h is None:
            raise RuntimeError(f"{DOC.relative_to(ROOT)} has no `## `/`### ` "
                               f"heading naming `{t}` -- a declared unit must "
                               "have a section to put its contract in")
        by_head.setdefault(h, []).append(t)
    out = []
    for h, ts in by_head.items():
        ts.sort(key=lambda x: lines[h].index("`" + x + "`"))
        first = lists_of(*units[ts[0]])
        for x in ts[1:]:
            if lists_of(*units[x]) != first:
                raise RuntimeError(f"`{ts[0]}` and `{x}` share a heading but "
                                   "declare different contracts")
        out.append((",".join(ts), h))
    return sorted(out)


def render_doc(text, units):
    lines = text.split("\n")
    # 1. Remove every existing region, remembering where each sat.
    kept, where = [], {}
    i = 0
    while i < len(lines):
        m = BEGIN.match(lines[i])
        if not m:
            kept.append(lines[i])
            i += 1
            continue
        t = m.group(1)
        end = END.format(t=t)
        j = i
        while j < len(lines) and lines[j] != end:
            j += 1
        if j == len(lines):
            raise RuntimeError(f"{DOC.relative_to(ROOT)}: region '{t}' has no "
                               f"`{end}` line")
        if t in where:
            raise RuntimeError(f"{DOC.relative_to(ROOT)}: two regions for '{t}'")
        where[t] = len(kept)
        i = j + 1
    # 2. Insert one region per declared unit: in place, else before the next
    #    heading after the unit's own.  Insert bottom-up so indices hold.
    plan = []
    for key, h in groups(kept, units):
        if key in where:
            plan.append((where[key], key, False))
        else:
            plan.append((_next_heading(kept, h), key, True))
    for pos, key, fresh in sorted(plan, key=lambda p: (p[0], p[1]), reverse=True):
        block = region(key, lists_of(*units[key.split(",")[0]]))
        if fresh:
            block = block + [""]
        kept[pos:pos] = block
    return "\n".join(kept)


TEX_OUT = ROOT / "docs" / "theoryGuide-unitAcceptanceTable.tex"
_TEX_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
                "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
                "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def _tex(s):
    """Plain text -> LaTeX: specials escaped, `code` spans set in \\texttt."""
    out = []
    for i, chunk in enumerate(s.split("`")):
        e = "".join(_TEX_SPECIAL.get(c, c) for c in chunk)
        out.append("\\texttt{" + e + "}" if i % 2 else e)
    return "".join(out)


def render_tex(units):
    """One longtable row per declared unit for the Theory Guide: what it
    models, what it may pass through, and the NAMES of what it refuses (the
    sentences live in docs/ai/unit-ops.md and in the GUI's Model tab; this is
    the map a reader holds before opening either)."""
    grouped = {}      # a type and its aliases are one row
    for t in sorted(units):
        binary, u = units[t]
        L = lists_of(binary, u)
        names = []
        if u["phases"]["accepted"] != ["liquid", "vapour"]:
            names.append("phase: " + " or ".join(u["phases"]["accepted"])
                         + " only")
        for port in u.get("ports", []):
            if port["accepted"] != ["liquid", "vapour"]:
                names.append("phase of the " + port["name"] + ": "
                             + " or ".join(port["accepted"]) + " only")
        if u["solvent"]["aqueousRequired"]:
            names.append("no aqueous solvent")
        if u["models"]["rule"] != "everyComponent":
            names.append("component outside the model")
        for c in u["refusesAlso"]:
            names.append(c["id"])
        for n in u["needs"]:
            names.append("needs " + n["capability"])
        may = ("fate " + " | ".join(u["passThrough"]["fates"])
               if u["passThrough"]["fates"] else "none")
        body = (" & " + _tex(L["models"][0]) + " & " + _tex(may) + " & "
                + _tex("; ".join(names) if names else "nothing") + " \\\\")
        grouped.setdefault(body, []).append(t)
    rows = [", ".join("\\texttt{" + "".join(_TEX_SPECIAL.get(c, c) for c in x)
                      + "}" for x in ts) + body
            for body, ts in grouped.items()]
    col = ">{\\raggedright\\arraybackslash}p{%s\\linewidth}"
    head = ("% " + HEADER + "\n"
            "\\begin{longtable}{@{}" + col % "0.17" + col % "0.38"
            + col % "0.12" + col % "0.28" + "@{}}\n"
            "\\hline\n"
            "\\textbf{Unit} & \\textbf{Models} & \\textbf{May pass} & "
            "\\textbf{Refuses (clause names)} \\\\\n"
            "\\hline\n\\endhead\n")
    return head + "\n".join(rows) + "\n\\hline\n\\end{longtable}\n"


def render_json(units):
    obj = {"comment": HEADER, "schema": "unitAcceptanceDocs-v1",
           "units": {t: lists_of(*units[t]) for t in sorted(units)}}
    return json.dumps(obj, indent=1, ensure_ascii=False) + "\n"


def outputs():
    units, listed = declared_units()
    return (render_doc(DOC.read_text(), units), render_json(units), units,
            listed, render_tex(units))


def main(argv):
    try:
        doc, js, units, listed, tex = outputs()
    except (RuntimeError, ValueError) as e:
        print(f"gen_unit_acceptance_docs: REFUSED -- {e}")
        return 1
    rel = (DOC.relative_to(ROOT), JSON_OUT.relative_to(ROOT))
    if "--check" in argv[1:]:
        stale = [str(p) for p, new in ((DOC, doc), (JSON_OUT, js), (TEX_OUT, tex))
                 if not p.exists() or p.read_text() != new]
        if stale:
            print("gen_unit_acceptance_docs: STALE -- " + ", ".join(stale)
                  + " is not what the engine's declarations generate; run "
                  "bin/curate/gen_unit_acceptance_docs.py")
            return 1
        print(f"unit-acceptance-docs: OK -- {rel[0]}, {rel[1]} and "
              f"{TEX_OUT.relative_to(ROOT)} are what "
              f"the {len(units)} declared contract(s) generate "
              f"({', '.join(sorted(units))}), read from choupoSolve "
              f"({listed['choupoSolve']} types) and choupoBatch "
              f"({listed['choupoBatch']} types) --describe-units; NOT checked: "
              "the text outside the generated regions")
        return 0
    DOC.write_text(doc)
    JSON_OUT.write_text(js)
    TEX_OUT.write_text(tex)
    print(f"gen_unit_acceptance_docs: wrote {rel[0]} ({len(units)} region(s)) "
          f"and {rel[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
