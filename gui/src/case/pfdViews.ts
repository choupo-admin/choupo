/*---------------------------------------------------------------------------*\
  Choupo GUI -- the VIEWS of a plant a PFD is drawn from (S2)

  A flat case is one view; a sectored case is the plant overview (sectors as
  boxes) plus one view per sector.  Each view is the graph the canvas itself
  would draw for that flowsheet (`flowsheetToGraph`: the same nodes, sizes and
  positions) turned into the plain figure `flowsheetSvg` draws, together with
  the result streams that belong to it, its equipment tags and the utilities
  its stubs name.

  Stream numbers are the canvas's (`streamNumbering.ts`): the figure's wire
  badges and the table's column heads come from ONE resolver, so a number on
  the drawing and the same number in the table are the same stream.

  Wires are redrawn here as orthogonal polylines between the boxes (the
  canvas's own routing lives in the DOM); a bend a student dragged on the
  canvas is not carried to the sheet.
\*---------------------------------------------------------------------------*/

import type { EquipmentItem, RunResult, StreamResult } from "../adapters/SolverAdapter.js";
import { parse, toJson } from "../dict/index.js";
import type { JsonDict } from "../dict/index.js";
import { globalStreamNumbering } from "./streamNumbering.js";
import { compositeMembers, flowsheetToGraph, streamNumbersForFlowsheet, type FlowsheetGraph } from "./toGraph.js";
import { buildPfdSheets, type PageSizeName, type PfdLegendItem, type PfdSheet, type PfdView } from "./pfdSheet.js";
import type { SvgEdge, SvgNode } from "./flowsheetSvg.js";
import { symbolOf } from "./unitFamily.js";

/** The equipment TAG the engine published for a unit: `tagNo`, generated by
 *  the tag rule (Turton's `XX-YZZ A/B`, `EquipmentTag.cpp`) or declared by the
 *  case.  `EquipmentItem.tag` is NOT it -- that is the sub-item word (`train1`,
 *  `shell`) -- so only `tagNo` is read, as the engine wrote it (it can be
 *  `P-101A-D`, `MB-101A..F`, `P-101A/B`; no pattern is applied here, the GUI
 *  draws what the engine published). */
export function tagOfUnit(equipment: readonly EquipmentItem[] | undefined, qualifiedUnit: string): string | undefined {
  for (const it of equipment ?? [])
    if (it.unit === qualifiedUnit && typeof it.tagNo === "string" && it.tagNo.length > 0) return it.tagNo;
  return undefined;
}

export interface SectorFlowsheet { path: string; flowsheet: JsonDict; raw: { [rel: string]: string } }

function parseFs(text: string, name: string): JsonDict | undefined {
  try { return toJson(parse(text, { sourceName: name })) as JsonDict; }
  catch { return undefined; }
}

/** The top-level sectors of a sectored root (children with their own
 *  flowsheetDict that hold units or members); [] for a flat case. */
export function sectorFlowsheets(root: JsonDict, raw: { [rel: string]: string }): SectorFlowsheet[] {
  const out: SectorFlowsheet[] = [];
  for (const child of compositeMembers(root)) {
    for (const base of [child, `sectors/${child}`, `unitOperations/${child}`]) {
      const t = raw[`${base}/flowsheetDict`] ?? raw[`${base}/system/flowsheetDict`];
      if (t === undefined) continue;
      const fs = parseFs(t, `${child}/flowsheetDict`);
      if (!fs) break;
      const has = (Array.isArray(fs["units"]) && (fs["units"] as unknown[]).length > 0)
        || compositeMembers(fs).length > 0;
      if (has) {
        const scoped: { [rel: string]: string } = {};
        for (const [k, v] of Object.entries(raw))
          if (k.startsWith(base + "/")) scoped[k.slice(base.length + 1)] = v;
        out.push({ path: child, flowsheet: fs, raw: scoped });
      }
      break;
    }
  }
  return out;
}

/** (path, local name) -> the whole-plant number, the canvas's own. */
export function pfdNumbering(root: JsonDict, raw: { [rel: string]: string }): (path: string, name: string) => number | undefined {
  if (compositeMembers(root).length > 0) return globalStreamNumbering(root, raw);
  const local = streamNumbersForFlowsheet(root, raw);
  return (_path, name) => local.get(name);
}

/* ---- figure --------------------------------------------------------------- */

const TIER_STROKE: Record<string, string> = {
  heating: "#c2410c", cooling: "#0369a1", power: "#6d28d9",
};

type Box = { x: number; y: number; w: number; h: number };

function ortho(a: Box, b: Box, back: boolean, bottom: number): string {
  const sx = a.x + a.w, sy = a.y + a.h / 2, tx = b.x, ty = b.y + b.h / 2;
  if (!back && sx <= tx) {
    const mx = (sx + tx) / 2;
    return `M ${sx} ${sy} L ${mx} ${sy} L ${mx} ${ty} L ${tx} ${ty}`;
  }
  const yb = bottom + 24;
  return `M ${sx} ${sy} L ${sx + 16} ${sy} L ${sx + 16} ${yb} L ${tx - 16} ${yb} L ${tx - 16} ${ty} L ${tx} ${ty}`;
}

export function figureOfGraph(
  graph: FlowsheetGraph,
  qualify: (localUnit: string) => string,
  numberIn: (localStream: string) => number | undefined,
  equipment: readonly EquipmentItem[] | undefined,
): { nodes: SvgNode[]; edges: SvgEdge[] } {
  const boxes = new Map<string, Box>();
  const isStub = new Map<string, boolean>();
  const nodes: SvgNode[] = [];
  let bottom = 0;
  for (const n of graph.nodes) {
    const sz = graph.sizes.get(n.id) ?? { width: 190, height: 84 };
    const box = { x: n.position.x, y: n.position.y, w: sz.width, h: sz.height };
    boxes.set(n.id, box);
    bottom = Math.max(bottom, box.y + box.h);
    const d = n.data as {
      unit?: { name?: string; type?: string }; name?: string; role?: string;
      tier?: string; utilityName?: string; dutyPort?: string;
    };
    if (n.type === "unitNode" && d.unit) {
      const name = d.unit.name ?? n.id;
      const tag = tagOfUnit(equipment, qualify(name));
      const sym = symbolOf(d.unit.type);
      nodes.push({ ...box, kind: "unit", label: tag ?? name, sub: tag ? name : undefined,
                   stroke: "#374151", fill: "#ffffff",
                   symbolPath: sym?.path, symbolTag: sym?.tag });
    } else {
      const stub = d.role === "utility";
      isStub.set(n.id, stub);
      nodes.push({ ...box, kind: "terminal",
                   label: stub ? (d.utilityName ?? d.tier ?? d.name ?? "utility") : (d.name ?? n.id.replace(/^stream:/, "")),
                   stroke: stub ? (TIER_STROKE[d.tier ?? ""] ?? "#6b7280") : "#6b7280",
                   fill: stub ? "#f9fafb" : "#f3f4f6" });
    }
  }
  const edges: SvgEdge[] = [];
  for (const e of graph.edges) {
    const a = boxes.get(e.source), b = boxes.get(e.target);
    if (!a || !b) continue;
    const energy = e.id.startsWith("e:energy");
    const stubEdge = isStub.get(e.source) || isStub.get(e.target);
    let d: string;
    if (stubEdge) {
      const ac = { x: a.x + a.w / 2, y: a.y + a.h / 2 }, bc = { x: b.x + b.w / 2, y: b.y + b.h / 2 };
      const down = bc.y > ac.y;
      d = `M ${ac.x} ${down ? a.y + a.h : a.y} L ${bc.x} ${down ? b.y : b.y + b.h}`;
    } else {
      d = ortho(a, b, e.type === "tear" || (e.data as { backEdge?: boolean } | undefined)?.backEdge === true, bottom);
    }
    const st = (e.style ?? {}) as { stroke?: string; strokeDasharray?: string; strokeWidth?: number };
    const num = !energy && !stubEdge && typeof e.label === "string" ? numberIn(e.label) : undefined;
    edges.push({ d, stroke: st.stroke ?? "#4b5563", width: st.strokeWidth ?? 1.6,
                 dash: st.strokeDasharray, arrow: true,
                 ...(num !== undefined ? { label: String(num) } : {}) });
  }
  return { nodes, edges };
}

/* ---- legend ---------------------------------------------------------------- */

export function legendOfGraph(
  graph: FlowsheetGraph,
  qualify: (localUnit: string) => string,
  result: Pick<RunResult, "equipment" | "utilityAllocation">,
): PfdLegendItem[] {
  const items: PfdLegendItem[] = [];
  const seen = new Set<string>();
  const add = (it: PfdLegendItem) => { const k = it.kind + it.text; if (!seen.has(k)) { seen.add(k); items.push(it); } };
  for (const n of graph.nodes) {
    const d = n.data as { role?: string; ownerUnit?: string; dutyPort?: string; tier?: string; utilityName?: string };
    if (d.role !== "utility" || !d.ownerUnit) continue;
    const q = qualify(d.ownerUnit);
    const row = (result.utilityAllocation ?? []).find((r) =>
      r.unit === q && (r.port === (d.dutyPort ?? "") || (d.dutyPort === "Q" && r.port === "")));
    const util = row && row.allocated ? row.utility : (d.utilityName ?? `${d.tier ?? "duty"} (not allocated)`);
    add({ kind: "utility", text: `${tagOfUnit(result.equipment, q) ?? d.ownerUnit} ${d.dutyPort ?? ""}: ${util}`.replace("  ", " ") });
  }
  for (const n of graph.nodes) {
    const u = (n.data as { unit?: { name?: string } }).unit;
    if (n.type !== "unitNode" || !u?.name) continue;
    const tag = tagOfUnit(result.equipment, qualify(u.name));
    if (tag) add({ kind: "tag", text: `${tag}  ${u.name}` });
  }
  return items;
}

/* ---- streams of a view ----------------------------------------------------- */

export function streamsOfView(
  graph: FlowsheetGraph, path: string, result: Pick<RunResult, "streams" | "streamAliases">,
): StreamResult[] {
  const byName = new Map(result.streams.map((s) => [s.name, s] as const));
  const out = new Map<string, StreamResult>();
  const prefix = path ? path.replace(/\//g, ".") + "." : "";
  for (const local of graph.streamNumbers.keys()) {
    const dotted = local.replace(/\//g, ".");
    for (const cand of [prefix + local, prefix + dotted, dotted, local]) {
      const id = byName.has(cand) ? cand : result.streamAliases?.[cand];
      const s = id !== undefined ? byName.get(id) : undefined;
      if (s) { out.set(s.name, s); break; }
    }
  }
  return [...out.values()];
}

/* ---- the views ------------------------------------------------------------- */

export function pfdViews(
  root: JsonDict, raw: { [rel: string]: string }, result: RunResult,
): { views: PfdView[]; numberOf: (streamName: string) => number | undefined } {
  const num = pfdNumbering(root, raw);
  const sectors = sectorFlowsheets(root, raw);
  const mk = (fs: JsonDict, rawFs: { [rel: string]: string }, path: string, caption: string): PfdView => {
    const graph = flowsheetToGraph(fs, rawFs);
    const qualify = (u: string) => (path ? path.replace(/\//g, ".") + "." : "") + u;
    return {
      sector: path, caption,
      figure: figureOfGraph(graph, qualify, (l) => num(path, l), result.equipment),
      streams: streamsOfView(graph, path, result),
      legend: legendOfGraph(graph, qualify, result),
    };
  };
  const views: PfdView[] = [];
  if (sectors.length === 0) views.push(mk(root, raw, "", "Flowsheet"));
  else {
    views.push(mk(root, raw, "", "Plant overview"));
    for (const s of sectors) views.push(mk(s.flowsheet, s.raw, s.path, `Sector ${s.path}`));
  }
  //  the table's column head is the number of the stream by its RESULT name
  const numberOf = (name: string) => num("", name);
  return { views, numberOf };
}

/** The sheets of a run: the one call the Reports workspace and the canvas
 *  export both make. */
export function buildPfd(
  root: JsonDict, raw: { [rel: string]: string }, result: RunResult, forced?: PageSizeName,
): PfdSheet[] {
  const { views, numberOf } = pfdViews(root, raw, result);
  return buildPfdSheets({ views, numberOf, componentMolarMass: result.componentMolarMass, forced });
}
