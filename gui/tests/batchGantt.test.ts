/*---------------------------------------------------------------------------*\
  The batch plan's Gantt chart (DEV.md 4c C99, C110 G2/G5) is DRAWN, never
  computed: one row per published stage, one bar per published Gantt row at
  its published start and end, in the lane of its published unit; a field
  the engine did not publish is NAMED, never defaulted; and a multiproduct
  year (G2) is drawn as the engine wrote it -- campaigns, changeovers, the
  clean before the next product, each stage's own clean.  Fixtures in the
  two shapes src/result/BatchPlanJson.cpp writes, and the apalutamide plan
  as THIS tree's engine wrote it (its run log, read through the adapter that
  reads a real run, beside the gantt.csv of the same run; generated by the
  witness setup, never committed).
\*---------------------------------------------------------------------------*/

