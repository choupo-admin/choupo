/** The bar's x where its block's window puts the published hour. */
const xAt = (fig: GanttFigure, blk: GanttBlockGeom, h: number) =>
  fig.plotX + (h - blk.t0) * blk.scale;
const blockOf = (fig: GanttFigure, key: string) => fig.blocks.find((b) => b.key === key)!;

