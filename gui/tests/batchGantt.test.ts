describe("shapeBatchPlan, one product: the published block, typed and policed", () => {
  it("keeps every stage and every drawable bar; a bar without a number for a "
     + "time is NAMED and not drawn", () => {
    const p = shapeBatchPlan(SINGLE)! as SingleProductPlan;
    expect(p.multiProduct).toBe(false);
    expect(p.stages.map((s) => s.name)).toEqual(["A", "B", "C"]);
    expect(p.stages[0]!.limiting).toBe(true);
    expect(p.gantt).toHaveLength(SINGLE.gantt.length - 1);
    expect(p.missing).toEqual(["gantt[gantt:T2:C:3].start"]);
  });

  it("a field the drawing reads and the block lacks is NAMED, never defaulted", () => {
    const raw = structuredClone(SINGLE) as Record<string, unknown>;
    const st = (raw.stages as Record<string, unknown>[])[1]!;
    delete st.cycleTime;
    delete (raw.trains as Record<string, unknown>[])[0]!.campaignDuration;
    const p = shapeBatchPlan(raw)! as SingleProductPlan;
    expect(p.missing).toEqual(expect.arrayContaining(
      ["stages[B].cycleTime", "trains[T1].campaignDuration"]));
    expect(Number.isNaN(p.stages[1]!.cycleTime)).toBe(true);
  });

  it("no stage, no plan", () => {
    expect(shapeBatchPlan({ ...SINGLE, stages: [] })).toBeUndefined();
    expect(shapeBatchPlan(undefined)).toBeUndefined();
  });
});

describe("ganttFigure, one product: the first campaign as published", () => {
  const plan = shapeBatchPlan(SINGLE)!;
  const fig = ganttFigure(plan)!;

  it("ONE BLOCK PER TRAIN, ONE STAGE ROW PER PUBLISHED STAGE, in its train's order", () => {
    expect(fig.blocks.map((b) => b.key)).toEqual(["single:T1", "single:T2"]);
    expect(fig.blocks.flatMap((b) => b.rows.filter((r) => r.stage)).map((r) => r.stage!.name))
      .toEqual(plan.stages.map((s) => s.name));
  });

  it("ONE BAR PER PUBLISHED GANTT ROW, at its published start and end", () => {
    expect(fig.bars).toHaveLength(plan.gantt.length);
    for (const g of plan.gantt) {
      const b = fig.bars.find((x) => x.src === g)!;
      const blk = blockOf(fig, b.block);
      expect(b.x).toBeCloseTo(xAt(fig, blk, g.start), 9);
      expect(b.w).toBeCloseTo((g.end - g.start) * blk.scale, 9);
    }
  });

  it("each train on its own axis from zero, reaching its own last published end", () => {
    for (const blk of fig.blocks) {
      const ends = fig.bars.filter((b) => b.block === blk.key).map((b) => b.src.end);
      expect(blk.t0).toBe(0);
      expect(blk.ticks.at(-1)!).toBeGreaterThanOrEqual(Math.max(...ends));
      expect(blk.scale * (blk.t1 - blk.t0)).toBeCloseTo(GANTT.plotW, 9);
    }
  });

  it("the published out-of-phase unit is the lane", () => {
    const bRow = fig.blocks[0]!.rows.find((r) => r.key === "stage:B")!;
    expect(bRow.lanes).toBe(2);
    const lot2 = fig.bars.find((b) => b.rowKey === "stage:B" && b.src.lot === 2)!;
    const lot1 = fig.bars.find((b) => b.rowKey === "stage:B" && b.src.lot === 1)!;
    expect([lot1.lane, lot2.lane]).toEqual([0, 1]);
    expect(lot2.y).toBeGreaterThan(lot1.y);
  });

  it("the limiting stage is the published one, T_L dimensioned between its "
     + "published lot-1 and lot-2 starts and labelled with the published T_L", () => {
    const t1 = fig.blocks[0]!;
    expect(t1.rows.filter((r) => r.limiting).map((r) => r.label)).toEqual(["A"]);
    expect(t1.cycleDim!.x1 - t1.cycleDim!.x0).toBeCloseTo((5 - 0) * t1.scale, 9);
    expect(t1.cycleDim!.hours).toBe(5);
  });

  it("the changeover, and a word this GUI does not know, each get a labelled "
     + "segment row of their train -- never dropped", () => {
    expect(fig.kinds[0]).toBe(LOT_KIND);
    expect(fig.kinds).toEqual(expect.arrayContaining(["changeover", "sterilisation"]));
    expect(fig.blocks.map((b) => b.rows.some((r) => r.label === "changeover")))
      .toEqual([true, true]);
    const steri = fig.bars.find((b) => b.kind === "sterilisation")!;
    const row = fig.blocks[0]!.rows.find((r) => r.key === steri.rowKey)!;
    expect(row.stage).toBeNull();
    expect(row.label).toBe("sterilisation");
    for (const b of fig.bars.filter((x) => x.kind !== LOT_KIND))
      expect(b.label || b.labelOutside, b.src.id).toBe(b.kind);
    const cols = fig.kinds.filter((k) => k !== LOT_KIND).map((k) => kindColour(k, fig.kinds));
    expect(new Set(cols).size).toBe(cols.length);
  });

  it("segmentKind: the engine's word first, a lot only on a published stage", () => {
    const names = new Set(["A"]);
    const g = plan.gantt[0]!;
    expect(segmentKind(g, names)).toBe(LOT_KIND);
    expect(segmentKind({ ...g, kind: "stageClean" }, names)).toBe("stageClean");
    expect(segmentKind({ ...g, stage: "changeover", lot: 0 }, names)).toBe("changeover");
    expect(segmentKind({ ...g, stage: "Z" }, names)).toBe("Z");
  });
});

