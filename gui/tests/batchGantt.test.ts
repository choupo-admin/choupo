describe("ganttFigure, several products: the year, then each first campaign", () => {
  const plan = shapeBatchPlan(MULTI)! as MultiProductPlan;
  const fig = ganttFigure(plan)!;
  const year = blockOf(fig, "year:T");

  it("per train a YEAR block, then one FIRST-CAMPAIGN block per product in "
     + "the published campaign order", () => {
    expect(fig.multiProduct).toBe(true);
    expect(fig.products).toEqual(["A", "B"]);
    expect(fig.blocks.map((b) => b.key)).toEqual(["year:T", "first:T:A", "first:T:B"]);
  });

  it("THE YEAR HOLDS EVERY PUBLISHED BAR ONCE, at its published start and end", () => {
    const inYear = fig.bars.filter((b) => b.block === year.key);
    expect(inYear).toHaveLength(plan.gantt.length);
    for (const x of plan.gantt) {
      const b = inYear.find((y) => y.src === x)!;
      expect(b.x).toBeCloseTo(xAt(fig, year, x.start), 9);
      expect(b.w).toBeCloseTo((x.end - x.start) * year.scale, 9);
    }
  });

  it("campaigns and changeovers in sequence on ONE campaigns row; lots and "
     + "each stage's clean on the stage's row; an unknown kind on its own row", () => {
    const rowOf = (kind: string) => new Set(fig.bars.filter((b) => b.block === year.key
      && b.kind === kind).map((b) => b.rowKey));
    const campRow = `segment:T:${CAMPAIGNS_ROW}`;
    for (const k of ["campaign", "changeover", "productChangeover"])
      expect([...rowOf(k)], k).toEqual([campRow]);
    expect([...rowOf("stageClean")].sort()).toEqual(["stage:S1", "stage:S2"]);
    expect([...rowOf(LOT_KIND)].sort()).toEqual(["stage:S1", "stage:S2"]);
    expect([...rowOf("inspection")]).toEqual(["segment:T:inspection"]);
    expect(year.rows.map((r) => r.key))
      .toEqual([campRow, "segment:T:inspection", "stage:S1", "stage:S2"]);
    expect(fig.kinds).toEqual(expect.arrayContaining(
      ["lot", "campaign", "changeover", "productChangeover", "stageClean", "inspection"]));
    //  At a year's scale no word is written outside a bar (they would
    //  overprint); the first-campaign blocks label every segment.
    expect(fig.bars.filter((b) => b.block === year.key).every((b) => b.labelOutside === ""))
      .toBe(true);
    for (const b of fig.bars.filter((x) => x.block !== year.key
      && x.kind !== LOT_KIND && x.kind !== "campaign"))
      expect(b.label || b.labelOutside, b.src.id).toBe(b.kind);
  });

  it("the year's axis reaches the train's PUBLISHED available hours and marks them", () => {
    expect(year.t1).toBeGreaterThanOrEqual(1000);
    expect(year.availableHours).toBe(1000);
    expect(year.availableX).toBeCloseTo(xAt(fig, year, 1000), 9);
  });

  it("a first-campaign block is a WINDOW between two published bars -- its "
     + "campaign-1 bar and the changeover published after it -- holding only "
     + "that product's bars, none re-timed", () => {
    const a = blockOf(fig, "first:T:A");
    expect(a.t0).toBeLessThanOrEqual(0);
    expect(a.t1).toBeGreaterThanOrEqual(11);
    const aBars = fig.bars.filter((b) => b.block === a.key);
    expect(aBars.every((b) => b.src.product === "A")).toBe(true);
    expect(aBars.filter((b) => b.kind === LOT_KIND)).toHaveLength(2);
    for (const b of aBars) expect(b.x).toBeCloseTo(xAt(fig, a, b.src.start), 9);
    //  B's single campaign ends in the clean before A: its stage cleans are in.
    const bb = fig.bars.filter((b) => b.block === "first:T:B");
    expect(bb.filter((b) => b.kind === "stageClean")).toHaveLength(2);
    expect(bb.every((b) => b.src.product === "B")).toBe(true);
  });

  it("T_L is each product's PUBLISHED cycle time on its published limiting stage", () => {
    const a = blockOf(fig, "first:T:A");
    expect(a.rows.filter((r) => r.limiting).map((r) => r.key)).toEqual(["stage:S1"]);
    expect(a.cycleDim).toBeNull();          // one lot a campaign: no lot 2 to dimension
    expect(a.detail).toContain("T_L = 4.00 h (limiting: S1)");
    expect(blockOf(fig, "first:T:B").detail).toContain("the clean before A: 6.00 h");
    expect(a.rows.find((r) => r.key === "stage:S2")!.right).toBe("util. 100.0 %");
  });
});

