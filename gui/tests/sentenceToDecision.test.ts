/*---------------------------------------------------------------------------*\
  sentenceToDecision.test.ts -- the `sentence-to-decision` EduTool (DEV.md 4c
  C127).

  WHAT IS HELD, and against what:
    1. every file:line the lesson cites contains the fragment it quotes;
    2. the parsers read the shipped files: the two series, the case's
       declaration, the catalogue record, the golden -- and the record, the
       golden and the files agree where they state the same fact;
    3. THE PAGE'S JOIN IS HELD TO THE ENGINE: the points the page draws are the
       engine's own tables of the case (generated by the witness setup from
       this tree's binary), joined to the measured files, and the page's
       arithmetic (a mean absolute residual, a root-mean-square) equals what
       the engine pinned in the golden (1e-4);
    4. the claims the prose and the quiz make about the example are true of
       those numbers (the held-out isobar is above the highest fitted one,
       another model is closer on the same points, the average hides a region);
    5. the page draws: every page, fit and held-out points as two roles.
\*---------------------------------------------------------------------------*/

import { readFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { MantineProvider } from "@mantine/core";
import { describe, expect, it } from "vitest";

import {
  ATM_KPA, FIT_SERIES, GOLDEN, HELD_SERIES, PROPS_DICT, RECORD, RECORD_PARSED, REQUEST_P_KPA,
  aadOf, byIsobar, fitPoints, golden, goldenAad, heldPoints, independenceOf, parseBand,
  parseEvidenceDecl, parseSeries, rmsOf,
} from "../src/ui/methods/sentenceToDecisionData.js";
import { SD_CITATIONS, SD_LIMITS, SD_QUIZ, SD_STEPS } from "../src/ui/methods/sentenceToDecisionLesson.js";
import { SentenceToDecisionTool, lineOf } from "../src/ui/methods/SentenceToDecisionTool.js";
import { METHOD_TOOLS } from "../src/ui/methods/registry.js";
import { witnessOutput } from "./witnessRead.js";

const REPO = new URL("../../", import.meta.url);
const read = (rel: string): string => readFileSync(new URL(rel, REPO), "utf-8");
const near = (a: number, b: number, rel = 1e-4, what = ""): void => {
  expect(Math.abs(a - b), `${what}: ${a} vs ${b}`).toBeLessThanOrEqual(rel * Math.max(1, Math.abs(b)));
};

const CASE = "tutorials/props/curation/curate04_nrtl_methanol_water";
const parityCsv = (): string => witnessOutput(CASE, "parity.csv");
const residualsCsv = (): string => witnessOutput(CASE, "postProcessing/fit_nrtl/residuals.csv");
const html = (page: number): string => renderToStaticMarkup(createElement(MantineProvider, null,
  createElement(SentenceToDecisionTool, {
    initialPage: page, injected: { parity: parityCsv(), residuals: residualsCsv() },
  })));

//  THE PROSE CITATIONS OF THE LESSON, each with the text the lesson says is
//  there (bin/curate/repoint_lesson_citations.py keeps these current when the
//  engine file moves; the test below reads every one back).
const CLAIMS: { [key: string]: string } = {
  "src/thermo/activityCoefficient/NRTL.cpp:114": "tau_ij = a_ij + b_ij / T",
  "src/propertyOps/EvidencePartition.cpp:386": "the ONE independence",
  "src/propertyOps/EvidencePartition.cpp:428": "Canonical, order-independent fingerprint",
  "src/propertyOps/EvidencePartition.cpp:466": "agreement with measured data",
  "src/propertyOps/EvidencePartition.cpp:590": "ANNOUNCED, never adjudicated",
  "src/propertyOps/FitParameters.cpp:1545": "std::fabs(rV[k]) / tVal[k]",
};

describe("sentence-to-decision: every claim about Choupo has a line", () => {
  it("each prose citation says what the lesson says is there", () => {
    for (const [key, text] of Object.entries(CLAIMS)) {
      const m = /^(.*):(\d+)$/.exec(key)!;
      const line = read(m[1]!).split("\n")[Number(m[2]) - 1] ?? "";
      expect(line, key).toContain(text);
    }
  });

  for (const c of SD_CITATIONS) {
    it(`${c.file}:${c.line}`, () => {
      const line = read(c.file).split("\n")[c.line - 1] ?? "";
      expect(line, `${c.file}:${c.line}`).toContain(c.contains);
    });
  }
});

describe("sentence-to-decision: the files are read, not retyped", () => {
  it("the two series are the shipped ones", () => {
    expect(FIT_SERIES.x.length).toBe(54);
    expect(HELD_SERIES.x.length).toBe(13);
    expect(FIT_SERIES.U.length).toBe(54);
    expect(HELD_SERIES.U.length).toBe(13);
    expect(HELD_SERIES.heldPressureKPa).toBeCloseTo(101.32, 6);
    expect(FIT_SERIES.doi).toBe("10.1016/j.jct.2009.11.020");
    expect(HELD_SERIES.doi).toBe("10.1021/je200341c");
    expect(FIT_SERIES.reviewStatus).toBe("transcribedNotCheckedAgainstArticle");
    expect(parseSeries(read(`${CASE}/constant/experiments/methanol-water-bubble-je200341c.dat`)).T)
      .toEqual(HELD_SERIES.T);
  });

  it("the record names the same two files by the same hashes", () => {
    const e = RECORD_PARSED.evidence;
    expect(e.map((x) => x.role)).toEqual(["fit", "validation"]);
    expect(e[0]!.sha256).toBe(FIT_SERIES.sha256);
    expect(e[1]!.sha256).toBe(HELD_SERIES.sha256);
    expect(e[0]!.doi).toBe(FIT_SERIES.doi);
    expect(e[1]!.doi).toBe(HELD_SERIES.doi);
  });

  it("the record, the golden and the declaration state the same facts", () => {
    near(RECORD_PARSED.heldOut.aad_K, golden("fit_nrtl", "aad_heldout_K"), 1e-5, "aad_K");
    near(RECORD_PARSED.heldOut.aad_pct, golden("fit_nrtl", "aad_heldout_pct"), 1e-5, "aad_pct");
    near(RECORD_PARSED.rms_K, golden("fit_nrtl", "rms"), 1e-6, "rms");
    expect(RECORD_PARSED.heldOut.points).toBe(golden("fit_nrtl", "n_heldout"));
    expect(RECORD_PARSED.nDataPoints).toBe(golden("fit_nrtl", "n_data"));
    expect(RECORD_PARSED.verdict).toBe("validated");
    expect(parseBand(PROPS_DICT)).toMatchObject({ value: 0.33, unit: "percent" });
    expect(RECORD_PARSED.maxAAD_pct).toBe(0.33);
    expect(RECORD_PARSED.validity.PmaxPa).toBe(95300);
    expect(GOLDEN).toContain("verdict fit_nrtl");
    expect(RECORD).toContain("recordType binaryInteractionParameters");
    expect(parseEvidenceDecl(PROPS_DICT)).toEqual([
      { dataset: "constant/experiments/methanol-water-bubble-j.jct.2009.11.020.dat", role: "fit" },
      { dataset: "constant/experiments/methanol-water-bubble-je200341c.dat", role: "validation" },
    ]);
  });

  it("the independence is read from the declaration: another study", () => {
    const i = independenceOf(FIT_SERIES, HELD_SERIES, parseEvidenceDecl(PROPS_DICT));
    expect(i.level).toBe("anotherStudy");
    const one = independenceOf(FIT_SERIES, HELD_SERIES, [
      { dataset: "a.dat", role: "fit" }, { dataset: "a.dat", role: "validation" }]);
    expect(one.level).toBe("splitOfOneStudy");
  });

  it("lineOf finds the line in the file it just read", () => {
    const n = lineOf(PROPS_DICT, "name        fit_nrtl;");
    expect(PROPS_DICT.split("\n")[n - 1]).toContain("name        fit_nrtl;");
  });
});

describe("sentence-to-decision: the page's join is held to the engine", () => {
  it("fitted points: the engine's parity table, row for row the measured file's", () => {
    const fit = fitPoints(parityCsv(), FIT_SERIES);
    expect(fit.length).toBe(54);
    near(rmsOf(fit), golden("fit_nrtl", "rms"), 1e-4, "in-sample rms");
    near(Math.max(...fit.map((p) => Math.abs(p.res))), golden("fit_nrtl", "max_abs_resid"), 1e-4, "max |r|");
    // the engine prints T_model to six significant figures, the residual to six decimals
    for (const p of fit) near(p.calc - p.T, p.res, 5e-3, "calc - measured");
  });

  it("held-out points: the engine's heldOutResidual series, and its AAD", () => {
    const held = heldPoints(residualsCsv(), HELD_SERIES);
    expect(held.length).toBe(13);
    near(aadOf(held).K, golden("fit_nrtl", "aad_heldout_K"), 1e-4, "held-out AAD, K");
    near(aadOf(held).pct, golden("fit_nrtl", "aad_heldout_pct"), 1e-4, "held-out AAD, %");
    expect(held.every((p) => p.role === "heldOut")).toBe(true);
  });

  it("a table that is not the file's is refused, not guessed", () => {
    const bad = parityCsv().replace(/\n0\.1,15190,/, "\n0.1,15191,");
    expect(() => fitPoints(bad, FIT_SERIES)).toThrow(/not the measured file's row/);
    const short = parityCsv().split("\n").slice(0, 10).join("\n");
    expect(() => fitPoints(short, FIT_SERIES)).toThrow(/rows/);
  });
});

describe("sentence-to-decision: what the prose and the quiz say is true of the numbers", () => {
  it("the request reaches below the fit evidence and the held-out isobar is above it", () => {
    const fit = fitPoints(parityCsv(), FIT_SERIES);
    const top = Math.max(...fit.map((p) => p.P));
    expect(top).toBeCloseTo(RECORD_PARSED.validity.PmaxPa / 1000, 6);
    expect(HELD_SERIES.heldPressureKPa!).toBeGreaterThan(top);
    expect(REQUEST_P_KPA[0]).toBeCloseTo(0.5 * ATM_KPA, 9);
    expect(REQUEST_P_KPA[1]).toBeCloseTo(ATM_KPA, 9);
    // the held-out series is one isobar; it is at the top of the request
    expect(new Set(HELD_SERIES.P).size).toBe(1);
    // fitted isobars inside the request exist (they are what covers its lower part)
    expect(byIsobar(fit).filter((g) => g.P >= REQUEST_P_KPA[0] && g.P <= REQUEST_P_KPA[1]).length).toBeGreaterThan(0);
  });

  it("UNIFAC is closer than the fitted pair on the held-out points; the y comparison has no band", () => {
    expect(goldenAad("heldout_methanol_water", "txy_unifac.T_bubble.aadAbs"))
      .toBeLessThan(goldenAad("heldout_methanol_water", "txy_nrtl.T_bubble.aadAbs"));
    expect(PROPS_DICT).not.toMatch(/y_eq_methanol[^\n]*maxAAD/);
  });

  it("the average hides a region: held-out points miss by more than 3 U where x is small", () => {
    const held = heldPoints(residualsCsv(), HELD_SERIES);
    const bad = held.filter((p) => Math.abs(p.res) / p.U > 3);
    expect(bad.length).toBeGreaterThan(0);
    expect(Math.max(...bad.map((p) => p.x))).toBeLessThan(0.2);
    expect(Math.max(...held.map((p) => Math.abs(p.res)))).toBeGreaterThan(3 * aadOf(held).K);
  });

  it("the quiz: shape, a correct index in range, steps the lesson has", () => {
    expect(SD_QUIZ.length).toBe(4);
    const have = new Set(SD_STEPS.map((s) => s.n));
    for (const q of SD_QUIZ) {
      expect(q.q.endsWith("?")).toBe(true);
      expect(q.options.length).toBeGreaterThanOrEqual(3);
      expect(q.correct).toBeLessThan(q.options.length);
      expect(q.steps.every((n) => have.has(n))).toBe(true);
    }
    expect(SD_LIMITS.length).toBeGreaterThan(0);
  });
});

