/*---------------------------------------------------------------------------*\
  phaseEnvelopeLens — the Explorer's mixture P-T envelope (2026-11-15).

  What is held: the lens is OFFERED where an envelope can exist and named on
  the strip; the case it builds is the corpus witnesses' frame and refuses an
  ideal-gas vapour with its reason; and -- the point of the lens -- a branch
  that STOPPED is reported as stopped, with the engine's own sentence and the
  pressure it stopped at, a branch that never started is not called a stop,
  a cricondentherm appears only where the engine published one, and the
  report rendered beside the figure says the nose is open.  The runs read are
  this checkout's engine on envelope03 (both branches stop) and envelope01 (a
  bubble branch that never starts, a bracketed cricondentherm on the dew
  branch), generated by tests/witnessOutputs.ts.
\*---------------------------------------------------------------------------*/

