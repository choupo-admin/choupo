/*---------------------------------------------------------------------------*\
  pxyLens — the binary boiling envelope at FIXED T (2026-11-15).

  What is held: the lens is offered beside the T-x-y and named; its spec asks
  the engine for `P_bubble` and `y_eqT_<more volatile>` along x at the held T
  (and for no two-liquid package -- the lens says one liquid is assumed); the
  CSV reader returns the engine's rows and COUNTS the compositions the engine
  could not answer.  The run read is this checkout's engine on pxy01 (ethanol
  /water at 70 C), generated by tests/witnessOutputs.ts.
\*---------------------------------------------------------------------------*/

import { describe, expect, it } from "vitest";

import { CATALOGUE } from "../src/case/catalogue.js";
import { LENS_SHORT, PLOT_TYPES } from "../src/case/exploreLenses.js";
import { synthesizeExploreCase } from "../src/case/exploreSynth.js";
import { theoryAnchor } from "../src/case/exploreTheory.js";
import { viewsFor } from "../src/case/exploreViews.js";
import { binaryPxySpec, readPxyCsv } from "../src/case/methodFeeds.js";
import { buildLocalUnifac } from "../src/case/unifacGroups.js";
import { witnessOutput } from "./witnessRead.js";

const NO_LOCAL = buildLocalUnifac({});

describe("the P-x-y lens is offered and named", () => {
  it("offered with the T-x-y for a VLE-able binary, never for one compound or three", () => {
    const has = (sel: string[]) => viewsFor(sel, CATALOGUE, NO_LOCAL).has("pxy");
    expect(has(["ethanol", "water"])).toBe(true);
    expect(has(["benzene", "toluene"])).toBe(true);
    expect(has(["benzene"])).toBe(false);
    expect(has(["benzene", "toluene", "water"])).toBe(false);
    expect(has(["water", "NaCl"])).toBe(false);
  });

  it("its word, its label and its Theory destination", () => {
    expect(LENS_SHORT.pxy).toBe("P-x-y");
    expect(PLOT_TYPES.find((p) => p.id === "pxy")!.label).toBe("Binary boiling envelope at fixed T (P-x-y)");
    expect(theoryAnchor("pxy", "Psat")).toBe("sec:bubble-pressure");
  });
});

describe("the spec: P_bubble and y_eqT along x at the held T", () => {
  const spec = binaryPxySpec({
    pair: ["water", "ethanol"], catalogue: CATALOGUE, activity: "NRTL", eos: "idealGas",
    T: 343.15, n: 21, localUnifac: NO_LOCAL,
  });

  it("the more volatile component is on the axis, whichever order the pair was picked in", () => {
    expect(spec.components).toEqual(["ethanol", "water"]);
    expect(spec.axis.variable).toBe("x[ethanol]");
    expect(spec.properties).toEqual(["P_bubble", "y_eqT_ethanol"]);
    expect(spec.state.T).toBe(343.15);
    //  one liquid: no two-liquid package is asked for
    expect(spec.vleTwoLiquid).toBeUndefined();
  });

  it("synthesises one propertyScan1D at that T on a gamma-phi package", () => {
    const f = synthesizeExploreCase(spec);
    const op = (f.propsDict!["operations"] as Record<string, unknown>[])[0]!;
    expect(op["type"]).toBe("propertyScan1D");
    expect((op["state"] as Record<string, unknown>)["T"]).toBe(343.15);
    expect(op["properties"]).toEqual(["P_bubble", "y_eqT_ethanol"]);
    expect((f.thermoPackage!["equilibrium"] as Record<string, unknown>)["formulation"]).toBe("gammaPhi");
  });
});

describe("the reading, against the witness's own run (pxy01, ethanol/water at 70 C)", () => {
  it("21 rows, none missing, the pure ends at the two vapour pressures, the peak at x = 0.9", () => {
    const r = readPxyCsv(witnessOutput("tutorials/props/scan/pxy01_ethanol_water_70C", "pxy.csv"))!;
    expect(r.comp).toBe("ethanol");
    expect(r.rows).toHaveLength(21);
    expect(r.missing).toBe(0);
    const first = r.rows[0]!, last = r.rows[r.rows.length - 1]!;
    expect(first.x).toBe(0);
    expect(first.y).toBe(0);
    expect(last.y).toBeCloseTo(1, 12);
    //  a maximum-pressure azeotrope: the curve rises above BOTH pure ends
    const peak = r.rows.reduce((a, b) => (b.P > a.P ? b : a));
    expect(peak.x).toBeCloseTo(0.9, 9);
    expect(peak.P).toBeGreaterThan(last.P);
    expect(peak.P).toBeGreaterThan(first.P);
    //  and there the vapour and the liquid nearly coincide
    expect(Math.abs(peak.y - peak.x)).toBeLessThan(0.01);
  });

  it("a composition the engine could not answer is counted and left out, never filled", () => {
    const r = readPxyCsv("x[a],P_bubble,y_eqT_a\n0,100,0\n0.5,nan,nan\n1,200,1\n")!;
    expect(r.rows.map((x) => x.x)).toEqual([0, 1]);
    expect(r.missing).toBe(1);
    expect(readPxyCsv("x[a],T_bubble,y_eq_a\n0,300,0\n")).toBeNull();
  });
});
