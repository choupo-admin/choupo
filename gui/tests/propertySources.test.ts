import { extractStructured } from "../src/adapters/WasmAdapter.js";
import {
  propertyWords, rowsByUnit, rowsOfUnit, shapePropertySources, stateText, valueText,
  type PropertySourcesReport,
} from "../src/adapters/propertySourcesPayload.js";
import { LIQUID_PROPERTY_SOURCES_DEST, liquidPropertySourcesLink } from "../src/case/modelDocs.js";
import { reportSections, type ReportFacts } from "../src/case/reportSections.js";
import type { CaseFiles } from "../src/case/types.js";
