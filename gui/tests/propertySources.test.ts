vi.mock("../src/state/store.js", () => ({
  useStore: Object.assign(
    (sel: (s: unknown) => unknown) => sel({}),
    { getState: () => ({}), setState: () => undefined, subscribe: () => () => undefined }),
}));

const emptyCase: CaseFiles = { thermoPackage: {}, controlDict: {} };
const PUMP = "tutorials/steady/rotating/pump01_water";
const PEQ = "tutorials/plant/greenAmmoniaPEQ_baseCase";

const html = (el: React.ReactElement): string =>
  renderToStaticMarkup(createElement(MantineProvider, null, el));

const blockOf = (_log: string, block: string): string =>
  `<<<Choupo:result-begin>>>\n${block}\n<<<Choupo:result-end>>>\n`;

const MINIMAL = `{ "version": 1, "converged": true, "components": [], "streams": {} }`;

/** The engine's printed table, from its own log. */
const printed = (log: string): string => {
  const at = log.indexOf("[liquid properties]");
  expect(at).toBeGreaterThan(-1);
  return log.slice(at, log.indexOf("<<<Choupo:result-begin>>>", at));
};

describe("propertySources: a real pump run (pump01_water)", () => {
  const log = witnessOutput(PUMP, "log.choupoSolve");
  const ps = extractStructured(log, emptyCase).propertySources;

  it("carries the pump's density row exactly as the engine published it", () => {
    expect(ps).toBeDefined();
    const rows = rowsOfUnit(ps, "pump01");
    expect(rows).toHaveLength(1);
    const r = rows[0]!;
    expect(r.consumerType).toBe("pump");
    expect(r.property).toBe("liquidDensity");
    expect(r.sourceId).toBe("bypass.recordVliq25C");
    expect(r.sourceClass).toBe("bypass");
    expect(r.label).toContain("computed by the unit itself, not by the property kernel");
    expect(r.valueMin).toBeCloseTo(996.956281129, 6);
    expect(r.TMin).toBeCloseTo(298.15, 6);
    expect(r.PMin).toBe(100000);
    expect(r.extra).toEqual({});     // nothing the page does not know today
  });

  it("every row's value, state and words are in the line the engine printed", () => {
    const text = printed(log);
    for (const r of ps!.used) {
      const line = `${propertyWords(r.property)}   ${valueText(r)} ${stateText(r)}   ${r.label}`;
      expect(text, line).toContain(line);
    }
  });
});

describe("propertySources: the green-ammonia plant (several units, grouped)", () => {
  const log = witnessOutput(PEQ, "log.choupoSolve");
  const ps = extractStructured(log, emptyCase).propertySources;

  it("groups the rows by the unit the engine named", () => {
    expect(ps).toBeDefined();
    const groups = rowsByUnit(ps);
    expect(groups.length).toBeGreaterThan(5);
    expect(groups.reduce((n, g) => n + g.rows.length, 0)).toBe(ps!.used.length);
    for (const g of groups) for (const r of g.rows) expect(r.unit).toBe(g.unit);
    //  a unit appears once as a group
    expect(new Set(groups.map((g) => g.unit)).size).toBe(groups.length);
  });

  it("a flowsheet unit finds the sizing rows that quote it, and only it", () => {
    const sep = rowsOfUnit(ps, "Separator");
    expect(sep).toHaveLength(1);
    expect(sep[0]!.unit).toBe("inventory 'Separator'");
    expect(sep[0]!.sourceClass).toBe("kernel");
    expect(rowsOfUnit(ps, "Aftercooler").map((r) => r.property).sort())
      .toEqual(["liquidDensity", "liquidViscosity"]);
    expect(rowsOfUnit(ps, "Sep")).toHaveLength(0);          // a prefix is not the unit
    expect(rowsOfUnit(ps, "NoSuchUnit")).toHaveLength(0);
  });

  it("every row's value, state and words are in the line the engine printed", () => {
    const text = printed(log);
    for (const r of ps!.used) {
      const line = `${propertyWords(r.property)}   ${valueText(r)} ${stateText(r)}   ${r.label}`;
      expect(text, line).toContain(line);
    }
  });

  it("the Reports table draws every unit, its words and the Theory link", () => {
    const out = html(createElement(LiquidPropertiesReport, { report: ps! }));
    for (const g of rowsByUnit(ps)) expect(out).toContain(g.unit.replace(/'/g, "&#x27;"));
    expect(out).toContain("data-liquid-report");
    expect(out).toContain('data-source-class="kernel"');
    expect(out).toContain(encodeURIComponent(LIQUID_PROPERTY_SOURCES_DEST));
  });
});

describe("propertySources: absent, partial and unknown", () => {
  it("a result without the block carries none, and the page draws nothing", () => {
    const parsed = extractStructured(blockOf("", MINIMAL), emptyCase);
    expect(parsed.propertySources).toBeUndefined();
    expect(shapePropertySources(undefined)).toBeUndefined();
    expect(shapePropertySources("text")).toBeUndefined();
    expect(html(createElement(UnitLiquidPropertiesRows, { report: undefined, unit: "pump01" }))).not.toContain("Liquid");
    const sections = reportSections({ equipment: false, sheets: false, layout: false, trains: false,
      columns: false, exchangers: false, economics: false, sensitivity: false, batchPlan: false });
    expect(sections.map((s) => s.id)).not.toContain("liquidProperties");
  });

  const block = `{ "version": 1, "converged": true, "components": [], "streams": {},
    "propertySources": { "used": [
      { "unit": "v1", "consumerType": "tank", "property": "liquidDensity", "sourceId": "k.x",
        "label": "property kernel: a method", "class": "kernel", "pressure": "applied", "calls": 2,
        "valueMin": 800, "valueMax": 800, "TMin": 300, "TMax": 300, "PMin": 101325, "PMax": 101325,
        "leftOut": [], "method": "idealMix", "domain": { "TMin": 250, "TMax": 400 }, "evidence": ["Perry 2-98"] },
      { "unit": "v2", "consumerType": "tank", "property": "liquidViscosity", "sourceId": "d.case",
        "label": "declared by the case", "class": "declared", "pressure": "n/a", "calls": 1,
        "valueMin": null, "valueMax": null, "TMin": null, "TMax": null, "PMin": null, "PMax": null,
        "leftOut": [] } ],
      "declared": [], "declaredNotUsed": [], "mismatches": [],
      "pricedTwice": ["the same liquid (300.0 K, 1.01 bar, one composition) is given two densities: v1 (tank) 800.00 kg/m3, v3 (pump) 1000.00 kg/m3"],
      "constantBesideComputed": [], "modelParameters": [], "futureBlock": 7 } }`;
  const ps = extractStructured(blockOf("", block), emptyCase).propertySources!;

  it("keeps a field it does not know, per row and per block", () => {
    const r = rowsOfUnit(ps, "v1")[0]!;
    expect(r.extra).toEqual({ method: "idealMix", domain: { TMin: 250, TMax: 400 }, evidence: ["Perry 2-98"] });
    expect(ps.extra).toEqual({ futureBlock: 7 });
  });

  it("renders the unknown fields in a generic 'more' row, never dropped", () => {
    const out = html(createElement(UnitLiquidPropertiesRows, { report: ps, unit: "v1" }));
    expect(out).toContain("data-liquid-more");
    expect(out).toContain("method: idealMix");
    expect(out).toContain("evidence: [&quot;Perry 2-98&quot;]");
    expect(out).toContain("800.00 kg/m3");
    expect(out).toContain("at 300.0 K, 1.01 bar");
    expect(out).toContain('data-source-class="kernel"');
  });

  it("says 'value not recorded' where the engine recorded none, and marks the declared class", () => {
    const out = html(createElement(UnitLiquidPropertiesRows, { report: ps, unit: "v2" }));
    expect(out).toContain("value not recorded");
    expect(out).toContain('data-source-class="declared"');
    expect(out).toContain("declared by the case");
    expect(valueText(rowsOfUnit(ps, "v2")[0]!)).toBe("");
  });

  it("a unit with no row gets no box at all", () => {
    const out = html(createElement(UnitLiquidPropertiesRows, { report: ps, unit: "v9" }));
    expect(out).not.toContain("data-liquid-properties");
    expect(out).not.toContain("Liquid properties used");
  });

  it("the Reports section leads with the engine's 'same liquid, two numbers' finding", () => {
    const out = html(createElement(LiquidPropertiesReport, { report: ps }));
    expect(out).toContain("data-liquid-findings");
    expect(out).toContain("is given two densities");
    expect(out.indexOf("data-liquid-findings")).toBeLessThan(out.indexOf("<table"));
    expect(out).toContain("more");   // the unknown fields of the block and of the row
  });

  it("the section is listed only when the run has rows", () => {
    const base: ReportFacts = { equipment: false, sheets: false, layout: false, trains: false,
      columns: false, exchangers: false, economics: false, sensitivity: false, batchPlan: false };
    expect(reportSections({ ...base, propertySources: true }).map((s) => s.id)).toContain("liquidProperties");
    expect(reportSections(base).map((s) => s.id)).not.toContain("liquidProperties");
  });
});

describe("the engine's number formatting, mirrored", () => {
  const row = (property: string, v: number): PropertySourcesReport["used"][number] => ({
    unit: "u", consumerType: "t", property, sourceId: "s", label: "l", sourceClass: "kernel",
    pressure: "", calls: 1, valueMin: v, valueMax: v, TMin: null, TMax: null, PMin: null, PMax: null,
    leftOut: [], extra: {},
  });
  it("uses the display unit and digits of PropertySourceLog.cpp", () => {
    expect(valueText(row("liquidDensity", 996.956281129))).toBe("996.96 kg/m3");
    expect(valueText(row("liquidViscosity", 7.97223665293e-4))).toBe("0.7972 mPa s");
    expect(valueText(row("surfaceTension", 0.072))).toBe("72 mN/m");
    expect(valueText(row("liquidDiffusivity", 1.6e-9))).toBe("1.6e-09 m2/s");
    expect(valueText(row("liquidVolume", 1.8069e-5))).toBe("18.07 cm3/mol");
    expect(valueText(row("somethingNew", 12.5))).toBe("12.5 (SI)");
  });
});

describe("the Theory link", () => {
  it("opens a label the Theory Guide defines", () => {
    expect(liquidPropertySourcesLink()).toContain(encodeURIComponent(LIQUID_PROPERTY_SOURCES_DEST));
    const tex = readFileSync(join(REPO, "docs", "theoryGuide.tex"), "utf-8");
    expect(tex).toContain(`\\label{${LIQUID_PROPERTY_SOURCES_DEST}}`);
  });
});
