/*---------------------------------------------------------------------------*\
  "LIQUID PROPERTIES USED" (DEV.md 4c C378, the app's half): the engine's
  `propertySources` block, read from REAL runs -- the pump tutorial and the
  green-ammonia plant, as THIS tree's engine wrote them (run logs generated by
  the witness setup, never committed) -- and held to the engine's own PRINTED
  `[liquid properties]` table: every row's value, state and source words are
  found, character for character, in the line the engine printed, so the page
  can never show a number or a sentence the log does not.

  Also pinned: a result with no block draws nothing; a field the page does
  not know is carried and rendered in a generic "more" row; a value the
  engine did not record reads "value not recorded"; a unit with no row gets
  no box; the Theory link opens a label that exists.
\*---------------------------------------------------------------------------*/

