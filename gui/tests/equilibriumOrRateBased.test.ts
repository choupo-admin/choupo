/*---------------------------------------------------------------------------*\
  equilibriumOrRateBased.test -- the EduTool `equilibrium-or-rate-based`.

  WHAT IT HOLDS:
    * the registry entry and its place in the distillation sequence;
    * the knobs land on declared numbers, and the bulk column at the shipped
      efficiency writes back exactly what the case declares;
    * the efficiency sweeps are read by column NAME from the engine's own
      CSVs (generated by witnessSetup from this tree's binary), and the
      numbers the lesson's prose states about them hold;
    * every `file:line` the lesson cites, held to the text it claims;
    * every decision row names an origin that is a demonstration of the page
      or a reference the page lists;
    * the page opens without starting a run.

  WHAT IT DOES NOT HOLD: demonstration 1's numbers, which need the engine in
  the loop with the page's overrides; they were run natively when the page
  was built and docs/design/equilibrium-or-rate-based.md holds the table.
\*---------------------------------------------------------------------------*/

