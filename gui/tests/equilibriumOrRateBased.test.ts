describe("equilibrium-or-rate-based: the knobs land on declared numbers", () => {
  const FD = "system/flowsheetDict";
  const num = (text: string, key: string): number =>
    Number(new RegExp(`^[ \\t]*${key}[ \\t]+([-+0-9.eE]+)`, "m").exec(text)![1]);
  it("the bulk column at the shipped efficiency is the shipped case", () => {
    const base = methodCase(MURPHREE_WITNESS, []).rawFiles![FD]!;
    const same = methodCase(MURPHREE_WITNESS, murphreeOverrides("bulk", ASSUMED_EFFICIENCY)).rawFiles![FD]!;
    for (const k of ["nStages", "feedStage", "refluxRatio", "distillateRate", "murphreeEfficiency"])
      expect(num(same, k), k).toBe(num(base, k));
  });
  it("the trace column rewrites four numbers and the efficiency; the tray sweep moves the feed with the height", () => {
    const t = methodCase(MURPHREE_WITNESS, murphreeOverrides("trace", 0.4)).rawFiles![FD]!;
    expect(num(t, "nStages")).toBe(SPECS.trace.nStages);
    expect(num(t, "feedStage")).toBe(SPECS.trace.feedStage);
    expect(num(t, "refluxRatio")).toBe(3);
    expect(num(t, "distillateRate")).toBe(45);
    expect(t).toMatch(/distillateRate 45 kmol\/h;/);
    expect(num(t, "murphreeEfficiency")).toBe(0.4);
    expect(SPECS.trace.nStages - SPECS.trace.feedStage).toBe(TRACE_STRIPPING_STAGES);
    for (const n of [TRAY_STOPS[0]!, TRAY_STOPS[TRAY_STOPS.length - 1]!]) {
      const s = methodCase(MURPHREE_WITNESS, murphreeOverrides("trace", 1.0, n)).rawFiles![FD]!;
      expect(num(s, "nStages")).toBe(n);
      expect(num(s, "feedStage")).toBe(n - TRACE_STRIPPING_STAGES);
    }
    expect(TRAY_STOPS[0]).toBe(16);
    expect(TRAY_STOPS[TRAY_STOPS.length - 1]).toBe(80);
    expect(EFFICIENCY_STOPS).toContain(ASSUMED_EFFICIENCY);
  });
});

describe("equilibrium-or-rate-based: the readers", () => {
  const run = (comp: Record<string, number> | null): RunResult => ({
    status: "done", log: "", convergence: [],
    streams: comp ? [{ name: "distillate", role: "product", F: 1, T: 350, P: 1e5, vf: 0, composition: comp } as never] : [],
  } as unknown as RunResult);
  it("reads the toluene the engine publishes on the distillate, or nothing", () => {
    expect(distillateToluene(run({ benzene: 0.999998, toluene: 1.35e-6 }))).toBe(1.35e-6);
    expect(distillateToluene(run(null))).toBeNull();
    expect(distillateToluene(null)).toBeNull();
  });
  it("picks the smallest height on the grid that meets the target", () => {
    expect(smallestMeeting([16, 18, 20], [1e-3, 5e-6, 1e-7], 1e-5)).toBe(18);
    expect(smallestMeeting([16, 18], [1e-3, null], 1e-5)).toBeNull();
  });
  it("quotes an impurity in per cent or in ppm", () => {
    expect(asImpurity(0.0821)).toBe("8.21 %");
    expect(asImpurity(1.39e-6)).toBe("1.39 ppm");
  });
});

describe("equilibrium-or-rate-based: the three engine sweeps", () => {
  const sweeps = EFFICIENCY_WITNESSES.map((w) =>
    parseEfficiencySweep(witnessOutput(`tutorials/${w.witness}`, SWEEP_CSV)));
  it("reads every sweep by column name, 21 loads from 0.3 to 2.3", () => {
    for (const s of sweeps) {
      expect(s).not.toBeNull();
      expect(s!.fs.length).toBe(21);
      expect(s!.fs[0]).toBeCloseTo(0.3, 9);
      expect(s!.fs[20]).toBeCloseTo(2.3, 9);
    }
    expect(parseEfficiencySweep("point,a\n0,1\n")).toBeNull();
  });
  it("the three correlations span more than twenty points at the comparison load", () => {
    const at = sweeps.map((s) => atFs(s!, COMPARE_FS)!.overall);
    expect(at[0]).toBeCloseTo(0.7349, 3);   // AIChE
    expect(at[1]).toBeCloseTo(0.9012, 3);   // Chan & Fair
    expect(at[2]).toBeCloseTo(0.6225, 3);   // Syeda & Chuang
    const spread = Math.max(...at) - Math.min(...at);
    expect(spread).toBeGreaterThan(0.2);
    //  "disagree with each other by more than the measurement varies"
    const inRange = YANAGI_14_34KPA.filter((p) => p.fs >= 1 && p.fs <= 2.05).map((p) => p.overall);
    expect(spread).toBeGreaterThan(Math.max(...inRange) - Math.min(...inRange));
  });
  it("the measured efficiency stays between 63 and 74 % from F_s = 1 to 2, and falls near flood", () => {
    const inRange = YANAGI_14_34KPA.filter((p) => p.fs >= 1 && p.fs <= 2.05).map((p) => p.overall);
    expect(Math.min(...inRange)).toBeGreaterThanOrEqual(0.63);
    expect(Math.max(...inRange)).toBeLessThanOrEqual(0.745);
    expect(Math.max(...YANAGI_14_34KPA.filter((p) => p.fs > 2.2).map((p) => p.overall))).toBeLessThan(0.45);
  });
  it("transcribes the measured points from the record that read the paper", () => {
    const rec = tree("docs/design/c329-ratebased-first-delivery.md");
    for (const p of YANAGI_14_34KPA)
      expect(rec, String(p.fs)).toContain(`| ${p.fs.toFixed(3)} | ${(100 * p.overall).toFixed(1)} |`);
  });
  it("only AIChE is out of sample on this tray, as the record says", () => {
    expect(EFFICIENCY_WITNESSES.map((w) => w.inSample)).toEqual([false, true, true]);
  });
});

describe("equilibrium-or-rate-based: the lesson", () => {
  it("every equation parses", () => {
    for (const s of EQ_RB_STEPS) {
      if (s.formula) expect(texParses(s.formula), s.title).toBe(true);
      for (const w of s.where ?? []) expect(texParses(w.sym), w.sym).toBe(true);
    }
  });
  it("cites the engine at lines that say what the lesson claims", () => {
    const all = [EQ_RB_ENGINE_SCOPE, ...EQ_RB_STEPS.flatMap((s) => [s.body, s.note ?? ""])].join("\n");
    const cited = new Set([...all.matchAll(/([A-Za-z]+\.(?:cpp|H)):(\d+)/g)].map((m) => m[0]));
    const CLAIMS: Record<string, string> = {
      "DistillationColumn.cpp:1599": "lookupScalarOrDefault(\"murphreeEfficiency\", 1.0);",
      "DistillationColumn.cpp:1731": "Keff[j][i] = std::max(0.0, Emv * K[j][i] + (1.0 - Emv) * yDown / xj);",
      "DistillationColumn.cpp:2399": "`murphreeEfficiency` is not ",
      "DistillationColumn.cpp:5061": "tray efficiency is implemented for a BINARY",
    };
    for (const c of cited) expect(CLAIMS[c], `uncovered citation ${c}`).toBeDefined();
    const src = tree("src/unitOperations/distillation/DistillationColumn.cpp").split("\n");
    for (const [c, want] of Object.entries(CLAIMS)) {
      expect(cited.has(c), `claim ${c} is no longer cited`).toBe(true);
      const line = Number(c.split(":")[1]);
      expect(src[line - 1], c).toContain(want);
    }
    //  The refusal at 2398 is the MESH one, two lines on.
    expect(src.slice(2397, 2400).join("\n")).toContain("implemented for `method simultaneous`");
  });
  it("names the four witnesses it runs, and each exists in the tree", () => {
    for (const w of [MURPHREE_WITNESS, ...EFFICIENCY_WITNESSES.map((x) => x.witness)])
      expect(tree(`tutorials/${w}/system/controlDict`)).toContain("application");
  });
  it("every decision row and cost names a demonstration of this page or a reference it lists", () => {
    const list = refs.lessons["equilibrium-or-rate-based"]!.references.map((r) => r.text);
    const surnames = list.map((t) => t.split(",")[0]!);
    for (const r of [...DECISION_ROWS, ...EQ_RB_COSTS]) {
      const parts = r.origin.split(";").map((p) => p.trim());
      for (const p of parts) {
        const ok = /^Demonstrations? [12]/.test(p) || surnames.some((s) => p.startsWith(s));
        expect(ok, `origin '${p}'`).toBe(true);
      }
    }
    for (const f of REFERENCE_FINDINGS)
      expect(surnames.some((s) => f.source.startsWith(s)), f.source).toBe(true);
    //  Five cards, six rows, seven references; the card whose paper this page
    //  did not open carries no quotation and says who read it.
    expect(REFERENCE_FINDINGS.length).toBe(5);
    expect(DECISION_ROWS.length).toBe(7);
    expect(list.length).toBe(10);
    //  The four papers this page did not open: each reference entry says so,
    //  and every place the page uses one of them marks who read it.
    const entries = refs.lessons["equilibrium-or-rate-based"]!.references as
      { text: string; verified: { evidence: string } }[];
    const unopened = ["Pelkonen", "Krishnamurthy", "Taylor, R.; Krishna", "Taylor, R.; Kooijman"];
    for (const u of unopened) {
      const e = entries.find((x) => x.text.startsWith(u))!;
      expect(e, u).toBeDefined();
      expect(e.verified.evidence.toLowerCase(), u).toMatch(/not opened for this page|this page's author did not open it/);
    }
    for (const r of [...DECISION_ROWS, ...EQ_RB_COSTS])
      for (const part of r.origin.split(";").map((x) => x.trim()))
        if (/^(Krishnamurthy and Taylor|Taylor and Krishna|Taylor and Kooijman)/.test(part))
          expect(part, part).toContain("read by the project's coordinating session");
    expect(EQ_RB_STEPS.find((x) => x.n === 4)!.body)
      .toContain("four papers read for this page, and four read by the project's coordinating session");
    const reactive = DECISION_ROWS.find((r) => r.situation.startsWith("A reactive column"))!;
    expect(reactive.origin).toContain("Taylor and Krishna (2000)");
    expect(DECISION_ROWS.find((r) => r.situation.startsWith("A multicomponent"))!.origin)
      .toContain("Krishnamurthy and Taylor (1985)");
    const sizes = EQ_RB_COSTS.find((c) => c.text.startsWith("The size of the problem"))!.text;
    for (const n of ["70", "160", "550", "1 300", "2c + 1", "5c + 1"]) expect(sizes).toContain(n);
    const p = REFERENCE_FINDINGS.find((f) => f.source.startsWith("Pelkonen"))!;
    expect(p.quote).toBeNull();
    expect(p.setting).toContain("not opened for this page");
    expect(DECISION_ROWS.find((r) => r.situation.startsWith("Azeotropic"))!.origin).toContain("Pelkonen");
  });
  it("names no simulator or company the papers name", () => {
    const prose = [EQ_RB_OPENING, EQ_RB_TASK, EQ_RB_ENGINE_SCOPE,
      ...EQ_RB_STEPS.flatMap((s) => [s.body, s.note ?? ""]),
      ...REFERENCE_FINDINGS.flatMap((f) => [f.setting, f.found, f.quote ?? ""]),
      ...DECISION_ROWS.flatMap((r) => [r.situation, r.use, r.why]),
      ...EQ_RB_COSTS.map((c) => c.text), ...EQ_RB_LIMITS.map((l) => l.body)].join("\n");
    for (const w of ["ChemSep", "Shell", "Uhde", "BASF", "Neste", "Koch"]) expect(prose).not.toContain(w);
    expect(prose).not.toMatch(/ -- | - /);
  });
});

