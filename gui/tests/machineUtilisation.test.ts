/*---------------------------------------------------------------------------*\
  The per-machine utilisation table (DEV.md 4c C195 item 1, C210) is READ
  from the `ratedMachine` sheets and the sizing advisories the engine
  published: synthetic sheets pin the reading (sort, kinds, the announcement
  by locus, a pump sheet and a result with no plan drawing nothing), and the
  two tablet plants as THIS tree's engine wrote them (their run logs,
  generated by the witness setup, never committed) are held to the engine's
  own numbers -- every utilisation the table shows is the sheet's
  `utilisation`, never a division made here, and the announced set is the
  advisories' set.
\*---------------------------------------------------------------------------*/

import { describe, expect, it } from "vitest";

import type { EquipmentItem } from "../src/adapters/SolverAdapter.js";
import { extractStructured } from "../src/adapters/WasmAdapter.js";
import { isPlanMachine, machineKind, machineUtilisation } from "../src/case/machineUtilisation.js";
import type { CaseFiles } from "../src/case/types.js";
import { witnessOutput } from "./witnessRead.js";

const item = (unit: string, values: Record<string, number>, type = "ratedMachine"): EquipmentItem =>
  ({ unit, item: unit, type, material: "SS316", values }) as EquipmentItem;

const MIXER = item("blender", { V_nominal: 1.2, maxFill: 0.7, V_working_capacity: 0.84,
  V_working_required: 0.711, machinesInstalled: 1, utilisation: 0.8466, utilisation_plan: 0.3,
  lotTime_forShift: 3, shiftLength: 8 });
const MILL = item("mill", { capacity_machine: 500, load: 125.49, machinesInstalled: 1,
  utilisation: 0.251, utilisation_plan: 0.45 });
const PRESS = item("press", { capacity_machine: 162000, load: 142857, stations: 45, turretSpeed: 60,
  machinesInstalled: 1, utilisation: 0.9, utilisation_plan: 0.65 });
const PACK = item("pack", { capacity_machine: 720, load: 631, packsPerMinute: 12,
  machinesInstalled: 2, utilisation: 0.44, utilisation_plan: 1 });
const PUMP = item("pump", { utilisation: 0.7, maxFlowPerUnit: 100 });   // volumeRate: no plan

describe("machineUtilisation: the engine's sheets, least capacity margin first", () => {
  it("sorts by the published utilisation, descending, and reads the kind from the keys", () => {
    const rows = machineUtilisation([MILL, MIXER, PRESS, PACK, PUMP], []);
    expect(rows.map((r) => r.unit)).toEqual(["press", "blender", "pack", "mill"]);
    expect(rows.map((r) => r.kind)).toEqual(["tabletPress", "batchVolume", "packagingLine", "massRate"]);
    expect(rows.map((r) => r.utilisation)).toEqual([0.9, 0.8466, 0.44, 0.251]);
    expect(rows[0]!.rating).toContain("45 stations");
    expect(rows[1]!.load).toEqual({ value: 0.711, unit: "m³" });
    expect(rows[1]!.capacity).toEqual({ value: 0.84, unit: "m³" });
    expect(rows[2]!.installed).toBe(2);
  });
  it("a pump sheet (no plan) is not a row, and a result with no machine draws nothing", () => {
    expect(isPlanMachine(PUMP)).toBe(false);
    expect(machineUtilisation([PUMP, item("hx", { utilisation: 0.5 }, "shellTubeHX")], [])).toEqual([]);
    expect(machineUtilisation(undefined, undefined)).toEqual([]);
  });
  it("the announcement is the engine's advisory for that unit, by locus", () => {
    const msg = "utilisation 0.9 is above 0.85 (the engine's stated announcement threshold)";
    const rows = machineUtilisation([MILL, PRESS], [
      { category: "sizing", severity: "warning", locus: "ratedMachine 'press'", message: msg },
      { category: "sizing", severity: "warning", locus: "ratedMachine 'mill'",
        message: "the case installs 2 machine(s) but the batch plan's stage assumes 1" },
    ]);
    expect(rows.find((r) => r.unit === "press")!.announced).toBe(msg);
    expect(rows.find((r) => r.unit === "mill")!.announced).toBeNull();   // another advisory, not an announcement
  });
  it("machineKind prefers the most specific key", () => {
    expect(machineKind({ capacity_machine: 1 })).toBe("massRate");
  });
});

const emptyCase: CaseFiles = { thermoPackage: {}, controlDict: {} };
const TABLETS = ["apalutamide01_tablets", "donepezil01_tablets"];

describe.each(TABLETS)("%s, as this tree's engine wrote it", (name) => {
  const dir = `tutorials/batch/plant/${name}`;
  const parsed = () => extractStructured(witnessOutput(dir, "log.choupoSolve"), emptyCase);

  it("every plan machine is a row, each utilisation is the sheet's own, least capacity margin first", () => {
    const r = parsed();
    const rows = machineUtilisation(r.equipment, r.advisories);
    const sheets = (r.equipment ?? []).filter(isPlanMachine);
    expect(rows.length).toBe(sheets.length);
    expect(rows.length).toBeGreaterThan(4);
    for (const row of rows)
      expect(row.utilisation).toBe(sheets.find((s) => s.unit === row.unit)!.values["utilisation"]);
    const u = rows.map((x) => x.utilisation);
    expect(u).toEqual([...u].sort((a, b) => b - a));
    // the data-sheet limit holds: the engine refuses a run above 1
    expect(Math.max(...u)).toBeLessThanOrEqual(1 + 1e-12);
  });
  it("the machines marked announced are exactly the engine's utilisation advisories", () => {
    const r = parsed();
    const rows = machineUtilisation(r.equipment, r.advisories);
    const fromEngine = (r.advisories ?? [])
      .filter((a) => /^ratedMachine '/.test(a.locus) && a.message.startsWith("utilisation"))
      .map((a) => a.locus.replace(/^ratedMachine '(.*)'$/, "$1")).sort();
    expect(rows.filter((x) => x.announced !== null).map((x) => x.unit).sort()).toEqual(fromEngine);
  });
});
