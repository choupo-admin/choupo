/*---------------------------------------------------------------------------*\
  The "Compressing a gas" EduTool (DEV.md 4c C442) held to the engine.

  THE ANCHOR: the lesson's own arithmetic (compression.ts), fed with the
  engine's printed inlet state of section 1 of compressor03_staged_design,
  reproduces the engine's printed section 1 (temperature, head, power) to the
  digits the sheet prints, and, at the engine's own choice, its total.  Every
  number the prose states is then recomputed here from the sheet, so a prose
  number that stops being the engine's fails by name.  The sheets are RUN
  OUTPUTS generated by the witness setup from this tree's engine
  (witnessOutputs.ts), never transcribed.
\*---------------------------------------------------------------------------*/

