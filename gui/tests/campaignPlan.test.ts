// ---- the declarations, read from the case's own postDict ------------------

type J = { [k: string]: unknown };
const hours = (v: unknown): number => {
  if (typeof v === "number") return v;
  const p = typeof v === "string" ? parseScalarString(v) : null;
  if (!p) throw new Error(`not a number: ${String(v)}`);
  return p.value;
};
const dictOf = (caseDir: string): J =>
  (toJson(parse(read(`tutorials/batch/plant/${caseDir}/system/postDict`))) as J).batchPlan as J;

/** One declared stage, as the case writes it; `fromFlowsheet` and the
 *  masses are what the ENGINE published (they are read from the flowsheet,
 *  never typed in the dict). */
function stageFromDecl(d: J, next: string | null, pub: Row | undefined, holdsFactor: number): StageSpec {
  const type = String(d.type) as StageSpec["type"];
  const op = d.operatingTime;
  const fromFlow = op === "fromFlowsheet";
  const fed = d.dischargeTime === "throughFedStage";
  const feeds = d.feeds !== undefined ? (d.feeds === "none" ? null : String(d.feeds)) : next;
  return {
    name: String(d.stage), type,
    charge: hours(d.chargeTime),
    process: type === "batch" ? hours(d.processTime)
      : fromFlow ? Number(pub!.processTime_h) : hours(op),
    discharge: fed ? "fedStage" : hours(d.dischargeTime),
    clean: hours(d.cleanTime),
    outOfPhase: d.outOfPhase !== undefined ? Number(d.outOfPhase) : 1,
    inPhase: d.inPhase !== undefined ? Number(d.inPhase) : 1,
    feeds,
    holdsFactor,
    ...(type === "batch" ? { bulkDensity: hours(d.bulkDensity), fillFraction: Number(d.fillFraction) } : {}),
    operating: "declared",
  };
}

const arr = (v: unknown): J[] => (Array.isArray(v) ? (v as J[]) : []);

