type Row = { [k: string]: string };
function csv(text: string): Row[] {
  const [head, ...lines] = text.trim().split("\n");
  const cols = head!.split(",");
  return lines.map((l) => {
    const c = l.split(",");
    return Object.fromEntries(cols.map((k, i) => [k, c[i] ?? ""]));
  });
}
const num = (r: Row, k: string): number => Number(r[k]);
