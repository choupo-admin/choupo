describe("the toy's arithmetic, worked by hand on the page's plant", () => {
  // solutionTank 1+1+4(fed)+1 = 7; dryer 4; blender 1+.5+.5+1 = 3; press .5+2.5+0+.5 = 3.5;
  // coater .5+2+.5+.5 = 3.5.  T_L = 7 (the tank).  Offsets: 0, 2, 6, 7.5 + 3 = 10.5? see below.
  const p1 = singlePlan(toyASpec(TOY_A_DEFAULT));
  const by = (n: string) => p1.stages.find((s) => s.name === n)!;
  it("cycles, the limiting stage and T_L", () => {
    expect(by("solutionTank").cycleTime).toBe(7);
    expect(by("sprayDryer").cycleTime).toBe(4);
    expect(by("blender").cycleTime).toBe(3);
    expect(by("press").cycleTime).toBe(3.5);
    expect(by("coater").cycleTime).toBe(3.5);
    expect(p1.trains[0]!.cycleTime).toBe(7);
    expect(p1.trains[0]!.limitingStage).toBe("solutionTank");
    expect(by("solutionTank").limiting).toBe(true);
    expect(by("sprayDryer").limiting).toBe(false);
  });
  it("offsets: each stage starts when the one before begins to discharge", () => {
    // tank 0; dryer 0+1+1 = 2; blender 2+0+4 = 6; press 6+1+.5 = 7.5;
    // coater 7.5+.5+2.5 = 10.5
    expect([0, 2, 6, 7.5, 10.5]).toEqual(p1.stages.map((s) => s.offset));
  });
  it("the year: 40 lots, 5 campaigns, span(8) = 14 + 7 x 7 = 63, 5 x (63 + 24) = 435 h", () => {
    const t = p1.trains[0]!;
    expect(p1.summary.lotsPerYear).toBe(40);
    expect(t.campaigns).toBe(5);
    expect(t.campaignSpan).toBe(63);
    expect(t.requiredTime).toBe(435);
    near(t.occupancy, 435 / 3840, 1e-12);
    //  the tank: 40 lots x 7 h + 5 x 24 h = 400 h
    expect(by("solutionTank").busyHours).toBe(400);
  });
  it("sizes: tank V = 4 x 100 / (800 x 0.8) = 0.625 m3; dryer asks for 100 / 4 = 25 kg/h", () => {
    near(by("solutionTank").volume!, 0.625, 1e-12);
    near(by("sprayDryer").rate!, 25, 1e-12);
    near(by("blender").volume!, 100 / (450 * 0.6), 1e-12);
  });
  it("a second tank out of phase hands the limit to the dryer: 7 / 2 = 3.5 < 4", () => {
    const p2 = singlePlan(toyASpec({ ...TOY_A_DEFAULT, tanks: 2 }));
    expect(p2.trains[0]!.limitingStage).toBe("sprayDryer");
    expect(p2.trains[0]!.cycleTime).toBe(4);
    expect(p2.stages[0]!.effectiveCycle).toBe(3.5);
    //  the lots alternate on the two tank lanes
    const lanes = p2.gantt.filter((g) => g.stage === "solutionTank").map((g) => g.unit);
    expect(lanes.slice(0, 4)).toEqual([1, 2, 1, 2]);
  });
  it("a longer dryer run lengthens the tank's cycle too (throughFedStage)", () => {
    const p = singlePlan(toyASpec({ ...TOY_A_DEFAULT, dryerHours: 8 }));
    expect(p.stages[0]!.cycleTime).toBe(11);
    expect(p.trains[0]!.cycleTime).toBe(11);
    // two tanks: 5.5 against the dryer's 8 -> the dryer limits
    const q = singlePlan(toyASpec({ ...TOY_A_DEFAULT, dryerHours: 8, tanks: 2 }));
    expect(q.trains[0]!.limitingStage).toBe("sprayDryer");
  });
  it("the limiting stage is recoloured as it moves (one outlined row at a time)", () => {
    for (const dryerHours of [1, 4, 6, 12])
      for (const tanks of [1, 2] as const) {
        const p = singlePlan(toyASpec({ ...TOY_A_DEFAULT, dryerHours, tanks }));
        expect(p.stages.filter((s) => s.limiting)).toHaveLength(1);
      }
  });
  it("a lot of 400 kg is 10 lots and one campaign; the year needs fewer hours", () => {
    const p = singlePlan(toyASpec({ ...TOY_A_DEFAULT, lot: 400 }));
    expect(p.summary.lotsPerYear).toBe(10);
    expect(p.trains[0]!.campaigns).toBe(2);
  });
  it("N = ceil(Q/B) with the engine's guard: 20000 / 400 is 50, not 51", () => {
    expect(lotsPerYear(20000, 400)).toBe(50);
    expect(lotsPerYear(10156, 410.4008762)).toBe(25);
  });
  it("an over-booked plant is flagged as one the engine would refuse", () => {
    const p = singlePlan(toyASpec({ ...TOY_A_DEFAULT, perYear: 20000, lot: 20, available: 800 }));
    expect(p.findings.some((f) => f.kind === "overYear")).toBe(true);
  });
});

describe("the schedule: a side feed is scheduled backwards (BatchPlanPass.cpp:160-225)", () => {
  it("a stage fed by none, feeding a later one, ends its discharge when that one starts processing", () => {
    // a (first, feeds c): 0; b (fed by none earlier, feeds c) is a side feed.
    const v = [
      { name: "a", feeds: "c", charge: 1, proc: 2, cycle: 4, offset: 0 },
      { name: "b", feeds: "c", charge: 1, proc: 1, cycle: 3, offset: 0 },
      { name: "c", feeds: null, charge: 1, proc: 2, cycle: 4, offset: 0 },
    ];
    const last = scheduleCampaign(v);
    // c starts when the later of a and b discharge: a at 3, b (scheduled forward: first stage k=0 only
    // is a; b has nobody before it feeding it, so it is scheduled backwards from c): c = 3, b = 3 + 1 - 1 - 1 = 2
    expect(v[2]!.offset).toBe(3);
    expect(v[1]!.offset).toBe(2);
    expect(last).toBe(7);
  });
});

