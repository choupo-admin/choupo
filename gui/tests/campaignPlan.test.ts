        near(x.start, num(r, "start_h"), 1e-6, `${x.product} start`);
        near(x.productChangeover, num(r, "productChangeover_h"), 1e-6, `${x.product} clean`);
        near(x.requiredTime, num(r, "requiredTime_h"), 1e-6, `${x.product} required`);
