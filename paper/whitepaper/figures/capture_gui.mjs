/*---------------------------------------------------------------------------*\
  capture_gui.mjs -- the white paper's two front-end figures, regenerated by
  driving the BUILT app in a real browser (DEV.md 4c C126).

  WHAT IT DOES, and nothing else:
    1. serves the production bundle gui/dist on a local port, reached by
       Chromium under a NON-localhost name (choupo.test), because on
       localhost the app shows development-only chrome (the agent console,
       the clipboard bridge -- TopBar.tsx) that a student on the site never
       sees;
    2. opens the case at ?case=<id>, checks a POSITIVE SENTINEL (the app's
       own chrome: #root mounted and the CHOUPO wordmark) before judging
       anything, presses Run, and waits on the RUN LEDGER the app writes on
       <html> (gui/src/adapters/runLedger.ts) -- the engine is the WASM
       build of the same C++ in gui/dist/wasm, run in the page's worker;
    3. Figure A: switches the stream colouring to Temperature (the Colours
       menu, gui/src/ui/ColoursMenu.tsx), waits for the canvas to settle and
       saves the window at deviceScaleFactor --dpr;
    4. Figure B: opens the Reports view's plant layout in its own tab (the
       "Open in new tab" pop-out, the ?layout=<key> route), waits for the
       three.js canvas, verifies it is NOT BLANK by sampling its pixels, and
       only then saves it.  A 3D view it cannot see is a REFUSAL (exit 2),
       never a blank figure.

  Prerequisites (the script refuses, naming them, when absent):
      make wasm-gui                      # the five engines -> gui/public/wasm
      npm --prefix gui ci && npm --prefix gui run build     # -> gui/dist
  Chromium: the Playwright tree under PLAYWRIGHT_BROWSERS_PATH (default
  /opt/pw-browsers) or CHOUPO_CHROMIUM, found by gui/tools/checkGui/cdp.mjs
  -- the repository's own CDP client, so no new dependency.

  Usage (from the repository root):
      node paper/whitepaper/figures/capture_gui.mjs
      node paper/whitepaper/figures/capture_gui.mjs --case plant/greenAmmoniaPEQ_baseCase \
           --dpr 2 --out paper/whitepaper/figures
      node paper/whitepaper/figures/capture_gui.mjs --debug <dir>   # a PNG per step

  Exit codes: 0 both figures saved · 2 refused (could not honestly capture).
\*---------------------------------------------------------------------------*/
import { createReadStream, existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import http from "node:http";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { findChromium, launch } from "../../../gui/tools/checkGui/cdp.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../../..");
const DIST = join(ROOT, "gui/dist");
const HOST = "choupo.test";

// ---- CLI -------------------------------------------------------------------
const opt = {
  case: "plant/greenAmmoniaPEQ_baseCase",
  out: HERE, dpr: 2, debug: null,
  flowW: 1600, flowH: 1000,            // CSS pixels of Figure A's window
  layoutW: 1500, layoutH: 950,          // CSS pixels of Figure B's tab
  runTimeout: 900,                      // s, the engine run in the browser
};
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === "--case") opt.case = argv[++i];
  else if (a === "--out") opt.out = resolve(argv[++i]);
  else if (a === "--dpr") opt.dpr = Number(argv[++i]);
  else if (a === "--debug") opt.debug = resolve(argv[++i]);
  else if (a === "--run-timeout") opt.runTimeout = Number(argv[++i]);
  else { console.error(`unknown argument '${a}' (see the header of this file)`); process.exit(2); }
}

class Refusal extends Error {}
const log = (s) => console.log(s);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ---- preconditions ---------------------------------------------------------
function requireBuilt() {
  const engine = join(DIST, "wasm/choupoSolve.wasm");
  if (!existsSync(join(DIST, "index.html")))
    throw new Refusal(`no production bundle at ${DIST} -- run: npm --prefix gui ci && npm --prefix gui run build`);
  if (!existsSync(engine))
    throw new Refusal(`the bundle carries no engine (${engine}) -- run make wasm-gui, THEN npm --prefix gui run build`);
  const src = join(ROOT, "gui/public/wasm/choupoSolve.wasm");
  if (existsSync(src) && statSync(src).mtimeMs > statSync(engine).mtimeMs + 1000)
    throw new Refusal(`gui/public/wasm is newer than gui/dist/wasm -- rebuild the bundle (npm --prefix gui run build)`);
}

// ---- a static server for gui/dist (the shape the site serves: no COOP/COEP,
//      which GitHub Pages does not send either) --------------------------------
const MIME = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css",
  ".json": "application/json", ".wasm": "application/wasm", ".png": "image/png", ".svg": "image/svg+xml",
  ".pdf": "application/pdf", ".woff2": "font/woff2", ".txt": "text/plain", ".csv": "text/csv",
  ".webmanifest": "application/manifest+json", ".data": "application/octet-stream" };
function serve(dir) {
  const root = resolve(dir);
  const srv = http.createServer((req, res) => {
    let p = decodeURI(req.url.split("?")[0]);
    if (p.endsWith("/")) p += "index.html";
    let f = join(root, p);
    if (!f.startsWith(root) || !existsSync(f) || statSync(f).isDirectory()) f = join(root, "index.html");
    res.writeHead(200, { "Content-Type": MIME[extname(f)] || "application/octet-stream" });
    createReadStream(f).pipe(res);
  });
  return new Promise((ok) => srv.listen(0, "127.0.0.1", () => ok({ srv, port: srv.address().port })));
}

// ---- page helpers ------------------------------------------------------------
const APP_CHROME = `(() => {
  const root = document.querySelector('#root');
  const text = (document.body && document.body.innerText) || '';
  return { mounted: !!root && root.childElementCount > 0, wordmark: /CHOUPO/.test(text),
           title: document.title || '', head: text.replace(/\\s+/g, ' ').slice(0, 160) };
})()`;

async function requireSentinel(page, what, test, timeoutMs = 60000) {
  let seen = null;
  for (let t = 0; t <= timeoutMs; t += 500) {
    seen = await page.evaluate(APP_CHROME).catch((e) => ({ failed: String(e.message || e) }));
    if (test(seen)) return seen;
    await sleep(500);
  }
  throw new Refusal(`${what}: the app's own chrome never appeared (${JSON.stringify(seen)}`
    + `${page.lastNavigationError ? `; navigation: ${page.lastNavigationError}` : ""}).  Nothing was captured.`);
}

/** Click the first element matching a selector whose trimmed text (or
 *  aria-label) matches a regex.  Returns 'clicked' | 'absent' | 'disabled'. */
const clickJs = (selector, re) => `(() => {
  const re = ${re};
  const el = [...document.querySelectorAll(${JSON.stringify(selector)})].find((x) =>
    re.test((x.textContent || '').trim()) || re.test(x.getAttribute('aria-label') || ''));
  if (!el) return 'absent';
  if (el.disabled || el.getAttribute('aria-disabled') === 'true') return 'disabled';
  el.scrollIntoView({ block: 'center' }); el.click(); return 'clicked';
})()`;
async function click(page, selector, re, what) {
  const r = await page.evaluate(clickJs(selector, re));
  if (r !== "clicked") throw new Refusal(`${what}: ${r} (selector ${selector}, ${re})`);
  await sleep(600);
}

const LEDGER = `(() => { const h = document.documentElement; const g = (k) => h.getAttribute(k);
  return { state: g('data-run-state'), started: +(g('data-engine-started')||0), done: +(g('data-engine-done')||0),
           failed: +(g('data-engine-failed')||0), failure: g('data-engine-failure'), last: g('data-engine-last-done'),
           unavailable: g('data-engine-unavailable') }; })()`;

async function shot(page, file, clip) {
  const params = { format: "png", captureBeyondViewport: false };
  if (clip) params.clip = { ...clip, scale: 1 };
  const { data } = await page.send("Page.captureScreenshot", params, 120000);
  const buf = Buffer.from(data, "base64");
  if (file) { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, buf); }
  return buf;
}
async function debugShot(page, name) {
  if (!opt.debug) return;
  await shot(page, join(opt.debug, `${name}.png`));
  log(`    [debug] ${name}.png`);
}

/** Pixel statistics of a PNG, computed BY THE PAGE (a 2D canvas decodes
 *  it), so this script needs no PNG decoder.  Returns the number of
 *  distinct quantised colours, the luminance standard deviation and the
 *  fraction of pixels that differ from the most common colour. */
async function pixelStats(page, png) {
  const b64 = png.toString("base64");
  return page.evaluate(`(async () => {
    const img = new Image(); img.src = 'data:image/png;base64,${b64}';
    await img.decode();
    const c = document.createElement('canvas'); c.width = img.width; c.height = img.height;
    const g = c.getContext('2d'); g.drawImage(img, 0, 0);
    const d = g.getImageData(0, 0, c.width, c.height).data;
    const hist = new Map(); let n = 0, s = 0, s2 = 0;
    for (let i = 0; i < d.length; i += 4 * 7) {           // every 7th pixel
      const k = ((d[i] >> 4) << 8) | ((d[i+1] >> 4) << 4) | (d[i+2] >> 4);
      hist.set(k, (hist.get(k) || 0) + 1);
      const y = 0.2126*d[i] + 0.7152*d[i+1] + 0.0722*d[i+2]; s += y; s2 += y*y; n++;
    }
    const top = Math.max(...hist.values());
    const mean = s / n;
    return { w: c.width, h: c.height, colours: hist.size, lumStd: Math.sqrt(Math.max(0, s2/n - mean*mean)),
             nonBackground: 1 - top / n };
  })()`, { awaitPromise: true, timeoutMs: 120000 });
}

// ---- the drive ---------------------------------------------------------------
async function main() {
  requireBuilt();
  const { srv, port } = await serve(DIST);
  const base = `http://${HOST}:${port}/`;
  log(`[serve] ${DIST} at ${base} (127.0.0.1:${port})`);
  const bin = findChromium();
  if (!bin) throw new Refusal("no Chromium found (PLAYWRIGHT_BROWSERS_PATH or CHOUPO_CHROMIUM)");
  const browser = await launch(bin, [
    `--host-resolver-rules=MAP ${HOST} 127.0.0.1`,
    "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist",
  ]);
  try {
    // ---- the case, run in the browser ----------------------------------------
    const page = await browser.newPage(opt.flowW, opt.flowH);
    await page.setViewport(opt.flowW, opt.flowH, { dpr: opt.dpr });
    const url = `${base}?case=${encodeURIComponent(opt.case)}`;
    log(`[open] ${url}`);
    await page.goto(url, 90000);
    const chrome = await requireSentinel(page, `opening ${opt.case}`, (c) => c && c.mounted && c.wordmark);
    log(`    sentinel: #root mounted, CHOUPO wordmark present; title "${chrome.title}"`);
    await sleep(3000);
    await debugShot(page, "01-opened");

    const before = await page.evaluate(LEDGER);
    await click(page, "button", "/^Run\\b/i", "the run control");
    log("[run] pressed Run; waiting on the run ledger (data-engine-* on <html>)");
    const t0 = Date.now();
    let led = before;
    for (;;) {
      await sleep(2000);
      led = await page.evaluate(LEDGER, { timeoutMs: 60000 }).catch(() => led);
      if (led.unavailable) throw new Refusal(`engine unavailable: ${led.unavailable}`);
      if (led.failed > before.failed) throw new Refusal(`the run failed: ${led.failure}`);
      if (led.done > before.done && led.state === "idle") break;
      if ((Date.now() - t0) / 1000 > opt.runTimeout) throw new Refusal(`the run did not finish in ${opt.runTimeout} s`);
    }
    log(`    run finished in ${((Date.now() - t0) / 1000).toFixed(0)} s: ${led.last}`);
    await sleep(3000);
    await debugShot(page, "02-ran");

    // ---- Figure A: the flowsheet coloured by temperature -----------------------
    await click(page, "button", "/^Flowsheet$/", "the Flowsheet view");
    await click(page, "button", "/^Stream colours/", "the Colours menu");
    await click(page, "[role=menuitem]", "/^Temperature/", "Colour by > Temperature");
    await page.evaluate("document.activeElement && document.activeElement.blur()");
    await page.send("Input.dispatchKeyEvent", { type: "keyDown", key: "Escape", code: "Escape", windowsVirtualKeyCode: 27 });
    await page.send("Input.dispatchKeyEvent", { type: "keyUp", key: "Escape", code: "Escape", windowsVirtualKeyCode: 27 });
    await sleep(2500);
    const legend = await page.evaluate("/temperature/i.test(document.body.innerText)");
    if (!legend) throw new Refusal("Figure A: no temperature legend on the canvas after Colour by > Temperature");
    const figA = join(opt.out, "gui_flowsheet.png");
    await shot(page, figA);
    log(`[figure A] ${figA}`);

    // ---- Figure B: the plant layout, popped out into its own tab ---------------
    await click(page, "button", "/^Reports$/", "the Reports view");
    await sleep(2000);
    await debugShot(page, "03-reports");
    //  The pop-out calls window.open; capture the address it asks for and
    //  open it as a page of our own in the SAME browser context, so it reads
    //  the same localStorage stash the parent just wrote.
    await page.evaluate("window.__opened = []; window.open = (u) => { window.__opened.push(String(u)); return null; }");
    await click(page, "button", "/^Open in new tab$/", "the layout's 'Open in new tab'");
    const opened = await page.evaluate("window.__opened");
    if (!opened || !opened.length) throw new Refusal("the layout pop-out asked for no address");
    const popUrl = new URL(opened[0], base).toString();
    log(`[pop-out] ${popUrl}`);
    const tab = await browser.newPage(opt.layoutW, opt.layoutH);
    await tab.setViewport(opt.layoutW, opt.layoutH, { dpr: opt.dpr });
    await tab.goto(popUrl, 90000);
    await requireSentinel(tab, "the layout tab", (c) => c && c.mounted && /layout|plot plan/i.test(c.title + c.head));
    //  The canvas: present, sized, and then NOT BLANK.
    let rect = null;
    for (let t = 0; t < 120 && !rect; t++) {
      await sleep(1000);
      rect = await tab.evaluate(`(() => { const c = [...document.querySelectorAll('canvas')]
        .map((x) => x.getBoundingClientRect()).filter((r) => r.width > 200 && r.height > 200)
        .sort((a, b) => b.width * b.height - a.width * a.height)[0];
        return c ? { x: c.x, y: c.y, width: c.width, height: c.height } : null; })()`);
    }
    if (!rect) throw new Refusal("the layout tab drew no WebGL canvas within 120 s");
    await click(tab, "label, button, [role=radio]", "/^High$/", "Quality > High").catch(() => {});
    await sleep(8000);                         // let the scene settle (flow animation keeps rendering)
    await debugShot(tab, "04-layout-tab");
    const canvasPng = await shot(tab, null, rect);
    const st = await pixelStats(tab, canvasPng);
    log(`    canvas ${st.w}x${st.h} px: ${st.colours} colours, luminance sd ${st.lumStd.toFixed(1)}, `
      + `${(100 * st.nonBackground).toFixed(1)} % off the dominant colour`);
    if (st.colours < 40 || st.lumStd < 8 || st.nonBackground < 0.10)
      throw new Refusal("Figure B: the 3D canvas is BLANK or near-blank by its own pixels -- nothing saved");
    const figB = join(opt.out, "gui_layout3d.png");
    await shot(tab, figB);
    log(`[figure B] ${figB}`);
  } finally {
    await browser.close();
    srv.close();
  }
}

main().then(() => process.exit(0), (e) => {
  if (e instanceof Refusal) { console.error(`capture_gui REFUSED: ${e.message}`); process.exit(2); }
  console.error(e && e.stack || e); process.exit(2);
});
